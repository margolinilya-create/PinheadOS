/*
  Снятие блокировки со шрифтовой таблицы.

  Приём тот же, что был инлайном в `index.html`: ссылка приезжает
  с `media="print"`, поэтому браузер не ждёт её перед первым кадром,
  а после загрузки мы переводим её в `all`. Итоговая картинка не меняется —
  меняется момент первой отрисовки.

  Файл ОТДЕЛЬНЫЙ, а не атрибут `onload`, из-за CSP (L-06 отчёта QA
  13.08.2026): политика `script-src 'self'` блокирует инлайновые обработчики
  событий. Оставить обработчик и включить enforcing-CSP значило бы навсегда
  оставить таблицу в `media="print"` — то есть выкатить прод вообще без
  фирменных шрифтов, молча. Альтернатива («unsafe-hashes» с хешем строки)
  ломалась бы от любой правки этой строки, тоже молча.
*/
(function swapFontMedia() {
  var link = document.querySelector('link[data-font-swap]');
  if (!link) return;
  var apply = function () { link.media = 'all'; };
  // Таблица могла успеть загрузиться до выполнения скрипта
  if (link.sheet) apply();
  else link.addEventListener('load', apply, { once: true });
})();
