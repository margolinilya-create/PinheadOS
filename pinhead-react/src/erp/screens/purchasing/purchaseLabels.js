/**
 * ПОДПИСЬ ЦЕНЫ — ПО ЕДИНИЦЕ МАТЕРИАЛА (правка заказчика 21.09, п. 1).
 *
 * Документ: «для закупки с типом „Ткань" переименовать поле „Цена за единицу"
 * в „Цена за кг, ₽"». Буквальный «кг» здесь соврал бы: у ткани на бою 21.09
 * встречаются и «кг», и «Килограммы», и «шт» — «Дой-пакет» заведён тканью
 * в штуках. Поэтому единица берётся у материала (`unitShortLabel` приводит
 * имя справочника к коду), а «кг» появляется там, где он и есть.
 *
 * Функция одна на четыре места — модалку, инлайн-правку, карточку планшета
 * и заголовок таблицы: четыре литерала разошлись бы на первой же правке.
 */
export function pricePerUnitLabel(unit, units) {
  const short = unitShortLabel(unit, units);
  return short ? `Цена за ${short}, ₽` : 'Цена за единицу, ₽';
}

/**
 * У ТКАНИ ЦЕНА ОБЯЗАТЕЛЬНА (правка 21.09, п. 1): «сделать обязательным для
 * сохранения закупки ткани». По ней считается себестоимость полотна
 * и стоимость возвратного остатка — без неё обе выходят прочерком.
 *
 * Обязательность стоит только НА ЗАВЕДЕНИИ строки: на бою десять тканей
 * из семнадцати заведены без цены, и требование при каждой правке заперло бы
 * их целиком — нельзя было бы даже поменять поставщика. То же правило
 * и в триггере `erp_material_price_required` на INSERT.
 */
export function priceRequiredFor(kind) {
  return kind === 'fabric';
}

/**
 * ОБЯЗАТЕЛЬНЫЕ ПОЛЯ «НОВОЙ ЗАКУПКИ» — ОДНОЙ ЧИСТОЙ ФУНКЦИЕЙ (правка 27.09, п. 1).
 *
 * Документ: «при нажатии „Добавить" подсвечивать красной обводкой все
 * незаполненные обязательные поля. Пользователь должен сразу видеть, что
 * нужно дозаполнить». До правки `submit` останавливался на ПЕРВОЙ ошибке
 * тостом: человек чинил одно поле, нажимал снова, получал следующий тост.
 *
 * Возвращает ошибки ПО ВСЕМ полям сразу, ключ — поле формы: по нему модалка
 * ставит рамку, `aria-invalid` и текст под полем. Тост для этого не годится
 * (правило волны UX-4) — он не показывает, ГДЕ.
 *
 * Правила те же, что были в `submit`:
 *   · заказ и материал — всегда;
 *   · «Нужно по заказу» — у закупки (`source = purchase`): без него
 *     строка не закроется автоматически никогда (`supply.missingPlan`);
 *   · цена — у ткани (правка 21.09, п. 1; тот же гейт в триггере на INSERT).
 */
export function validatePurchaseForm(form, { priceRequired, priceLabel }) {
  const errors = {};
  if (!form.order_id) errors.order_id = 'Выберите заказ';
  if (!String(form.name ?? '').trim()) errors.name = 'Укажите материал';
  if (form.source === 'purchase' && !(Number(form.qty_expected) > 0)) {
    errors.qty_expected = `Укажите «${PURCHASE_FIELD_LABELS.qtyExpected}»`;
  }
  if (priceRequired && !(Number(form.price_per_unit) > 0)) {
    errors.price_per_unit = `Укажите «${priceLabel}»`;
  }
  return errors;
}

/**
 * СВОДКА ЗАКУПКИ ОДНОЙ СТРОКОЙ (правка 05.10, п. 6): «вместо больших
 * счётчиков — короткая строка». Шесть плиток занимали полэкрана широкой
 * панели и отодвигали таблицу материалов, ради которой карточку открывают.
 *
 * Нули не называются, кроме «всего»: «в пути 0 · пришло 0 · проблем 0»
 * заставляет читать три слова, чтобы узнать, что ничего не случилось.
 */
export function purchaseSummaryLine(summary) {
  const parts = [`материалов ${summary.total}`];
  const add = (n, label) => { if (n > 0) parts.push(`${label} ${n}`); };
  add(summary.notOrdered, 'не заказано');
  add(summary.ordered, 'заказано');
  add(summary.inTransit, 'в пути');
  add(summary.arrived, 'пришло');
  const problems = Array.isArray(summary.problems) ? summary.problems.length : summary.problems;
  add(problems, 'проблемы');
  const line = parts.join(' · ');
  return line.charAt(0).toUpperCase() + line.slice(1);
}
