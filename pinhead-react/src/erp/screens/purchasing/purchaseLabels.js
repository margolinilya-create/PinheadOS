/**
 * ПОДПИСИ ЗАКУПОЧНЫХ ПОЛЕЙ — ПО ОДНОЙ НА ВЕЛИЧИНУ (правки 24.08 п. 1, 14.09 п. 2).
 *
 * Документ 14.09: «количество из листа закупки отображается так, что плановую
 * потребность и фактически заказанное количество легко перепутать. Поле „Нужно
 * количество" переименовать в „Количество к заказу"… добавить отдельное поле
 * „Фактическое количество"… Итог: „Количество к заказу" = потребность
 * производства; „Фактическое количество" = сколько реально заказали
 * у поставщика».
 *
 * ПЕРЕИМЕНОВАНЫ ОБЕ, И ЭТО НЕ ОПЕЧАТКА. Имя «Количество к заказу» до 14.09
 * носила ДРУГАЯ величина (`qty_ordered` — факт закупщика), поэтому просьба
 * «переименовать первое» автоматически требует переименовать и второе: иначе
 * на экране оказались бы два поля с одним именем и разным смыслом — ровно то,
 * на что документ и жалуется.
 *
 * Величины остались прежними, переименование чисто словесное:
 *   `qty_expected` — ПОТРЕБНОСТЬ производства (знаменатель приёмки на складе
 *                    и условие автозакрытия закупки, `supply.missingPlan`);
 *   `qty_ordered`  — ФАКТ: сколько заказали у поставщика по счёту.
 *
 * История прежней правки (24.08) — почему слово «Заказано» ушло от намерения:
 * оно читалось как свершившийся факт рядом со статусом «Заказано». Тогда же
 * снят разнобой у плановой величины: одно и то же `qty_expected` подписывалось
 * «План, кол-во», «Нужно», «Плановое количество», «Нужно количество *»
 * и «План» — пять слов на одно число.
 *
 * Плитка сводки остаётся «Заказано» осознанно: она считает не поле, а ФАКТ
 * оформления (`supplyMaterialSummary.ordered`).
 */
export const PURCHASE_FIELD_LABELS = {
  /** Потребность производства — сколько надо заказать */
  qtyExpected: 'Количество к заказу',
  /** Факт закупщика — сколько заказано у поставщика по счёту */
  qtyOrdered: 'Фактическое количество',
};

