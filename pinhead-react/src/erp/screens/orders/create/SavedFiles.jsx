import { AttachmentList } from '../../../components/AttachmentList';
import styles from '../../../styles';

/**
 * ФАЙЛЫ, УЖЕ ПРИЛОЖЕННЫЕ К ЗАКАЗУ — в режиме правки (правка 12.09, баг 03).
 *
 * ЧТО БЫЛО. Секции «ТЗ в PDF» и «Лист закупки» рисовались в правке теми же
 * компонентами, что при создании, а их состояние принадлежит ФОРМЕ и стартует
 * пустым. Человек открывал заказ, у которого ТЗ и лист есть, и видел пустые
 * секции с требованием приложить файлы заново — «редактирование работает как
 * повторное создание».
 *
 * ПОЧЕМУ ЗДЕСЬ ТОЛЬКО ПОКАЗ. Загрузка, замена и версии ТЗ уже живут в карточке
 * заказа (`orderCard/TzDocsSection` с `uploadTzDocument`/`replaceTzDocument`,
 * по позициям и по заказу целиком). Второй способ менять те же файлы означал
 * бы две поверхности для одного решения — ровно то, от чего проект уходил
 * в подряде и закупке. Форма говорит это вслух, а не молчит: иначе отсутствие
 * кнопки читается как поломка.
 */
export function SavedFiles({ files, emptyText }) {
  return (
    <>
      {files.length === 0 ? (
        <p className={styles.subText}>{emptyText}</p>
      ) : (
        <AttachmentList files={files} label="Приложено к заказу" />
      )}
      <p className={styles.subText}>
        Файлы заказа ведутся в его карточке — там их можно открыть, заменить
        и посмотреть версии. Эта форма их не меняет.
      </p>
    </>
  );
}
