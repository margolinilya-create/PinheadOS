/**
 * Что показать, когда в списке заказов не осталось ни одной строки.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. В `OrdersScreen` на этом месте стояла вложенная
 * тернарная лесенка из шести исходов внутри серого `<div>`: вкладка × фильтр ×
 * поиск. Проверить её можно было только глазами, а «пусто» выглядело одинаково
 * и когда работы действительно нет, и когда подбор отсёк всё до последней
 * строки, — то самое различие, которого требует правило UX-2.
 *
 * Функция ЧИСТАЯ: ни стора, ни React, ни перевода в разметку. Она отвечает
 * на вопрос «что это за пустота», а рисуют её примитивы `EmptyState`
 * (работы нет по существу) и `EmptyResult` (подбор ничего не нашёл).
 *
 * ТЕКСТЫ СОХРАНЕНЫ ПО СМЫСЛУ: прежняя строка стала заголовком, пояснение
 * говорит, что делать дальше. Единственный исход, который лесенка выражала
 * одной фразой «Ничего не найдено по запросу», разбирается самим `EmptyResult`:
 * с набранным запросом он называет его в кавычках, без запроса (отсеяли даты) —
 * говорит про фильтры.
 */

/**
 * @typedef {Object} EmptyOrdersInput
 * @property {'active'|'archive'} tab      текущая вкладка списка
 * @property {string|null} filter          чип подбора: `ready` | `urgent` | `overdue` | null
 * @property {number} inTabCount           сколько заказов во вкладке ДО поиска и дат
 * @property {string} [query]              строка поиска
 * @property {string} [dateFrom]           граница «создан с»
 * @property {string} [dateTo]             граница «создан по»
 */

/**
 * @param {EmptyOrdersInput} input
 * @returns {{ kind: 'result', query: string, byDate: boolean }
 *          | { kind: 'empty', icon: string, title: string, text: string }}
 *
 * `kind: 'result'` — данные во вкладке ЕСТЬ, их отсёк поиск или даты создания.
 * `kind: 'empty'` — во вкладке нет ничего по существу.
 *
 * `byDate` читается ровно там, где запроса нет: сказать «ничего не найдено
 * по запросу», когда искали не текстом, а границами дат создания, — значит
 * назвать человеку не ту причину.
 */
export function emptyOrders({
  tab,
  filter,
  inTabCount,
  query = '',
  dateFrom = '',
  dateTo = '',
}) {
  const q = (query || '').trim();
  /**
   * Строки во вкладке есть — значит пусто из-за подбора, и человеку надо
   * предложить его снять, а не сообщать, что заказов нет.
   */
  if (inTabCount > 0) {
    return { kind: 'result', query: q, byDate: Boolean(dateFrom || dateTo) };
  }

  if (tab === 'archive') {
    return {
      kind: 'empty',
      icon: 'box',
      title: 'Архив пуст',
      text: 'Сюда попадают сданные и отменённые заказы.',
    };
  }

  /**
   * Чипы сроков и готовности. Пустой результат под таким чипом — это всё-таки
   * ответ по существу («просроченных нет»), поэтому исход `empty`, а не
   * `result`: так было и в прежней лесенке, и подпись чипа отвечает на вопрос
   * прямо. Пояснение при этом называет фильтр — снять его можно одним нажатием.
   *
   * Чипа «Стоит» здесь нет НАМЕРЕННО: `OrdersScreen` пропускает в `filter`
   * только `ready` | `urgent` | `overdue` (белый список рядом с чтением
   * параметра), и ветка по `stopped` была бы кодом, до которого не доходит
   * ни один путь. Расширят белый список — придёт и ветка, вместе с решением,
   * что там написать.
   */
  switch (filter) {
    case 'ready':
      return {
        kind: 'empty',
        icon: 'checkCircle',
        title: 'Готовых к отгрузке заказов пока нет',
        text: 'Снимите фильтр «Готовы к отгрузке», чтобы увидеть остальные активные заказы.',
      };
    case 'urgent':
      return {
        kind: 'empty',
        icon: 'clock',
        title: 'Заказов со сроком ≤ 3 дней нет',
        text: 'Снимите фильтр «Срок ≤ 3 дней», чтобы увидеть остальные активные заказы.',
      };
    case 'overdue':
      return {
        kind: 'empty',
        icon: 'clock',
        title: 'Просроченных заказов нет',
        text: 'Снимите фильтр «Просрочено», чтобы увидеть остальные активные заказы.',
      };
    default:
      return {
        kind: 'empty',
        icon: 'orders',
        title: 'Активных заказов нет',
        text: 'Создайте первый — кнопка «+ Новый заказ» в панели над списком.',
      };
  }
}
