import { formatDateHuman } from '../utils/time';
import { DATE_MIN, DATE_MAX, isDateOutOfRange } from '../utils/dateRange';
import styles from '../erp.module.css';

/**
 * Поле даты: нативный `<input type="date">` плюс эхо под ним.
 *
 * Поле остаётся нативным намеренно — на планшетах цехов это системный календарь,
 * лучший тач-ввод, какой вообще есть, и свой компонент был бы хуже. Но формат
 * отображения задаёт локаль браузера: при en-US поле показывает `mm/dd/yyyy`,
 * и «08/14» читается двояко. Поэтому у заполненного поля всегда есть
 * однозначное эхо — «14 авг. 2026».
 *
 * ПРЕСЕТЫ «Сегодня / +3 дня / +7 дней» УБРАНЫ (правки заказчика 10.08, P3):
 * блок дат просили упростить, а три кнопки под каждым полем занимали больше
 * места, чем само поле.
 *
 * ЭХО ЗАПОЛНЕННОГО ПОЛЯ ОСТАВЛЕНО СОЗНАТЕЛЬНО, хотя документ 10.08 называл его
 * дублирующим: без него «08/14» в браузере с en-US читается двояко, а на сроках
 * заказа это дороже одной строки под полем.
 *
 * ПОДСКАЗКА ПУСТОГО ПОЛЯ «дд.мм.гггг» УБРАНА (M-23 отчёта QA 13.08.2026).
 * Она была одновременно лишней и неверной: в браузере с русской локалью ровно
 * этот текст печатает сам `input type="date"` (получался дубль подписи), а
 * в браузере с en-US порядок ввода — mm/dd/yyyy, и подсказка называла НЕ ТОТ
 * порядок, ради разъяснения которого её и добавили.
 *
 * ДИАПАЗОН ДАТ (H-13). Нативное поле принимает любой год, включая `0002` и
 * `20026` — обычная опечатка при вводе с клавиатуры. Такая дата уходила
 * в базу молча и ломала все расчёты сроков. `min`/`max` дают границу и самому
 * календарю, и проверке; выход за границу подписывается прямо под полем,
 * а не тостом где-то ещё.
 */

export function DateField({
  value, onChange, className, min, max, ...rest
}) {
  const echo = formatDateHuman(value);
  /**
   * Сообщение говорит только про АБСУРДНЫЙ год, а не про любое нарушение
   * `min`/`max`. Границы сюда приходят и от соседнего поля интервала
   * («Создан с» ограничивает «по»), и тогда честный текст — «начало позже
   * конца», а его пишет сам фильтр: он один знает, что это за пара полей.
   */
  const outOfRange = isDateOutOfRange(value);

  return (
    <>
      <input
        type="date"
        className={outOfRange
          ? `${className ?? styles.input} ${styles.inputError}`
          : (className ?? styles.input)}
        value={value ?? ''}
        min={min ?? DATE_MIN}
        max={max ?? DATE_MAX}
        onChange={(e) => onChange(e.target.value)}
        aria-invalid={outOfRange || undefined}
        {...rest}
      />
      {(echo || outOfRange) && (
        <span className={styles.dateHint}>
          {outOfRange
            ? (
              <span className={styles.fieldError}>
                Год вне диапазона {DATE_MIN.slice(0, 4)}–{DATE_MAX.slice(0, 4)} — проверьте дату
              </span>
            )
            : <span className={styles.dateEcho}>{echo}</span>}
        </span>
      )}
    </>
  );
}
