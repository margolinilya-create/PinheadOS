import { useCatalogRefs } from '../hooks/useCatalogRefs';
import { useDictionary } from '../store/useDictionary';

/**
 * Подсказки КАТАЛОГА для обычного текстового поля — брат `DictionaryDatalist`.
 *
 * Разница в источнике: справочник (`erp_dictionaries`) заводят руками под то,
 * чего в каталоге нет — поставщики, единицы, причины блокировок, операции
 * маршрута. Изделия, крой, ткани и отделка живут в каталоге, и он же источник
 * правды по ассортименту (решение заказчика).
 *
 * `dictionaryKind` ДОПОЛНЯЕТ каталог, а не заменяет его. Нужен он потому, что
 * сверка с боевой базой показала расхождение: в справочнике типов изделий
 * заведены «Рубашка», «Фартук» и «Кепка», которых в каталоге SKU нет ни одной.
 * Снять справочник целиком — значит молча отобрать у менеджера три изделия,
 * которые он заводит; поэтому каталог идёт ПЕРВЫМ и остаётся источником,
 * а справочник добавляет то, чего в нём ещё нет. Дубли схлопываются: одно
 * и то же название в обоих списках дало бы две одинаковые строки подсказки.
 *
 * Именно `datalist`, а не `select`, по той же причине, что у справочника:
 * подсказка, а не ограничение. Срочная позиция, которой ещё нет ни там, ни там,
 * не должна упираться в форму — иначе менеджер выберет ближайшее из списка,
 * и цех получит не то изделие.
 */
export function CatalogDatalist({ field, id, dictionaryKind = null }) {
  const refs = useCatalogRefs();
  // Хук вызывается всегда (правило React), пустой вид отдаёт пустой список
  const extra = useDictionary(dictionaryKind);

  const fromCatalog = refs[field] ?? [];
  const seen = new Set(fromCatalog);
  const items = [
    ...fromCatalog,
    ...extra.map((d) => d.name).filter((name) => name && !seen.has(name)),
  ];

  if (items.length === 0) return null;
  return (
    <datalist id={id}>
      {items.map((name) => <option key={name} value={name} />)}
    </datalist>
  );
}
