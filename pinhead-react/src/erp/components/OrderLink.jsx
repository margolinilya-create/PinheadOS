import { Link, useLocation } from 'react-router-dom';
import { orderLinkTarget } from '../utils/orderLink';

/**
 * Ссылка на карточку заказа — единственный способ её открыть.
 *
 * ЗАЧЕМ ЭТОТ КОМПОНЕНТ. До правки заказчика 16.08 карточка открывалась боковой
 * панелью: десять экранов рендерили `<Link to="/orders/:id">` и тут же гасили
 * переход обработчиком `orderLinkClick`, который вместо навигации писал `?order=`
 * и поднимал Drawer. Заказчик от панели отказался — в узком окне не помещается
 * маршрут, материалы, ТЗ, файлы и комментарии сразу.
 *
 * Переход стал обычным, и вместе с ним появилась цена, которой у панели не было:
 * список ЗАКРЫВАЕТСЯ. Пока он оставался смонтированным, фильтры, страница и
 * позиция прокрутки жили сами собой; теперь контекст обязан уехать в переход
 * явно — иначе «Назад» из заказа приводит на «Активные» без фильтров и в начало
 * списка. Отсюда `state.from`: его читает `OrderCard` (`backTo`), а
 * `useScrollRestore` ключуется по `pathname+search` и находит свою позицию.
 *
 * Один компонент, а не `state` в каждой из десяти ссылок: правило сборки адреса
 * возврата должно жить в одном месте — забытый в одном экране `state` даёт
 * дефект, который видно только по возврату именно оттуда.
 */
export function OrderLink({ orderId, children, ...rest }) {
  const location = useLocation();
  const [to, options] = orderLinkTarget(orderId, location);
  return (
    <Link
      {...rest}
      to={to}
      state={options.state}
      /**
       * Клик не всплывает: заголовок заказа лежит внутри разворачиваемой строки
       * и внутри карточки канбана, и без этого переход заодно тоглил бы строку
       * или дёргал состояние перетаскивания.
       */
      onClick={(e) => e.stopPropagation()}
    >
      {children}
    </Link>
  );
}
