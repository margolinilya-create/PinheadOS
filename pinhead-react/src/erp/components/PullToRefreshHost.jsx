import { usePullToRefresh } from '../hooks/usePullToRefresh';
import styles from './PullToRefresh.module.css';

/**
 * Жест «потянуть — обновить» целиком: и слушатели, и видимая полоса.
 *
 * ─── ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ЛЕНИВЫЙ ЧАНК, А НЕ ЧАСТЬ ОБОЛОЧКИ ───────────────
 * Жест работает ТОЛЬКО под пальцем (`pointer: coarse`), а оболочку ERP
 * открывают в основном с мыши — менеджер, директор, закупщик. Статическим
 * импортом хук, полоса и её CSS ехали бы каждому: замерено — 690 Б gzip
 * в критическом пути, при том что бюджет оболочки на момент правки стоял
 * в 539 Б от потолка (189 461 из 190 000). То есть своей ценой эта правка
 * ломала сборку.
 *
 * Приём не новый: так же устроен `kanban/useTouchDndPolyfill` — он тянет
 * `mobile-drag-drop` динамическим импортом и только при `(pointer: coarse)`.
 * И так же устроен `DevAnnotations`: `lazy()` плюс гейт по тому, кому виджет
 * вообще показан.
 *
 * Хук живёт ВНУТРИ этого компонента, а не в `ErpLayout`, именно поэтому:
 * хук нельзя импортировать лениво — он вызывается в теле компонента, —
 * а компонент можно.
 *
 * ─── ПОЛОСА — НАКЛАДКОЙ, ВНЕ ПОТОКА ───────────────────────────────────────
 * `position: fixed` и никакого сдвига содержимого: сдвиг меряет сторож
 * раскладки `e2e/erp-cls.spec.ts`, а на планшете содержимое — это кнопки
 * этапа, и уезжающая из-под пальца цель в этом проекте уже была жалобой.
 *
 * ─── ДЛЯ СКРИНРИДЕРА ЕЁ НЕТ ───────────────────────────────────────────────
 * `aria-hidden`: это обратная связь на жест, которого у скринридера нет,
 * а об исходе (данные перечитываются) сообщает `StaleDataBar` — он и несёт
 * `role="status"`. Второй live-регион об одном и том же читался бы дважды.
 */
export default function PullToRefreshHost({ scrollRef, onRefresh, busy = false }) {
  const { pull, armed } = usePullToRefresh(scrollRef, onRefresh);

  if (!busy && pull <= 0) return null;

  const label = busy
    ? 'Обновляем…'
    : armed ? 'Отпустите, чтобы обновить' : 'Потяните, чтобы обновить';

  return (
    <div
      className={styles.wrap}
      /* Высота ползёт за пальцем; коробка зафиксирована, ниже ничего
         не двигается. При чтении высоту задаёт сама пилюля. */
      style={{ height: busy ? undefined : `${Math.min(pull, 96)}px` }}
      aria-hidden="true"
    >
      <span className={`${styles.pill} ${armed || busy ? styles.pillArmed : ''}`}>
        {label}
      </span>
    </div>
  );
}
