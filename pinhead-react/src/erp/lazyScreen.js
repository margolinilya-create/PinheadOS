import { lazy } from 'react';

/**
 * Ленивый экран ERP, которому гарантированно достался полный стор.
 *
 * Доменные действия стора (этапы, склад, подряд, план, справочники…) приезжают
 * отдельным чанком — оболочку грузят все и всегда, и платить за них рабочему,
 * который открывает только очередь своего цеха, незачем. Но экран, отрисованный
 * раньше подключения, получил бы `s.loadWarehouse` со значением `undefined`:
 * ошибка не при сборке и не при переходе, а при нажатии на кнопку.
 *
 * Поэтому подключение и есть часть загрузки экрана. `Promise.all` — оба чанка
 * едут ПАРАЛЛЕЛЬНО, лишнего круга ожидания не появляется; промис общий на все
 * экраны, поэтому со второго перехода он уже разрешён.
 *
 * Так гарантия держится на устройстве загрузки, а не на памяти разработчика:
 * забыть «прицепить слайс к экрану» здесь физически негде. Сторожит
 * `lazyScreen.test.js` — он проверяет, что ни один экран ERP не заведён
 * голым `lazy()`.
 */
let domainReady = null;

function ensureDomainSlices() {
  domainReady ??= import('./store/domainSlices').then((m) => {
    m.attachDomainSlices();
  });
  return domainReady;
}

/**
 * @param {() => Promise<{ default: unknown }>} load — импорт модуля экрана
 */
export function lazyScreen(load) {
  return lazy(() => Promise.all([load(), ensureDomainSlices()]).then(([mod]) => mod));
}

/** Тот же чанк в простое — вместе с предзагрузкой соседних экранов */
export { ensureDomainSlices };
