import type { ErpNotification } from '../types';

/**
 * ВСПЛЫВАЮЩИЕ УВЕДОМЛЕНИЯ (правка заказчика 20.09, п. 4).
 *
 * «Обязательный минимум — уведомления внутри ERP в реальном времени:
 * глобальная кнопка с бейджем, центр уведомлений и всплывающие уведомления».
 *
 * Здесь — ЧИСТОЕ РЕШЕНИЕ «что показать всплывающим», отдельно от разметки
 * и от запроса: правило «первая загрузка ничего не показывает» иначе живёт
 * внутри эффекта компонента, где его не проверить и где его легко потерять
 * при следующей правке оболочки.
 *
 * ПОЧЕМУ ПЕРВАЯ ЗАГРУЗКА МОЛЧИТ. Список приезжает вместе с оболочкой раздела,
 * то есть при каждом входе и каждом F5. Без этого правила человек, у которого
 * накопилось семь непрочитанных за ночь, получал бы семь всплывающих карточек
 * поверх экрана, на который только что пришёл работать, — причём ежедневно
 * и по поводам недельной давности. Всплывающее уведомление отвечает на вопрос
 * «пришло ПРЯМО СЕЙЧАС»; на вопрос «что я пропустил» отвечает колокол
 * и центр уведомлений.
 */

/** Сколько карточек висит одновременно: полоса поверх работы, а не лента */
export const POPUP_LIMIT = 3;

/**
 * Что показать всплывающим при очередной загрузке списка.
 *
 * @param rows   свежий список (сервер отдаёт от новых к старым)
 * @param seen   идентификаторы, которые эта вкладка уже видела
 * @param first  это первая загрузка сессии — тогда только запоминаем
 */
export function newPopups(
  rows: ErpNotification[],
  seen: readonly string[],
  first: boolean,
): ErpNotification[] {
  if (first) return [];
  const known = new Set(seen);
  return rows
    .filter((n) => !n.read_at && !known.has(n.id))
    .slice(0, POPUP_LIMIT);
}

/**
 * Чем запомнить показанное.
 *
 * Помним ВЕСЬ список, а не только показанное: прочитанное в другой вкладке
 * приедет сюда уже с `read_at`, и без этого оно всплыло бы у человека, который
 * его только что и прочитал. Список короткий (`LIMIT` слайса), поэтому
 * хранение целиком дешевле любой хитрости.
 */
export function seenIds(rows: ErpNotification[]): string[] {
  return rows.map((n) => n.id);
}

/**
 * Очередь показа: новое сверху, без повторов, не длиннее `POPUP_LIMIT`.
 *
 * Повтор возможен буднично: realtime звонит на каждую строку, а список
 * перечитывается целиком — одно и то же уведомление приходит дважды, пока
 * первая карточка ещё висит.
 */
export function mergePopups(
  current: ErpNotification[],
  incoming: ErpNotification[],
): ErpNotification[] {
  if (incoming.length === 0) return current;
  const have = new Set(current.map((n) => n.id));
  const add = incoming.filter((n) => !have.has(n.id));
  if (add.length === 0) return current;
  return [...add, ...current].slice(0, POPUP_LIMIT);
}
