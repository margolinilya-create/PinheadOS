/**
 * Указатель «id этапа → этап» с памяткой ПО МАССИВУ.
 *
 * Зачем. `isStageReady`, `waitingReason` и `stageInputQty` строили
 * `new Map(allStages.map(…))` заново на КАЖДЫЙ вызов, а зовут их для каждого
 * этапа позиции с одним и тем же массивом. Позиция из S этапов строила
 * S карт по S элементов — O(S²) при том, что карта каждый раз одна и та же.
 *
 * Замер (общее число этапов зафиксировано ~120 000, менялась только длина
 * маршрута позиции):
 *
 *   этапов на позицию │  4  │  8  │ 16  │ 32  │  64 │ 128
 *   isStageReady, мс  │ 48  │ 98  │ 159 │ 269 │ 554 │ 1023   (×21)
 *   stageInputQty, мс │ 53  │ 97  │ 153 │ 266 │ 539 │ 1036   (×20)
 *
 * Сегодня S = 3–8, то есть это «всего лишь» постоянный множитель ×2 на самом
 * горячем пути раздела. Но маршрут растёт сам собой: три метода нанесения
 * плюс циклы образца дают 12–16 этапов на позицию — уже ×4.
 *
 * ВАЖНО ПРО ПАМЯТКУ. Ключ — сам массив, и памятка верна ровно до тех пор,
 * пока массивы этапов не правятся НА МЕСТЕ. В этом сторе так и есть: любое
 * изменение пересоздаёт массив (`patchStageIn`, `sortOrderFull`, `map`/
 * `filter` в слайсах) — на этом же держится и мемоизация React. Если однажды
 * появится код, мутирующий массив этапов по месту, он получит устаревшую
 * карту МОЛЧА, и искать это будет тяжело: расчёт готовности станет отвечать
 * по прежнему составу этапов. Поэтому — не мутировать; правило записано здесь,
 * а не только в общей культуре стора.
 *
 * `WeakMap` выбран, чтобы карты уходили вместе с массивами и не копились:
 * при каждом realtime-событии массив пересоздаётся, и обычный `Map` держал бы
 * все прежние версии до конца смены.
 */

type WithId = { id: string };

const cache = new WeakMap<object, Map<string, unknown>>();

export function stagesById<T extends WithId>(stages: readonly T[]): Map<string, T> {
  const hit = cache.get(stages as unknown as object);
  if (hit) return hit as Map<string, T>;
  const built = new Map<string, T>(stages.map((s) => [s.id, s]));
  cache.set(stages as unknown as object, built as Map<string, unknown>);
  return built;
}
