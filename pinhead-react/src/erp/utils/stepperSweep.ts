/**
 * РАЗГОН УДЕРЖАНИЯ У ЧИСЛОВОГО СТЕППЕРА — чистой функцией, отдельно от DOM.
 *
 * Приём взят у блока `Drag stepper` с bencho.dev и сформулирован там же одной
 * строкой: «тап точен, удержание грубо и быстро». Степпер, у которого есть
 * только тап, заставляет цех нажать «+» двадцать раз; степпер, у которого
 * есть только свип, не даёт поставить ровно 3.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ТЕЛО КОМПОНЕНТА. Кривая разгона — это
 * арифметика, и проверяется она значениями, а не рендером: «через сколько
 * секунд удержания набежит двадцать шагов» на jsdom не спросишь — там нет
 * ни кадров, ни реального времени. Тот же довод, по которому в проекте живут
 * `utils/progress`, `utils/stagePlan` и прочие модули-листы.
 *
 * ⚠️ ШАГИ СЧИТАЮТСЯ ОТ НАЧАЛА УДЕРЖАНИЯ, А НЕ ПРИРАЩЕНИЯМИ ЗА КАДР.
 * Компонент спрашивает «сколько всего шагов положено к моменту t» и добирает
 * разницу с уже выданными. Приращение за кадр зависело бы от частоты кадров:
 * на подтормаживающем планшете цеха (а это единственное устройство, где
 * удержание вообще применяют) шагов набегало бы МЕНЬШЕ, чем на быстром
 * ноутбуке разработчика, — то есть одно и то же движение пальца давало бы
 * разный результат. Интеграл от частоты такой зависимости не имеет.
 */

/** Задержка до начала свипа. Короче — и обычный тап начнёт «ехать». */
export const HOLD_MS = 400;

/** Шагов в секунду в начале свипа. */
const RATE_FROM = 10;

/** Шагов в секунду на полном разгоне. */
const RATE_TO = 40;

/** За сколько секунд частота доходит от RATE_FROM до RATE_TO. */
const RAMP_S = 1.2;

/** Прирост частоты, шагов в секунду за секунду. */
const ACCEL = (RATE_TO - RATE_FROM) / RAMP_S;

/** Шагов, набежавших за время разгона целиком. */
const RAMP_STEPS = RATE_FROM * RAMP_S + (ACCEL * RAMP_S * RAMP_S) / 2;

/**
 * Сколько шагов положено выдать за `ms` миллисекунд СВИПА (время считается
 * с момента, когда свип начался, то есть уже после `HOLD_MS`).
 *
 * Частота растёт линейно от 10/с до 40/с за 1,2 с и дальше держится:
 * интеграл линейной частоты — квадратичный, поэтому первые шаги идут
 * неторопливо (успеваешь отпустить на нужном), а через секунду набор
 * становится быстрым.
 */
export function sweptSteps(ms: number): number {
  if (!(ms > 0)) return 0;
  const t = ms / 1000;
  if (t <= RAMP_S) return Math.floor(RATE_FROM * t + (ACCEL * t * t) / 2);
  return Math.floor(RAMP_STEPS + RATE_TO * (t - RAMP_S));
}

/**
 * Привести число к границам. `null` означает «значение не задано» и границами
 * не трогается: пустое поле факта — это не ноль (правило проекта о том, что
 * поле «сколько сдано» стоит пустым, а не предзаполненным).
 */
export function clampValue(n: number, min?: number, max?: number): number {
  let v = n;
  if (typeof min === 'number' && v < min) v = min;
  if (typeof max === 'number' && v > max) v = max;
  return v;
}

/**
 * Значение после `steps` шагов в сторону `dir` от `start`.
 *
 * Округление до знаков самого шага обязательно: у приёмки материала шаг 0.01,
 * и `0.1 + 0.01` в двоичной плавающей даёт 0.11000000000000001 — в поле
 * количества такое показывать нельзя.
 */
export function valueAfterSteps(
  start: number,
  steps: number,
  dir: 1 | -1,
  step: number,
  min?: number,
  max?: number,
): number {
  const raw = start + dir * steps * step;
  const decimals = decimalsOf(step);
  const rounded = decimals > 0 ? Number(raw.toFixed(decimals)) : raw;
  return clampValue(rounded, min, max);
}

/** Сколько знаков после запятой у шага: 0.01 → 2, 1 → 0. */
export function decimalsOf(step: number): number {
  if (!Number.isFinite(step)) return 0;
  const s = String(step);
  const dot = s.indexOf('.');
  if (dot === -1) return 0;
  return s.length - dot - 1;
}
