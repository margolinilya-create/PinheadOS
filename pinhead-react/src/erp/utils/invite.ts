/**
 * Ссылка-приглашение — чистая функция, а не строка по месту.
 *
 * Адрес собирается в двух местах (модалка выдачи и список действующих
 * приглашений) и обязан совпадать с тем, что читает `JoinScreen`: разойдутся —
 * получится ссылка, которая открывает форму входа вместо приглашения, и
 * человек упрётся ровно в то, ради чего приглашения и заводились.
 */

/** Путь экрана приглашения. Живёт здесь же, чтобы у адреса был один источник */
export const JOIN_PATH = '/join';

export function inviteUrl(code: string, origin?: string): string {
  const base = origin ?? (typeof window !== 'undefined' ? window.location.origin : '');
  return `${base}${JOIN_PATH}?code=${code}`;
}
