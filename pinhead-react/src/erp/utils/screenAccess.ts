import type { ErpPermission } from '../types';

/**
 * Кто видит разделы «Операции» — ОДИН источник для маршрута и для меню.
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ. Экраны «Закупка», «Склад», «Подряд» и «Эксперим. цех» были
 * закрыты ролью УЧЁТНОЙ ЗАПИСИ (`admin`/`director`) — и в маршруте, и в меню,
 * двумя независимыми списками. Права, заведённые 10.08 под конкретных людей,
 * оказались недостижимы: кладовщик получил `warehouse.manage`, но не видел
 * пункта «Склад» и не мог открыть адрес; технолог — то же с образцами,
 * закупщик — с закупкой. Право есть, работать нельзя.
 *
 * ПРАВИЛО. Раздел видит тот, кто может там работать, ПЛЮС менеджер заказа —
 * ему нужно видеть, где стоит его заказ, даже когда действия ему недоступны
 * (экраны это умеют: без права они остаются на чтение).
 *
 * Список один, потому что два уже разъехались: маршрут и меню — разные файлы,
 * и «добавили в одном, забыли в другом» здесь означает либо пункт, ведущий
 * в отказ, либо экран, до которого не дойти.
 */
export const SCREEN_ACCESS: Record<string, ErpPermission[]> = {
  // Ведёт снабжение; менеджер заказа смотрит, чем закрыта потребность
  '/purchasing': ['material.receive', 'order.manage'],
  // Приёмка, маркировка, упаковка и отгрузка — работа кладовщика
  '/warehouse': ['warehouse.manage', 'order.manage'],
  // Решение по маршруту заказа: что делаем не у себя
  '/subcontracting': ['order.manage'],
  // Разработку образцов ведёт технолог
  '/experimental': ['experimental.manage', 'order.manage'],
};

/**
 * Открыт ли раздел. `can` — это `useErpAccess().can`.
 *
 * Незнакомый путь открыт: гейт разделов перечисляет ИСКЛЮЧЕНИЯ, а не выдаёт
 * доступ. Иначе новый экран, забытый в этом списке, молча пропал бы у всех.
 */
export function canOpenScreen(
  can: (p: ErpPermission) => boolean,
  path: string,
): boolean {
  const needed = SCREEN_ACCESS[path];
  if (!needed) return true;
  return needed.some((p) => can(p));
}
