/**
 * Ключ идемпотентности ОДНОЙ попытки записи.
 *
 * Задача, которую он решает, одна и очень конкретная: запрос ушёл, сервер его
 * закоммитил, ответ не вернулся — человек видит ошибку и жмёт кнопку второй
 * раз. Для приёмки материала это молча удвоенный приход, то есть неверное
 * количество материала на фабрике. Клиентский `saving` тут не помогает: он
 * гасит кнопку на время ОДНОГО запроса, а здесь их два, и оба настоящие.
 *
 * Правило простое и объяснимое человеку: **не изменил ввод — это та же
 * попытка**. Ключ живёт, пока не менялся набранный текст; поменял число —
 * новая попытка, новый ключ, вторая строка журнала (и это правильно: пришло
 * ещё столько-то). Успех тоже сбрасывает ключ — следующая приёмка новая.
 *
 * Хранить ключ в состоянии компонента нельзя: перерисовка от realtime сбросила
 * бы его ровно в тот момент, когда он нужен. Поэтому ref, живущий столько же,
 * сколько форма.
 */

/**
 * @returns {{ keyFor: (signature: string) => string, reset: () => void }}
 *   `keyFor` отдаёт тот же ключ, пока подпись ввода не изменилась;
 *   `reset` — после успеха.
 */
export function createAttemptKeeper() {
  let signature = null;
  let key = null;
  return {
    keyFor(next) {
      if (next !== signature || !key) {
        signature = next;
        key = crypto.randomUUID();
      }
      return key;
    },
    reset() {
      signature = null;
      key = null;
    },
  };
}
