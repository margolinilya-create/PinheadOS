/**
 * ЕДИНИЦА ИЗМЕРЕНИЯ МАТЕРИАЛА И УЧЁТ РУЛОНАМИ (правка заказчика 16.09, п. 5).
 *
 * ЧТО ПРОСИТ ДОКУМЕНТ. «Если материал учитывается в кг, под полем „Пришло
 * сейчас, килограммы" добавить дополнительное обязательное поле „Количество
 * рулонов, шт."».
 *
 * ПОЧЕМУ ЭТО НЕ СРАВНЕНИЕ СТРОКИ. `erp_materials.unit` — свободный текст
 * (метка для человека, а не коэффициент: пересчёта между единицами система
 * не делает и делать не должна). На боевой базе 16.09 в нём уже РАЗНОБОЙ:
 * `кг` у четырёх строк, `Килограммы` у трёх, `шт` у трёх, пусто у одной.
 * Причина видна там же: в справочнике `erp_dictionaries` вида `unit` у
 * значения есть И КОД (`кг`), И ИМЯ (`Килограммы`), а форма закупки пишет
 * то, что человек выбрал. Условие `unit === 'кг'` не сработало бы на трёх
 * строках из семи — то есть поле рулонов не появилось бы там, где оно
 * обязательно.
 *
 * ПОЧЕМУ ПРИЗНАК В СПРАВОЧНИКЕ, А НЕ СПИСОК В КОДЕ. «Рулонность» — свойство
 * единицы, а единицы ведёт админка. Список в коде означал бы, что новая
 * единица («погонный метр», «бухта») требует правки кода, — ровно то, что
 * правило проекта запрещает про `gate_material_kinds` и `result_fields`.
 * Поэтому источник — `meta.rolls` у значения справочника, а синонимы ниже
 * нужны только для строк, набранных руками ДО того, как справочник появился.
 *
 * FAIL-OPEN. Единица неизвестна, справочник не загрузился, значение пустое —
 * поле рулонов НЕ показываем и приёмку не блокируем. Обратное означало бы,
 * что кладовщик не может принять фурнитуру, пока кто-то не заполнит
 * справочник: остановка склада из-за отсутствующего поля. Тот же довод,
 * что у материального гейта участков.
 */

import type { ErpDictionaryItem } from '../types';

/** Приведение написания к сравнимому виду: регистр, пробелы, точки */
export function normalizeUnit(raw: string | null | undefined): string {
  return (raw ?? '')
    .toLowerCase()
    .replace(/\./g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Синонимы «килограммов», набранные руками до справочника.
 *
 * Список закрытый и намеренно короткий: он НЕ заменяет справочник, а лечит
 * уже существующие строки. Новую единицу заводят в админке, а не здесь.
 */
const KG_SYNONYMS = new Set(['кг', 'килограмм', 'килограммы', 'килограммов', 'kg']);

/** Значение справочника единиц, у которого стоит признак «учитывается рулонами» */
function dictTracksRolls(item: ErpDictionaryItem | undefined): boolean {
  const meta = item?.meta as { rolls?: unknown } | null | undefined;
  // Строго `true`: у значений без признака `meta` пустой объект, и любое
  // «не false» объявило бы рулонными все единицы разом
  return meta?.rolls === true;
}

/**
 * Учитывается ли материал в этой единице РУЛОНАМИ.
 *
 * Сначала справочник (по коду и по имени — в данных встречается и то, и
 * другое), затем синонимы для строк, набранных руками.
 */
export function unitTracksRolls(
  unit: string | null | undefined,
  dictionary: readonly ErpDictionaryItem[] | null | undefined,
): boolean {
  const value = normalizeUnit(unit);
  if (!value) return false;

  const units = (dictionary ?? []).filter((d) => d.kind === 'unit');
  const match = units.find(
    (d) => normalizeUnit(d.code) === value || normalizeUnit(d.name) === value,
  );
  if (match) return dictTracksRolls(match);

  // Единицы нет в справочнике: её мог набрать закупщик руками (справочник —
  // подсказка, а не ограничение). Тогда решают синонимы, и только они
  return KG_SYNONYMS.has(value);
}

/**
 * Подпись единицы человеку: код справочника, если он найден, иначе как есть.
 *
 * Нужна, чтобы «Пришло сейчас, Килограммы» читалось как «Пришло сейчас, кг» —
 * подпись поля не должна зависеть от того, код или имя выбрал закупщик.
 */
export function unitShortLabel(
  unit: string | null | undefined,
  dictionary: readonly ErpDictionaryItem[] | null | undefined,
): string {
  const raw = (unit ?? '').trim();
  if (!raw) return '';
  const value = normalizeUnit(raw);
  const match = (dictionary ?? []).find(
    (d) => d.kind === 'unit'
      && (normalizeUnit(d.code) === value || normalizeUnit(d.name) === value),
  );
  return match?.code || raw;
}
