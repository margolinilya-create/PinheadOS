import { storageGetRaw } from '../../lib/storage';

/** Минимум строки цеха: код и id */
interface DeptLike {
  id: string;
  code: string;
}

/**
 * Код «своего» участка; пустая строка — своего участка нет.
 *
 * Пустую строку отдаём, а не `null`: вызывающие подставляют её в адрес
 * (`/queue/${code}`), и `null` дал бы путь `/queue/null` — вместо отказа
 * получилась бы страница несуществующего цеха.
 */
export function myDeptCode(
  departments: DeptLike[] = [],
  myDeptId: string | null | undefined,
): string {
  const bound = departments.find((d) => d.id === myDeptId);
  return bound?.code || storageGetRaw('erp_my_dept') || '';
}
