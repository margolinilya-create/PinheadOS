/**
 * Плановая дата завершения этапа — ОДНО правило подстановки на все точки ввода.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Разбор 23.08 показал, что дату пишет РОВНО ОДНА
 * форма — «Взять в работу» в очереди цеха, — и потому её нет ни у одного
 * этапа, который ещё не запущен. Точек входа в работу при этом три: сама
 * форма, возврат брака (целевой этап переоткрывается) и запуск закупки.
 * Две последние дату не спрашивали вовсе.
 *
 * Правило подстановки при этом нетривиальное и уже однажды чинилось: «сегодня»
 * там стоять не должно — этап с дальним сроком становился бы «просрочен»
 * на следующий день (ERP-04). Копия этого правила в каждой из трёх форм
 * разошлась бы молча: все три «работают», просто предлагают разные даты.
 */

import { factoryToday } from '../../utils/date';
import { shiftIsoDate } from './time';

export interface PlanDefaultInput {
  /** Уже заданный план этапа — он всегда сильнее расчёта */
  plannedEnd?: string | null;
  /** Норматив участка в днях (`erp_departments.norm_days`), 0/пусто — не задан */
  normDays?: number | null;
  /** Срок сдачи заказа */
  dueDate?: string | null;
  /**
   * Дата запуска заказа (`erp_orders.launch_date`) — правка заказчика 30.08,
   * п. 10: «Выбранную дату использовать как фактическую дату запуска заказа
   * для расчёта сроков». Здесь и есть тот расчёт: до 30.08 дата запуска
   * не участвовала ни в одной формуле вовсе, её только показывали.
   */
  launchDate?: string | null;
}

/**
 * База отсчёта: работа не начинается раньше, чем заказ запущен.
 *
 * Запуск в БУДУЩЕМ («заведём сейчас, запустим в понедельник») сдвигает базу
 * на себя: план от «сегодня» пообещал бы срок, к которому цех даже
 * не приступит. Запуск в ПРОШЛОМ (заказ переносится в ERP задним числом —
 * тот самый случай, ради которого п. 10 и написан) базу не двигает: этап
 * берут в работу сегодня, и план в прошлом объявил бы просроченным всё,
 * что только начинается. Обещание — величина будущая, а прошлое запуска
 * отвечает на другой вопрос: с какого дня заказ идёт, и это видно в плане.
 */
function planBase(launchDate: string | null | undefined, today: string): string {
  return launchDate && launchDate > today ? launchDate : today;
}

/**
 * Что предложить человеку в поле «План завершения».
 *
 * Порядок: свой план этапа → норматив участка от базы → срок заказа → база.
 * Последняя ступень — вынужденная: поле обязательно к заполнению, и пустым
 * его оставлять нельзя, но до неё доходит только заказ без срока на участке
 * без норматива.
 */
export function defaultPlannedEnd(
  { plannedEnd, normDays, dueDate, launchDate }: PlanDefaultInput,
  today: string = factoryToday(),
): string {
  if (plannedEnd) return plannedEnd;
  // База — переданный `today`, а не `factoryToday()` внутри `shiftIsoDate`:
  // иначе аргумент функции влиял бы на две ступени из трёх, и тест в чужом
  // часовом поясе проверял бы не то, что работает в цеху
  const base = planBase(launchDate, today);
  if (normDays && normDays > 0) return shiftIsoDate(base, normDays);
  // Срок заказа по-прежнему сильнее базы: правило «не „сегодня", пока есть
  // срок» (ERP-04) не отменялось. Противоречие «срок раньше запуска» —
  // ошибка ВВОДА, и ловит её `validateOrderForm`, а не подстановка
  return dueDate || base;
}

/** Открытые этапы: закрытые и пропущенные плана уже не ждут */
const OPEN_STATUSES = new Set(['waiting', 'ready', 'in_progress', 'blocked']);

/**
 * Сколько ОТКРЫТЫХ этапов идут без плановой даты.
 *
 * Считается для одного набора этапов — позиции или заказа. Отвечает
 * на вопрос «сколько работы выпало из контроля сроков»: у такого этапа
 * не считается ни просрочка, ни загрузка цеха, и до 23.08 это состояние
 * было у 100 % открытых этапов, то есть не выделяло ничего.
 *
 * Подрядные этапы считаются наравне с нашими: срок подрядчику нужен так же.
 */
export function unplannedStages<T extends { status: string; planned_end?: string | null }>(
  stages: readonly T[] | null | undefined,
): { total: number; unplanned: number } {
  let total = 0;
  let unplanned = 0;
  for (const st of stages ?? []) {
    if (!OPEN_STATUSES.has(st.status)) continue;
    total += 1;
    if (!st.planned_end) unplanned += 1;
  }
  return { total, unplanned };
}
