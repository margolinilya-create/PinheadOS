/**
 * Плановая дата завершения этапа — ОДНО правило подстановки на все точки ввода.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Разбор 23.08 показал, что дату пишет РОВНО ОДНА
 * форма — «Взять в работу» в очереди цеха, — и потому её нет ни у одного
 * этапа, который ещё не запущен. Точек входа в работу при этом три: сама
 * форма, возврат брака (целевой этап переоткрывается) и запуск закупки.
 * Две последние дату не спрашивали вовсе.
 *
 * Правило подстановки при этом нетривиальное и уже однажды чинилось: «сегодня»
 * там стоять не должно — этап с дальним сроком становился бы «просрочен»
 * на следующий день (ERP-04). Копия этого правила в каждой из трёх форм
 * разошлась бы молча: все три «работают», просто предлагают разные даты.
 */

import { factoryToday } from '../../utils/date';
import { shiftIsoDate } from './time';

export interface PlanDefaultInput {
  /** Уже заданный план этапа — он всегда сильнее расчёта */
  plannedEnd?: string | null;
  /** Норматив участка в днях (`erp_departments.norm_days`), 0/пусто — не задан */
  normDays?: number | null;
  /** Срок сдачи заказа */
  dueDate?: string | null;
}

/**
 * Что предложить человеку в поле «План завершения».
 *
 * Порядок: свой план этапа → норматив участка от сегодня → срок заказа →
 * сегодня. Последняя ступень — вынужденная: поле обязательно к заполнению,
 * и пустым его оставлять нельзя, но до неё доходит только заказ без срока
 * на участке без норматива.
 */
export function defaultPlannedEnd(
  { plannedEnd, normDays, dueDate }: PlanDefaultInput,
  today: string = factoryToday(),
): string {
  if (plannedEnd) return plannedEnd;
  // База — переданный `today`, а не `factoryToday()` внутри `shiftIsoDate`:
  // иначе аргумент функции влиял бы на две ступени из трёх, и тест в чужом
  // часовом поясе проверял бы не то, что работает в цеху
  if (normDays && normDays > 0) return shiftIsoDate(today, normDays);
  return dueDate || today;
}
