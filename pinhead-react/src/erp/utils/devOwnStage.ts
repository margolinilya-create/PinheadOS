import type { DevStage } from './experimentalBoard';
import type { ErpItemStage } from '../types';

/**
 * СОБСТВЕННЫЕ ЭТАПЫ ЭКСПЕРИМЕНТАЛЬНОГО ЦЕХА (правка заказчика 01.09, вторая
 * итерация, п. 3).
 *
 * ЧТО ПРОСИТ ДОКУМЕНТ. «Для этапов, которые экспериментальный цех выполняет
 * своими силами, отдельного подтверждения выполнения нет и не нужно. Построение
 * лекал, крой, пошив и другие собственные этапы закрываются самим переносом
 * карточки технологом на следующий этап… Сейчас карточку можно передвигать
 * дальше, но предыдущий этап не закрывается».
 *
 * ГРАНИЦА ПРОВЕДЕНА ПО ТОМУ, ЧЬИМИ РУКАМИ ДЕЛАЕТСЯ РАБОТА, и документ называет
 * её прямым текстом: «Если этап выполняет экспериментальный цех сам, перенос
 * карточки технологом является подтверждением завершения текущего этапа. Если
 * этап выполняет обычный производственный цех, экспериментальный цех не может
 * двигаться дальше, пока этот цех не завершил работу».
 *
 * Поэтому НАНЕСЕНИЯ В ЭТОЙ ТАБЛИЦЕ ОТСУТСТВУЮТ, и это не пропуск: их закрывает
 * цех, а перенос карточки мимо них запрещён гейтом `devMoveIntent`
 * (отказ `branding`). Закрывай мы их здесь — сами бы и обошли собственный
 * запрет, объявив сделанным то, чего цех не делал.
 *
 * У шагов `patterns`, `materials` и `final` этапа маршрута нет вовсе:
 * `BASE_CHAIN` их не заводит, а «Ожидает материалы» — стоянка, а не работа.
 * Отсутствие в таблице читается как «закрывать нечего», а не как «забыли».
 */
export const DEV_OWN_STAGE_DEPT: Partial<Record<DevStage, string>> = {
  cutting: 'cutting',
  sewing: 'sewing',
};

export interface DevOwnStageInput {
  /** Шаг, КОТОРЫЙ ПОКИДАЮТ: его работа и объявляется завершённой */
  from: DevStage;
  /** Этапы позиции разработки */
  stages?: readonly ErpItemStage[] | null;
  /** Справочник цехов — код ищется по нему, константы кодов здесь нет */
  departments?: readonly { id: string; code: string }[] | null;
}

const CLOSED = new Set(['done', 'skipped']);

/**
 * Этап маршрута, который надо закрыть при уходе с шага; `null` — закрывать
 * нечего.
 *
 * Берётся ОТКРЫТЫЙ этап нужного цеха с наименьшим `cycle`: у образца бывает
 * несколько заходов в один цех (доработка), и закрывать надо тот, который идёт
 * сейчас, а не первый попавшийся. Уже закрытый этап отсеивается здесь же —
 * повторный перенос карточки не должен пытаться закрыть его второй раз.
 */
export function devOwnStageToClose(input: DevOwnStageInput): ErpItemStage | null {
  const code = DEV_OWN_STAGE_DEPT[input.from];
  if (!code) return null;
  const dept = (input.departments ?? []).find((d) => d.code === code);
  if (!dept) return null;
  const open = (input.stages ?? [])
    .filter((s) => s.department_id === dept.id && !CLOSED.has(s.status))
    .sort((a, b) => (a.cycle ?? 0) - (b.cycle ?? 0));
  return open[0] ?? null;
}

/**
 * Сколько штук осталось дописать этапу до полного тиража.
 *
 * СЧЁТЧИК ПИШЕТСЯ ПРИРАЩЕНИЕМ (правило проекта): абсолют с клиента — потерянное
 * обновление, и `erp_stage_report_progress` принимает именно приращение,
 * а `done` ставит сама, когда тираж добран. Ноль означает «дописывать нечего»:
 * этап уже набрал тираж, и звать RPC незачем.
 */
export function devStageRemainder(
  stage: Pick<ErpItemStage, 'qty_done'>,
  itemQty: number | null | undefined,
): number {
  const total = Number(itemQty ?? 0);
  if (!(total > 0)) return 0;
  return Math.max(total - (stage.qty_done ?? 0), 0);
}
