/**
 * ЧЬЁ ГОТОВОЕ ИЗДЕЛИЕ (правки заказчика 07.09 п. 4, 14.09 п. 1).
 *
 * Документ 07.09 просил «разделить тип производства „Готовое изделие“ на два
 * сценария»; ось назвал владелец — ЧЬЁ ИЗДЕЛИЕ. Документ 14.09 добавил третий
 * вариант. Из каждого следуют ровно две маршрутные вещи — нужна ли закупка
 * и нужен ли этап склада:
 *
 *   `purchased` — изделие закупаем мы: лист закупки и этап «Закупка»
 *                 как прежде; этап склада — только при нанесении.
 *   `customer`  — давальческое. Изделие привозит клиент, мы только наносим:
 *                 закупать нечего (этап «Закупка» из маршрута уходит),
 *                 а приёмка склада обязательна — иначе никто не фиксирует,
 *                 что чужой товар доехал.
 *   `stock`     — берём со склада готовой продукции. Закупать тоже нечего
 *                 (изделие уже наше и уже на фабрике), но склад обязан
 *                 ОТДАТЬ его в работу — иначе у позиции не осталось бы
 *                 ни одного этапа вовсе, и никто не знал бы, выдан ли товар.
 *
 * СРАВНЕНИЕ СТРОГО С КАЖДЫМ ЗНАЧЕНИЕМ, никогда с `!== 'purchased'`. Колонка
 * новая, и у позиций из старых фикстур, урезанных выборок и кэша её нет вовсе:
 * отрицание объявило бы НЕ-закупаемым всё готовое изделие разом и сняло бы
 * закупку у заведённых заказов задним числом. Ровно та же причина, по которой
 * подрядность читается как `executor === 'contractor'`.
 *
 * ВОПРОС ЗАДАЁТСЯ ТОЛЬКО ГОТОВОМУ ИЗДЕЛИЮ. У пошива изделия ещё нет — оно
 * появится из нашего кроя, — и «чьё оно» там не значит ничего. Поэтому
 * `garmentSourceOf` смотрит и на тип производства: значение, оставшееся
 * от переключённой позиции, не должно менять её маршрут молча.
 */

