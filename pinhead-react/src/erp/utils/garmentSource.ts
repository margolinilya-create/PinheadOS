/**
 * ЧЬЁ ГОТОВОЕ ИЗДЕЛИЕ (правки заказчика 07.09, п. 4).
 *
 * Документ просит «разделить тип производства „Готовое изделие“ на два
 * сценария» и тут же откладывает детализацию; ось назвал владелец: изделие
 * КЛИЕНТА или НАШЕ. Из этого следуют ровно две вещи, и обе — маршрутные:
 *
 *   `customer`  — давальческое. Изделие привозит клиент, мы только наносим:
 *                 закупать нечего (этап «Закупка» из маршрута уходит),
 *                 а приёмка склада обязательна — иначе никто не фиксирует,
 *                 что чужой товар доехал.
 *   `purchased` — изделие закупаем мы: лист закупки и этап «Закупка»
 *                 как прежде.
 *
 * СРАВНЕНИЕ СТРОГО С `'customer'`, никогда с `!== 'purchased'`. Колонка новая,
 * и у позиций из старых фикстур, урезанных выборок и кэша её нет вовсе:
 * второй вариант объявил бы давальческим ВСЁ готовое изделие разом и снял бы
 * закупку у заведённых заказов задним числом. Ровно та же причина, по которой
 * подрядность читается как `executor === 'contractor'`.
 *
 * ВОПРОС ЗАДАЁТСЯ ТОЛЬКО ГОТОВОМУ ИЗДЕЛИЮ. У пошива изделия ещё нет — оно
 * появится из нашего кроя, — и «чьё оно» там не значит ничего. Поэтому
 * `garmentSourceOf` смотрит и на тип производства: значение, оставшееся
 * от переключённой позиции, не должно менять её маршрут молча.
 */

import type { GarmentSource } from '../types';

export type { GarmentSource };

export const GARMENT_SOURCE_LABELS: Record<GarmentSource, string> = {
  purchased: 'Закупаем мы',
  customer: 'Давальческое — изделие клиента',
};

/**
 * Порядок плиток в форме. Явный массив, а не порядок ключей словаря подписей:
 * первым стоит прежнее поведение (`purchased`) — оно же значение по умолчанию,
 * и переставлять его вперёд «на глаз» при следующей правке подписей нельзя.
 */
export const GARMENT_SOURCE_ORDER: GarmentSource[] = ['purchased', 'customer'];

/** Что означает выбор на языке цеха и закупки */
export const GARMENT_SOURCE_HINTS: Record<GarmentSource, string> = {
  purchased: 'Нужен лист закупки, в маршруте будет этап «Закупка»',
  customer: 'Закупки нет; склад обязан принять изделие клиента до нанесения',
};

/** Позиция в объёме, достаточном для вопроса «чьё изделие» */
export interface GarmentSourceItem {
  production_type?: string | null;
  garment_source?: string | null;
}

/**
 * Сценарий позиции. Не «готовое изделие» — всегда `purchased`: вопрос к ней
 * не задавался, и её маршрут этой колонкой не управляется.
 */
export function garmentSourceOf(item: GarmentSourceItem | null | undefined): GarmentSource {
  if (item?.production_type !== 'ready_garment') return 'purchased';
  return item?.garment_source === 'customer' ? 'customer' : 'purchased';
}

/** Изделие принадлежит клиенту: закупать нечего, приёмка склада обязательна */
export function isCustomerGarment(item: GarmentSourceItem | null | undefined): boolean {
  return garmentSourceOf(item) === 'customer';
}

/**
 * Нужна ли по этой позиции закупка.
 *
 * Отдельная функция, а не отрицание предыдущей: читают её лист закупки
 * и валидация формы, и вопрос там задаётся ИМЕННО ТАК. Прочие основания
 * вырезать закупку (отметка «Закупка не требуется» на заказе, материал
 * подрядчика) живут в `buildItemRoute` и сюда не переезжают — это условия
 * ЗАКАЗА и ПОДРЯДА, а не свойство изделия.
 */
export function itemNeedsPurchase(item: GarmentSourceItem | null | undefined): boolean {
  return !isCustomerGarment(item);
}
