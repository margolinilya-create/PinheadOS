import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { latestMatching, withoutComments, withoutJsComments } from './migrations.testutil';
import { EMPTY_ITEM } from './orderForm';
import { ORDER_LIST_SELECT } from '../store/orderHelpers';

/**
 * СВЯЗЬ ПОЗИЦИИ ЗАКАЗА С КАРТОЧКОЙ МОДЕЛИ — от формы до базы и обратно.
 *
 * ЗАЧЕМ СТОРОЖ. Колонка `sku_card_id` появилась 15.09, а писатели заказа
 * перечисляют колонки ПОИМЁННО: забытая в перечне колонка не роняет ничего —
 * она просто не пишется, и «Использовать в заказе» работает на вид, а
 * статистика модели навсегда показывает ноль заказов. Ровно тот же отказ,
 * на котором проект уже ловился с `executor`.
 *
 * ПРОВЕРЯЕТСЯ ВЕСЬ ПУТЬ: черновик формы → payload обоих писателей → функции
 * базы → списочная выборка. Разрыв в любом звене делает связь невидимой
 * молча.
 *
 * Миграция ищется ПО ТЕКСТУ ПРАВИЛА (`latestMatching`), а не по функции:
 * `erp_create_order` и `erp_update_order` пересобраны из собственного
 * определения (`pg_get_functiondef` + вставки), и `latestDefining` их
 * не найдёт — это записанная оборотная сторона приёма.
 */

const SRC = join(process.cwd(), 'src');
const MODAL = withoutJsComments(
  readFileSync(join(SRC, 'erp/screens/orders/CreateOrderModal.jsx'), 'utf8'),
);
/**
 * ДВА ПРИЁМА, И ОБА ОБЯЗАТЕЛЬНЫ.
 *
 * 1. Комментарии снимаются И строчные (`--`), И БЛОЧНЫЕ (`/* … *\/`).
 *    Первая редакция этого сторожа снимала только строчные — и проверка
 *    «правка спрашивает наличие ключа» проходила НА КОММЕНТАРИИ, который
 *    объясняет, почему так сделано. Сторож, зелёный на снятом правиле;
 *    правило проекта записано ровно про этот случай.
 * 2. Экранирование кавычек разворачивается: вставки живут внутри `E'…'`,
 *    и в файле код выглядит как `nullif(v_item->>\'sku_card_id\', \'\')`.
 *    Кодировать экранирование в самом сторожe значило бы сторожить СПОСОБ
 *    записи вместо правила.
 */
const SQL = withoutJsComments(withoutComments(
  latestMatching(/v_item \? \\?'sku_card_id'/, 'связь позиции с карточкой модели'),
)).replace(/\\'/g, "'");

describe('связь позиции заказа с моделью каталога', () => {
  it('черновик формы несёт поле', () => {
    // Иначе правка заказа шлёт ключ с пустым значением и ОТВЯЗЫВАЕТ модель
    expect(EMPTY_ITEM).toHaveProperty('sku_card_id');
  });

  it('оба писателя шлют поле в payload', () => {
    /**
     * Их ДВА — создание и правка, — и это разные куски кода в одном файле.
     * Забыть один значит получить «создаётся со ссылкой, правится без неё»:
     * заказ теряет модель при первой же правке срока.
     */
    const writers = MODAL.match(/sku_card_id/g) ?? [];
    expect(writers.length, 'sku_card_id есть не у обоих писателей payload')
      .toBeGreaterThanOrEqual(2);
  });

  it('списочная выборка возит колонку', () => {
    // Без неё ссылка на модель в карточке заказа не рисовалась бы вовсе:
    // поле приехало бы undefined, без единой ошибки
    expect(ORDER_LIST_SELECT).toContain('sku_card_id');
  });

  /**
   * ПУСТАЯ СТРОКА НЕ ИМЕЕТ ПРАВА УРОНИТЬ СОЗДАНИЕ ЗАКАЗА. Форма шлёт `''`,
   * когда модель не выбрана, а голое `::uuid` отвечает на это 22P02 —
   * то есть заказ не создавался бы ВООБЩЕ, у всех и всегда.
   */
  it('создание принимает пустое значение как «не из каталога»', () => {
    expect(SQL).toMatch(/nullif\(v_item->>'sku_card_id', ''\)::uuid/);
  });

  /**
   * ПРАВКА СПРАШИВАЕТ НАЛИЧИЕ КЛЮЧА, А НЕ ЕГО ЗНАЧЕНИЕ.
   *
   * Голое присваивание отвязывало бы модель у всякого, кто правит заказ
   * из ОТКРЫТОЙ СТАРОЙ ВКЛАДКИ (прежний бандл ключа не шлёт), а `coalesce`
   * сделал бы связь неразрываемой — снять ошибочно выбранную модель стало бы
   * нечем. Оба отказа молчаливые, и оба ловятся здесь.
   */
  it('правка отличает «ключа нет» от «прислали пустое»', () => {
    expect(SQL).toMatch(/v_item \? 'sku_card_id'/);
    expect(SQL).not.toMatch(/coalesce\(v_item->>'sku_card_id'/);
  });

  it('каждая текстовая вставка в пересобранную функцию проверяется', () => {
    /**
     * Приём «pg_get_functiondef + replace» молчалив по построению:
     * не сработавшая замена оставляет функцию ПРЕЖНЕЙ, и миграция выглядит
     * применённой. Правило проекта — проверять каждую вставку.
     */
    const checks = SQL.match(/if v_new = v_src then/g) ?? [];
    expect(checks.length, 'вставок больше, чем проверок').toBeGreaterThanOrEqual(3);
  });
});
