/**
 * ПОДПИСИ КОЛОНОК КАРТОЧКИ МОДЕЛИ — для истории версий.
 *
 * Перечень полей, за которыми следит история, живёт В ТРИГГЕРЕ
 * `erp_sku_card_version`: он перечисляет значимые колонки и складывает их
 * имена в `changed_fields`. Клиент этот список ЧИТАЕТ, а не повторяет —
 * но подписать его обязан, иначе в истории появляется строка
 * «pattern_tech_name», то есть имя колонки вместо названия величины.
 *
 * СТОРОЖ СВЕРЯЕТ ОБЕ СТОРОНЫ (`skuCardFields.test.ts`): колонка, дописанная
 * в триггер и забытая здесь, даёт английское имя на экране — молча, потому
 * что показ работает. Обратное («подпись есть, а колонка не отслеживается»)
 * тоже ловится: это обещание истории, которой не будет.
 */

export const SKU_CARD_FIELD_LABELS: Record<string, string> = {
  name: 'Название',
  code: 'Артикул',
  category: 'Категория',
  description: 'Описание',
  fit: 'Крой',
  pattern_tech_name: 'Название лекал',
  pattern_version: 'Версия лекал',
  status: 'Статус',
  final_package: 'Технический пакет',
  price_min: 'Цена от',
  price_max: 'Цена до',
};

/**
 * Неизвестное имя отдаётся КАК ЕСТЬ, а не отбрасывается: колонка, забытая
 * в подписях, обязана быть видна — пропавшая строка истории читалась бы
 * как «правки не было». Fail-open, то же правило, что у раскладки вложений
 * по папкам.
 */
export function skuCardFieldLabel(field: string): string {
  return SKU_CARD_FIELD_LABELS[field] ?? field;
}
