import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { latestMatching } from './migrations.testutil';

/**
 * Вид вложения обязан существовать И в типе, И в CHECK базы.
 *
 * ЧТО СЛУЧИЛОСЬ 22.08. Правки заказчика завели три новых вида — `print`
 * (макет конкретного нанесения), `label` (файл конкретной бирки), `note`
 * (изображение заметки к заказу). В `ErpAttachmentKind` они попали, в CHECK
 * таблицы — нет. Типы сходились, весь unit-набор был зелёным, а первая же
 * попытка приложить макет отвечала 23514 и роняла СОЗДАНИЕ ЗАКАЗА целиком:
 * вложения вставляет та же транзакция, что и заказ.
 *
 * Нашлось это не тестом, а проверкой на живой базе — то есть случайно.
 * Отсюда сторож: расхождение двух перечислений не должно требовать удачи.
 *
 * ЭТО УЖЕ ТРЕТИЙ СЛУЧАЙ ОДНОГО ЖАНРА. `mixed` у `material_source` завели
 * в одной таблице, а CHECK соседней остался на двух — заказ со смешанными
 * материалами не создавался вообще. `unit` у справочников попал в CHECK
 * и подписи, но не в `KINDS` — вкладки просто не было. Правило записано
 * в CLAUDE.md: «перечисление, расширенное в одной таблице, проверьте
 * во ВСЕХ».
 *
 * ГРАНИЦА ЧЕСТНОСТИ. Тест читает репозиторий, а не базу: он знает только то,
 * что описано миграциями. Но все изменения схемы идут миграциями, и снимок
 * журнала (`APPLIED.json`) сторожит, что репозиторий описывает боевую базу.
 */

const ERP = join(process.cwd(), 'src/erp');

/** Виды из ДЕЙСТВУЮЩЕГО CHECK — последняя миграция, которая его пересоздаёт */
function kindsInCheck(): string[] {
  const sql = latestMatching(
    /add constraint erp_order_attachments_kind_check/,
    'CHECK видов вложения',
  );
  const block = sql.match(
    /add constraint erp_order_attachments_kind_check\s+check \(kind in \(([\s\S]*?)\)\)/,
  )?.[1] ?? '';
  return [...block.matchAll(/'([a-z_]+)'/g)].map((m) => m[1]).sort();
}

/**
 * Виды из клиентского союза `ErpAttachmentKind`.
 *
 * Комментарии снимаются ДО поиска блока, а не после. Объяснение «почему завели
 * вид» содержит те же слова, что и сам вид (обычная ловушка проекта), но здесь
 * важнее другое: конец союза ищется по `;`, и точка с запятой внутри прозы
 * («подрядных этапов бывает несколько; привязка идёт через stage_id») обрывает
 * блок на середине. Сторож тогда не падает, а МОЛЧА проверяет половину союза.
 */
function kindsInType(): string[] {
  const src = readFileSync(join(ERP, 'types.ts'), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/[^\n]*/g, '');
  const block = src.match(
    /export type ErpAttachmentKind =([\s\S]*?);\n/,
  )?.[1] ?? '';
  return [...block.matchAll(/'([a-z_]+)'/g)].map((m) => m[1]).sort();
}

describe('виды вложений: тип и CHECK базы не разошлись', () => {
  it('CHECK и союз перечисляют одно и то же', () => {
    expect(kindsInType()).toEqual(kindsInCheck());
  });

  /**
   * Виды правки 22.08 названы поимённо: общая сверка выше пройдёт и в том
   * случае, если оба перечисления «похудеют» одинаково, а эти три должны
   * существовать — на них держатся макет нанесения, файл бирки и заметки.
   */
  it('виды правки 22.08 на месте', () => {
    for (const kind of ['print', 'label', 'note']) {
      expect(kindsInCheck(), `${kind} нет в CHECK базы`).toContain(kind);
      expect(kindsInType(), `${kind} нет в ErpAttachmentKind`).toContain(kind);
    }
  });
});

/**
 * ОДНА DELETE-ПОЛИТИКА НА ВЛОЖЕНИЯХ — и сторож на неё.
 *
 * ЗАЧЕМ. 21.08 миграция `erp_att_delete_single_policy` намеренно свела три
 * пермиссивные политики в одну: Postgres исполняет ВСЕ пермиссивные политики
 * на каждую удаляемую строку (адвизор `multiple_permissive_policies`).
 * 24.08 миграция `erp_dev_task_files` создала `erp_att_delete_dev` заново,
 * чтобы добавить вид `dev_task`, — решение трёхдневной давности откатилось
 * молча. Ничего не сломалось, права остались верными, и заметил это только
 * адвизор на живой базе 04.09.
 *
 * ХУЖЕ ТОГО, предикаты успели разойтись: `dev_task` был только в воскресшей
 * политике, в сводной его не было. То есть попытка ужесточить удаление
 * dev-файлов правкой сводной политики НИЧЕГО бы не ужесточила — вторая
 * продолжала бы разрешать. Ровно тот случай, о котором правило проекта
 * говорит «две копии правила разошлись бы, обе работая».
 *
 * Сторож смотрит ПОСЛЕДНЮЮ миграцию, трогающую эти политики, и требует
 * от неё двух вещей: снять отдельную политику и перечислить все четыре вида
 * dev-файлов в сводной. Политика автора (`erp_att_delete_own`) — про другое
 * решение (человек убирает СВОЙ неприкреплённый файл) и здесь не участвует.
 */
describe('удаление вложений: одна политика на команду', () => {
  const latest = latestMatching(
    /policy erp_order_attachments_delete on public\.erp_order_attachments/,
    'DELETE-политику вложений',
  );

  it('отдельной политики dev-файлов не остаётся', () => {
    expect(latest).toMatch(/drop policy if exists erp_att_delete_dev/);
    expect(latest).not.toMatch(/create policy erp_att_delete_dev/);
  });

  it('сводная политика знает все четыре вида файлов разработки', () => {
    const create = latest.slice(latest.indexOf('create policy erp_order_attachments_delete'));
    for (const kind of ['dev_pattern', 'dev_passport', 'dev_photo', 'dev_task']) {
      expect(create, `${kind} выпал из сводной политики`).toContain(`'${kind}'`);
    }
  });
});
