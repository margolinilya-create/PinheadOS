/**
 * ПОСАДОЧНАЯ ПО РОЛИ: куда открывается раздел, когда человек пришёл на `/`.
 *
 * ЗАЧЕМ. `/` — «Обзор производства», экран менеджера: «Заказов в работе»,
 * «Готовы к отгрузке», «Загрузка производства». `start_url` PWA — тот же `/`,
 * поэтому рабочий закроя, открывая планшет в начале смены, каждый раз
 * приземлялся на сводку по всей фабрике, где нет ни одной цифры про его цех,
 * и делал один-два лишних тапа: плитка «Очередь» либо ☰ → свой участок.
 *
 * ПРАВИЛО. Роль отвечает на вопрос «где эта смена работает»:
 *
 * | роль                                    | посадочная        |
 * |-----------------------------------------|-------------------|
 * | цеховые (`worker`, `foreman`, участки)  | `/queue/<участок>`|
 * | `storekeeper`                            | `/warehouse`      |
 * | `purchaser`                              | `/purchasing`     |
 * | `technologist`                           | `/experimental`   |
 * | остальные                                | `/` (обзор)       |
 *
 * «Обзор» при этом НЕ отбирается: он остаётся пунктом меню у всех, просто
 * перестаёт быть первым экраном смены. Перенаправление одно на загрузку
 * приложения — открыв «Обзор» руками, человек его и получает.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Права раздела эта функция не выдаёт: она СПРАШИВАЕТ
 * `canOpen`, и целевой экран всё равно гейтится сам (`ErpGuard`). Отправить
 * человека туда, где его встретит «Нет доступа», хуже, чем оставить на обзоре.
 */

import type { EmployeeRole } from '../types';
import { DEPT_BOUND_ROLES } from './permissions';

/** Роли, у которых своя поверхность вместо очереди цеха */
const OWN_SCREEN: Partial<Record<EmployeeRole, string>> = {
  storekeeper: '/warehouse',
  purchaser: '/purchasing',
  technologist: '/experimental',
};

export interface LandingContext {
  /** `canOpenScreen(can, path)` вызывающего — гейт разделов «Операции» */
  canOpen: (path: string) => boolean;
  /**
   * Код своего участка (`utils/myDept.myDeptCode`); пусто — участка нет.
   *
   * До 07.09 здесь стоял `/queue` без кода: экран «Мой цех» сам брал привязку
   * сотрудника. Пункт меню и адрес без кода убраны правками 07.09 (п. 18),
   * и код участка теперь спрашивается СНАРУЖИ — второй раз выводить его тут
   * значило бы завести второе место, где решается, какой участок «свой».
   */
  deptCode?: string;
}

/**
 * Куда вести роль с `/`; `null` — оставить на обзоре.
 *
 * Цеховая роль без известного участка остаётся на обзоре, а не уезжает
 * в очередь несуществующего цеха: заведение сотрудника не закончено, и об этом
 * говорит `DeptBindingNotice` — на обзоре в том числе.
 */
export function landingPathForRole(
  role: EmployeeRole,
  { canOpen, deptCode = '' }: LandingContext,
): string | null {
  const own = OWN_SCREEN[role];
  if (own) return canOpen(own) ? own : null;
  /**
   * Кладовщик и закупщик тоже привязаны к участку (`DEPT_BOUND_ROLES`), но
   * работают не в очереди — поэтому своя поверхность проверяется ПЕРВОЙ.
   */
  if (DEPT_BOUND_ROLES.includes(role)) return deptCode ? `/queue/${deptCode}` : null;
  return null;
}
