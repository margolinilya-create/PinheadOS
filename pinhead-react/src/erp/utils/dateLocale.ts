/**
 * ПОРЯДОК ЧАСТЕЙ ДАТЫ В БРАУЗЕРЕ (правка заказчика 16.09, п. 3).
 *
 * ЧТО ПРОСИТ ДОКУМЕНТ. «Убрать дублирование даты справа и оставить одну
 * компактную строку: „План завершения [07.10.2026]"».
 *
 * ПОЧЕМУ НЕЛЬЗЯ ПРОСТО УДАЛИТЬ ЭХО. Оно появилось не из небрежности:
 * `<input type="date">` показывает дату в формате ЛОКАЛИ БРАУЗЕРА, и при
 * en-US «08/14» читается двояко — и как 8 августа, и как 14 августа.
 * На сроках производства это дороже одной строки под полем, и в шапке
 * `DateField` это записано прямым текстом.
 *
 * ЧТО ЗДЕСЬ РЕШЕНО. Эхо нужно ровно тогда, когда поле САМО показывает дату
 * неоднозначно, то есть месяцем вперёд. Когда браузер пишет день первым
 * (ru-RU: «07.10.2026»), эхо повторяет то же самое теми же цифрами — и вот
 * это и есть «дублирование даты», на которое жалуется документ.
 *
 * Порядок берётся у `Intl.DateTimeFormat`, а НЕ у `navigator.language`:
 * язык интерфейса и формат дат — разные настройки, и совпадают они не всегда.
 * Спрашиваем ровно то, что нужно знать: что стоит первым — день или месяц.
 *
 * FAIL-SAFE В СТОРОНУ ЭХА. Если `Intl` недоступен или ответил непонятным,
 * считаем формат неоднозначным и эхо ОСТАВЛЯЕМ. Лишняя строка под полем —
 * это шум; перепутанный месяц — это перенесённый срок заказа.
 */

/** Показывает ли браузер дату днём вперёд («07.10.2026»), а не месяцем («10/07/2026») */
export function browserShowsDayFirst(): boolean {
  try {
    const parts = new Intl.DateTimeFormat(undefined, {
      day: '2-digit', month: '2-digit', year: 'numeric',
    }).formatToParts(new Date(Date.UTC(2026, 9, 7)));

    const order = parts
      .filter((p) => p.type === 'day' || p.type === 'month')
      .map((p) => p.type);

    // Обе части обязаны найтись: «нашлась одна» — это неизвестный формат,
    // и решать по нему нельзя
    if (order.length < 2) return false;
    return order[0] === 'day';
  } catch {
    return false;
  }
}

/**
 * Нужно ли рисовать эхо даты под полем.
 *
 * `auto` — по формату браузера; `always`/`never` оставлены для мест, где
 * решение принимает вызывающий (печатная форма, компактная строка фильтра).
 */
export type DateEchoMode = 'auto' | 'always' | 'never';

export function shouldShowDateEcho(mode: DateEchoMode = 'auto'): boolean {
  if (mode === 'always') return true;
  if (mode === 'never') return false;
  return !browserShowsDayFirst();
}
