import type { ErpMaterial, MaterialStatus } from '../types';

/**
 * Статус «Заказано» СТАВИТСЯ ПО ФАКТУ, а не выбирается из списка
 * (правка заказчика 24.08, п. 1: «статус „Заказано" должен появляться только
 * после фактического оформления заказа поставщику»).
 *
 * ЗАЧЕМ. Селект статуса стоял рядом с полями «Количество к заказу» и «Дата
 * заказа» и ничего о них не знал: закупщик мог объявить материал заказанным,
 * не заполнив ни то ни другое, — и «Заказано» переставало что-либо значить.
 * Ровно тем же соображением сводка карточки считает оформленные позиции
 * не по статусу, а по факту (`supplyMaterialSummary`): расхождение двух
 * ответов на один вопрос и было причиной, по которой счётчик писали мимо.
 *
 * ФАКТ ЗДЕСЬ — ЭТО ДВА ПОЛЯ СРАЗУ: сколько заказано и когда. Одно количество
 * без даты — это ещё намерение (столбец так и называется «к заказу»), одна
 * дата без количества — описка.
 *
 * Обратно статус НЕ откатывается. Стёртая дата не отменяет разговора
 * с поставщиком; если оформление сорвалось, закупщик выбирает «Не заказано»
 * руками — этот пункт из списка не убран.
 */
export function autoOrderedStatus(
  next: Pick<ErpMaterial, 'source' | 'status' | 'qty_ordered' | 'ordered_on'>,
): MaterialStatus | null {
  // Оформляют у поставщика только закупаемое: у склада и давальческого
  // «заказать» нечего, и статусы там свои («Доступен со склада», «Пришло»)
  if (next.source !== 'purchase') return null;
  /**
   * Только из «Не заказано». Материал уже в пути или принят — движение вперёд
   * по своей шкале, и вернуть его в «Заказано» значило бы потерять приёмку.
   * Проверяется состояние ПОСЛЕ патча: выбрав статус руками, человек тем самым
   * выходит из `pending`, и подстановка его не перебивает.
   */
  if (next.status !== 'pending') return null;
  if (!next.qty_ordered || next.qty_ordered <= 0) return null;
  if (!next.ordered_on) return null;
  return 'ordered';
}

/**
 * СТАТУСЫ, КОТОРЫЕ ЗАКУПЩИК НЕ СТАВИТ (правка заказчика 12.09, п. 8).
 *
 * «Статус „Пришло" полностью убрать из закупки… Приход материала фактически
 * должен фиксироваться не закупкой, а складом».
 *
 * УБИРАЕТСЯ ВВОД, А НЕ ЗНАЧЕНИЕ, и это не буквоедство. `received` — несущий
 * статус приёмки: его ставит `erp_material_accept` одной транзакцией
 * с журналом, на нём держатся материальный гейт цехов
 * (`routes.isMaterialPending` — материал годен только как `received`
 * с приёмкой), закрытие складской задачи и вкладка «Пришло» в самой закупке.
 * Удали значение — материал перестанет считаться годным НИКОГДА, и встанет
 * не закупка, а всё производство.
 *
 * Поэтому закупщик просто теряет возможность его ВЫБРАТЬ. Тем же движением
 * уходит путь, которым на бое появлялись позиции «пришло» без приёмки:
 * закупщик отмечал приход сам, склад ничего не пересчитывал, а `supply`
 * показывал их отдельным вердиктом `not_accepted` («Ждёт приёмки складом»).
 *
 * `partial` здесь по той же причине: «Частично» — тоже вердикт приёмки,
 * его выводят из чисел журнала, а не выбирают рядом с ними.
 */
export const WAREHOUSE_OWNED_STATUSES: readonly MaterialStatus[] = ['received', 'partial'];

/** Может ли закупщик поставить статус руками */
export function isPurchaserChoosableStatus(status: MaterialStatus): boolean {
  return !WAREHOUSE_OWNED_STATUSES.includes(status);
}
