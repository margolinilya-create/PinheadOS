/**
 * Ключ ячейки размерной сетки «цвет × размер» — ОДИН на проект (обзор 26.09, п. 19).
 *
 * Разделитель — символ NUL: он не встречается ни в названии цвета, ни
 * в размере, и склейка «цвет + размер» не даёт ложных совпадений
 * («Бел» + «ый L» против «Белый» + «L»). Три модуля держали по своей копии,
 * и в каждой NUL стоял в исходнике СЫРЫМ БАЙТОМ, а не `\u0000`: grep считал
 * эти файлы бинарными и молча пропускал их при поиске по `src/`.
 */

export const CELL_SEP = '\u0000';

/** Ключ ячейки; пустой цвет — как передан (нормализацию делает вызывающий) */
export function cellKey(color: string, size: string): string {
  return `${color}${CELL_SEP}${size}`;
}
