/**
 * Состояние переподключения канала realtime — вынесено из `realtimeSlice`
 * (сессия 72, 28.09): у слайса потолок размера, а у этих трёх переменных
 * своя жизнь, отдельная от применения событий.
 *
 * ПОЧЕМУ ЗДЕСЬ ЕСТЬ «МЕТКА ЖИВОГО КАНАЛА». Обработчик статуса привязан
 * к КАНАЛУ, и у канала, который мы закрыли сами при переподключении, он
 * продолжает получать статусы: `CLOSED` от нашей же отписки, запоздалый
 * `CHANNEL_ERROR`, а иногда и `SUBSCRIBED`. До 28.09 эти статусы читались
 * как статусы живого канала — `CLOSED` от собственной отписки ставил новый
 * таймер переподключения, тот закрывал уже НОВЫЙ канал и заводил следующий,
 * и так по кругу: каждый круг оставлял ещё один живой канал со всеми
 * подписками, ещё пару слушателей окна и ещё один полный `loadAll`.
 * За сутки открытая вкладка цеха накапливала сотни каналов (семь-восемь
 * тысяч рукопожатий WebSocket в сутки на бою), а на пробуждении выпускала
 * всплеск в сотни одинаковых запросов списка заказов — снаружи это
 * выглядело как «ничего не загружается».
 *
 * Живой канал ровно один; его статусы — единственные, что мы слушаем.
 */

/**
 * Шаги паузы перед пересозданием канала. Растут до минуты и не дольше:
 * цех смотрит в очередь постоянно, и получасовое ожидание переподключения
 * для него то же самое, что его отсутствие.
 */
export const RECONNECT_STEPS_MS = [1000, 2000, 5000, 10000, 30000, 60000];

let timer: ReturnType<typeof setTimeout> | null = null;
let attempt = 0;
let live: symbol | null = null;

/** Объявить канал живым (или снять метку при отписке — `null`) */
export function markLive(token: symbol | null): void {
  live = token;
}

/** Наш ли это канал: статусы всех прочих — эхо прошлого, их игнорируем */
export function isLive(token: symbol): boolean {
  return live === token;
}

/** Снять ожидание переподключения; счёт попыток — с начала */
export function clearReconnect(): void {
  if (timer) clearTimeout(timer);
  timer = null;
  attempt = 0;
}

/**
 * Запланировать пересоздание канала, если оно ещё не запланировано.
 * `supabase-js` переподписывает канал и сам (`rejoinTimer`): дождавшееся
 * `SUBSCRIBED` снимает таймер через `clearReconnect`, и пересоздание —
 * запасной ход на случай, когда библиотека застряла.
 */
export function scheduleReconnect(fn: () => void): void {
  if (timer) return;
  const delay = RECONNECT_STEPS_MS[Math.min(attempt, RECONNECT_STEPS_MS.length - 1)];
  attempt += 1;
  timer = setTimeout(() => {
    timer = null;
    fn();
  }, delay);
}
