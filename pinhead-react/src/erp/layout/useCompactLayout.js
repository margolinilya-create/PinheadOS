import { useMediaQuery } from '../../hooks/useMediaQuery';

/**
 * Компактная (цеховая) раскладка: карточки вместо таблиц, сайдбар оверлеем.
 *
 * Раньше условие было `(max-width: 760px)` и повторялось магической строкой в
 * четырёх местах (`DepartmentQueue`, `OrdersScreen`, `ProductionBoard`,
 * `ErpSkeletons`). Число выбрано под телефон, а основное устройство цеха —
 * Android-планшет: в портрете это 768–800 CSS-px, то есть **760 < 768**, и
 * тач-оптимизированная `QueueCard` (крупные кнопки, полоса статуса, превью)
 * не показывалась НИ НА ОДНОМ реальном цеховом устройстве. Хуже: до 760px
 * сайдбар оставался постоянной колонкой 236px, и на 768px под сетку строки
 * очереди оставалось ~456px при нужных ~710px — рабочая область уезжала вбок,
 * а колонка «Действия» оказывалась за краем экрана.
 *
 * Правило теперь из двух частей:
 *  - `max-width: 1024px` — все планшеты в обеих ориентациях (768×1024 и 1024×768);
 *  - `pointer: coarse` — любое тач-устройство независимо от ширины: цеховой
 *    киоск с большим экраном всё равно работают пальцем, и таблица там неуместна.
 *
 * Скелетоны обязаны использовать тот же хук: иначе при загрузке рисуется одна
 * разметка, а после загрузки другая — это не скелетон, а мигание чужой вёрсткой.
 */
export const COMPACT_LAYOUT_QUERY = '(max-width: 1024px), (pointer: coarse)';

export function useCompactLayout() {
  return useMediaQuery(COMPACT_LAYOUT_QUERY);
}
