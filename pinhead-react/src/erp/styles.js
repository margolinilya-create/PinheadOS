import base from './erp.module.css';
import screens from './screens.module.css';

/**
 * Стили ЭКРАНА раздела «Производство» — один объект из двух CSS-модулей.
 *
 * ЗАЧЕМ. CSS раздела разделён надвое: `erp.module.css` нужен и оболочке,
 * и экранам, а `screens.module.css` — только экранам, и потому едет их
 * чанком, а не критическим путём. Но разложить классы по двум переменным
 * в разметке нельзя: в разделе два десятка обращений вида
 * `styles[STAGE_CHIP_CLASS[status]]`, `styles[k.cls]`, `styles[`planCard_${s}`]`.
 * Статически такие имена не видны — значит, при разделении переменных часть
 * из них молча стала бы `undefined`, то есть `className={undefined}`:
 * элемент рисуется, ничего не падает, меняется ТОЛЬКО ВИД. Ровно тот класс
 * ошибок, который в этом же заходе нашёлся четырьмя несуществующими классами
 * (`stackTight` и соседи).
 *
 * Поэтому экраны импортируют агрегатор и продолжают писать `styles.X` —
 * как писали до разделения. Слияние происходит один раз при загрузке модуля.
 *
 * ОБОЛОЧКА ЭТОТ ФАЙЛ НЕ ИМПОРТИРУЕТ: `layout/*` и общие компоненты берут
 * `erp.module.css` напрямую, иначе `screens.module.css` вернулся бы
 * в критический путь и разделение потеряло бы смысл. Сторож —
 * `stylesResolve.test.ts`.
 *
 * Имена классов уникальны в пределах исходного файла, из которого оба модуля
 * и нарезаны, поэтому пересечений при слиянии нет по построению.
 */
/*
 * Слияние через Proxy, а НЕ `{ ...base, ...screens }`.
 *
 * Спред казался очевидным и работал в браузере — но в Vitest CSS-модуль
 * подставляется прокси-заглушкой без перечислимых ключей, и спред давал
 * ПУСТОЙ объект: все `styles.X` в тестах становились `undefined`. Поймал
 * это ровно один тест (`PurchaseRowCard` ищет подписи по имени класса),
 * остальные и не заметили бы — className там просто не проверяют.
 *
 * Здесь обращение проксируется, поэтому работают обе среды: и настоящий
 * объект сборки, и заглушка тестов.
 */
export default new Proxy({}, {
  get: (_target, key) => base[key] ?? screens[key],
  has: (_target, key) => key in base || key in screens,
});
