import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

/**
 * Что обязано остаться в ГЛОБАЛЬНОМ CSS.
 *
 * ЗАЧЕМ. CSS разделов уезжает к их потребителям — это записанное правило
 * и уже дважды сделанная работа (шесть файлов Order Studio 22.08,
 * `forms-buttons.css` 23.08). Приём выгодный и потому соблазнительный:
 * «раздел ERP не использует из файла ни одного КЛАССА» выглядит достаточным
 * основанием вынести файл целиком.
 *
 * Оно недостаточно, и ровно на `forms-buttons.css` это видно втройне:
 *
 *  1. ЭЛЕМЕНТНЫЕ селекторы классов не имеют. `input[type="text"] { width: 100% }`
 *     задаёт ширину всем полям ERP — свой `.input` в `erp.module.css` её
 *     не объявляет вовсе. Уехал бы файл — поля раздела съёжились бы
 *     до авторазмера, и ни один функциональный тест этого не увидел бы.
 *  2. `:focus-visible` — доступность ВСЕГО приложения. В чанке раздела
 *     за выключенным флагом её просто не стало бы. Заметно только
 *     с клавиатуры, то есть не заметно.
 *  3. Экраны входа статичны (правило проекта: пустой «Загрузка…» вместо
 *     формы запрещён), поэтому их кнопки, импортированные из них же,
 *     приехали бы в тот же входной чанк — экономии ноль при полном риске.
 *
 * Тест разворачивает `@import` в `styles/index.css` и проверяет, что эти
 * правила действительно доезжают до всех. Он не про вес — про то, что́ вынос
 * ломает молча.
 */

const INDEX = join(__dirname, 'index.css');

/** Комментарии снимаем ДО поиска: объяснение «почему это здесь» содержит те же слова */
function withoutComments(css: string): string {
  return css.replace(/\/\*[\s\S]*?\*\//g, ' ');
}

/**
 * Собрать глобальный CSS так, как его собирает сборщик: с разворотом @import.
 *
 * Комментарии снимаются ПЕРЕД поиском импортов, и это не педантизм: первая
 * версия теста искала `@import` в сыром тексте и разворачивала ЗАКОММЕНТИРОВАННУЮ
 * строку тоже. То есть сторож оставался зелёным ровно на той правке, которую
 * он поставлен ловить, — проверено выключением импорта.
 */
function globalCss(entry = INDEX, seen = new Set<string>()): string {
  const path = resolve(entry);
  if (seen.has(path)) return '';
  seen.add(path);
  const src = withoutComments(readFileSync(path, 'utf8'));
  let out = src;
  for (const m of src.matchAll(/@import\s+['"](.+?)['"]\s*;/g)) {
    out += `\n${globalCss(join(dirname(path), m[1]), seen)}`;
  }
  return out;
}

describe('глобальный CSS', () => {
  const css = globalCss();

  /*
   * Ищем ОБЪЯВЛЕНИЯ в начале строки, а не подстроки. `utils.css` перечисляет
   * те же селекторы в защитных медиазапросах (`html input[type="text"]`,
   * `html .btn-accent`), и проверка подстрокой оставалась зелёной без
   * `forms-base.css` вовсе — то есть сторожила бы пустоту. Проверено
   * выключением импорта: должны падать все три.
   */
  it('задаёт базовый вид полей — ERP берёт ширину отсюда', () => {
    const rule = /^input\[type="text"\],[\s\S]*?\{([\s\S]*?)\}/m.exec(css);
    expect(rule, 'правила «базовое поле» больше нет в глобальном CSS').toBeTruthy();
    expect(rule![1], 'без width:100% все поля ERP станут авторазмерными')
      .toMatch(/width:\s*100%/);
  });

  it('объявляет кольца фокуса для всего приложения', () => {
    expect(css).toMatch(/^:focus-visible\s*\{/m);
  });

  it('несёт кнопки экранов входа — они статичны и своего чанка не имеют', () => {
    // AuthScreen / JoinScreen / NewPasswordScreen лежат во входном чанке
    expect(css).toMatch(/^\.btn-accent\s*\{/m);
    expect(css).toMatch(/^\.btn-secondary\s*\{/m);
  });

  /**
   * Обратная половина: CSS раздела за выключенным флагом глобальным быть
   * не должен. Проверяем по классам, которых нет нигде, кроме визарда.
   */
  it('не тянет CSS Order Studio', () => {
    for (const cls of ['.wizard', '.sku-table', '.kanban-page', '.label-configurator',
      '.items-tray', '.summary-grid']) {
      expect(css, `${cls} обязан жить в чанке своего раздела`).not.toContain(cls);
    }
  });
});
