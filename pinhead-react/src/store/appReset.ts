/**
 * Реестр сбросов состояния при выходе и потере сессии.
 *
 * Зачем понадобился. `useAuthStore` вызывал `resetErpStore()` прямым импортом,
 * и это тянуло ВЕСЬ ERP-стор — четырнадцать слайсов — в входной чанк, который
 * грузит каждый, включая тех, кто открыл только Order Studio. Бюджет входа
 * (`scripts/bundle-budget.mjs`) на этом и уткнулся в потолок: каждая правка
 * любого слайса росла там, где её быть не должно.
 *
 * Зависимость перевёрнута: сторы САМИ регистрируют свой сброс, когда их модуль
 * загружается. Выход зовёт зарегистрированные. Если ERP в этой сессии не
 * открывали, сбрасывать нечего — и это не обходной путь, а точное описание
 * положения дел.
 *
 * Никаких «сначала зарегистрируйте»: реестр пуст по умолчанию, вызов пустого
 * реестра — no-op. Регистрация идёт на уровне модуля стора, то есть ровно
 * тогда, когда состояние вообще может появиться.
 */

type ResetFn = () => void;

const resets = new Set<ResetFn>();

/** Зарегистрировать сброс стора. Повторная регистрация той же функции — no-op */
export function registerAppReset(fn: ResetFn): void {
  resets.add(fn);
}

/**
 * Сбросить всё зарегистрированное. Ошибка одного сброса не должна отменять
 * остальные: выход обязан довести чистку до конца — на общем цеховом планшете
 * недочищенный стор означает чужие заказы у следующего работника.
 */
export function runAppResets(): void {
  for (const fn of resets) {
    try {
      fn();
    } catch (err) {
      console.error('[appReset] сброс не выполнился', err);
    }
  }
}

/** Только для тестов: очистить реестр между прогонами */
export function _clearAppResets(): void {
  resets.clear();
}
