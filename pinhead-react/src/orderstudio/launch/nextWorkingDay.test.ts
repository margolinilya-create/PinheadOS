import { describe, it, expect } from 'vitest';
import { isoLocal, nextWorkingDay } from './nextWorkingDay';

/** Тесты идут в `TZ=Europe/Moscow` (`setupTests.js`): граница суток — по Москве */
describe('nextWorkingDay', () => {
  it.each([
    ['понедельник → вторник', '2026-10-19T09:00:00+03:00', '2026-10-20'],
    ['четверг → пятница', '2026-10-22T18:00:00+03:00', '2026-10-23'],
    ['пятница → понедельник', '2026-10-23T10:00:00+03:00', '2026-10-26'],
    ['суббота → понедельник', '2026-10-24T10:00:00+03:00', '2026-10-26'],
    ['воскресенье → понедельник', '2026-10-25T23:59:00+03:00', '2026-10-26'],
    ['23:30 UTC пятницы — по Москве уже суббота → понедельник', '2026-10-23T23:30:00Z', '2026-10-26'],
    ['конец месяца', '2026-10-30T12:00:00+03:00', '2026-11-02'],
  ])('%s', (_name, now, expected) => {
    expect(nextWorkingDay(new Date(now))).toBe(expected);
  });

  it('isoLocal — дата по местному времени, а не по UTC', () => {
    expect(isoLocal(new Date('2026-10-23T22:30:00Z'))).toBe('2026-10-24');
  });
});
