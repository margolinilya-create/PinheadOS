import { lazy, Suspense } from 'react';

/**
 * Agentation (https://www.agentation.com) — визуальная обратная связь агенту.
 *
 * Человек кликает по элементу прямо в работающем интерфейсе, пишет замечание,
 * и оно уезжает в ЛОКАЛЬНЫЙ MCP-сервер (`.mcp.json` → `agentation-mcp server`,
 * порт 4747), откуда его читает Claude — без копирования в чат руками.
 * Смонтирован ОДИН раз, в `GlobalHosts` (`App.jsx`): замечание одинаково нужно
 * и в «Производстве», и в Order Studio, и на экранах входа, а вторая точка
 * монтирования означала бы два условия показа, которые однажды разъедутся.
 *
 * ТОЛЬКО DEV, И ЭТО НЕ ОСТОРОЖНОСТЬ, А УСТРАНЕНИЕ ИЗВЕСТНОГО ДЕФЕКТА.
 * До этой правки виджет висел в `OrderStudioApp` под гейтом `isRealAdmin`,
 * без единой проверки режима сборки, а пакет стоял в `dependencies` — то есть
 * 42 кБ gzip инструмента разработки уезжали в прод и скачивались каждым
 * админом. Это findings аудита 29.07 (`docs/2026-07-29-full-audit.md`,
 * раздел D5) — прямым текстом: «гарда `import.meta.env.DEV` нет, комментарий
 * „tree-shakes out of prod“ не соответствует коду». Повторить это в оболочке
 * ERP было бы хуже вдвое: её грузят ВСЕ и всегда, включая цеховой планшет
 * по слабому Wi-Fi, ради которого четырежды снижался бюджет критического пути.
 * Того же требует и сам поставщик: «The NODE_ENV check ensures it only loads
 * in development» (agentation.com/install).
 *
 * ПОЧЕМУ `lazy()` СТОИТ ЗА ТЕРНАРНИКОМ, А НЕ В ТЕЛЕ КОМПОНЕНТА.
 * `import.meta.env.DEV` Vite подставляет литералом, поэтому в прод-сборке
 * `ENABLED` сворачивается в `false`, тернарник — в `null`, а вместе с мёртвой
 * веткой выбрасывается и `import('agentation')`: чанка в `dist` не остаётся
 * вовсе (сторожит `scripts/bundle-budget.mjs`). Оставь мы `lazy(() =>
 * import('agentation'))` безусловным вызовом на уровне модуля — Rollup
 * не вправе счесть вызов чистым, и чанк уехал бы в сборку, просто никем
 * не скачиваемый. Тот же приём, что у `lib/configError`: в правильной сборке
 * ветка не стоит ничего, потому что её нет.
 *
 * `VITE_AGENTATION=0` — выключатель для e2e (`playwright.config.ts`). Тулбар
 * рисуется поверх страницы, и в прогоне против dev-сервера он попадал бы
 * и в визуальные эталоны продукта, и под сканер доступности: чужая панель
 * стала бы частью снимка, а её следующая версия молча перекрасила бы эталон,
 * к продукту отношения не имеющий.
 */
const ENABLED = import.meta.env.DEV && import.meta.env.VITE_AGENTATION !== '0';

/**
 * Адрес MCP-сервера. Без него виджет умеет ровно половину — сложить разметку
 * в буфер обмена, — и замечание до агента не доходит НИКОГДА: ровно тот случай,
 * когда половина сделанного выглядит как сделанное целиком. Порт 4747 — тот же,
 * что поднимает `agentation-mcp server` из `.mcp.json`; переопределяется
 * `VITE_AGENTATION_ENDPOINT`, если сервер запущен на другом порту (`--port`).
 */
const ENDPOINT = import.meta.env.VITE_AGENTATION_ENDPOINT || 'http://localhost:4747';

/**
 * Отказ загрузки — `null`, а не бросок. Пакет лежит в `devDependencies`,
 * и установка без них (или оборванная сеть у dev-сервера) уронила бы чанк
 * в ближайший ErrorBoundary, то есть приложение целиком: инструмент
 * не имеет права ломать то, что помогает чинить.
 */
const Widget = ENABLED
  ? lazy(() => import('agentation')
    .then((m) => ({ default: m.Agentation }))
    .catch((err) => {
      console.warn('[agentation] виджет не загрузился, работаем без него', err);
      return { default: () => null };
    }))
  : null;

export default function DevAnnotations() {
  if (!Widget) return null;
  return (
    <Suspense fallback={null}>
      <Widget
        endpoint={ENDPOINT}
        onSessionCreated={(sessionId) => {
          // Идентификатор сессии — то, чем агент находит замечания
          // (`agentation_get_pending`). Печатаем, чтобы его можно было
          // передать руками, если автоподхват почему-то не сработал.
          console.info('[agentation] сессия:', sessionId);
        }}
      />
    </Suspense>
  );
}
