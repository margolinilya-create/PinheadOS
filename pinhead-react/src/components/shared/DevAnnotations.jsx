import { lazy, Suspense } from 'react';
import { useAuthStore } from '../../store/useAuthStore';

/**
 * Agentation (https://www.agentation.com) — визуальная обратная связь агенту.
 *
 * Человек кликает по элементу прямо в работающем интерфейсе, пишет замечание,
 * и оно уезжает в ЛОКАЛЬНЫЙ MCP-сервер (`.mcp.json` → `agentation-mcp server`,
 * порт 4747), откуда его читает Claude — без копирования в чат руками.
 * Смонтирован ОДИН раз, в `GlobalHosts` (`App.jsx`): замечание одинаково нужно
 * и в «Производстве», и в Order Studio, и на экранах входа, а вторая точка
 * монтирования означала бы два условия показа, которые однажды разъедутся.
 *
 * РАБОТАЕТ И В ПРОДЕ — решение владельца от 03.09. Прежняя редакция стояла
 * за `import.meta.env.DEV` и в прод-сборку не попадала вовсе; заказчику нужен
 * тулбар на боевом стенде, поэтому гейт снят. Цена названа вслух и снижена
 * двумя решениями ниже — она в весе и в том, что синка с боевой страницы
 * не будет.
 */

/** Общий выключатель: `VITE_AGENTATION=0` гасит виджет совсем (им пользуется e2e) */
const ENABLED = import.meta.env.VITE_AGENTATION !== '0';

const IS_DEV = import.meta.env.DEV;

/**
 * КОМУ ВИДНО В ПРОДЕ. Инструмент нужен тому, кто ведёт разработку продукта,
 * а не всей фабрике: рабочий цеха аннотаций не пишет, но за чанк платил бы
 * трафиком — на планшете по цеховому Wi-Fi, ради которого четырежды снижался
 * бюджет критического пути. Ровно этот же список стоял у прежнего монтирования
 * в `OrderStudioApp` (`isRealAdmin`), то есть поведение продукта здесь
 * не расширяется, а восстанавливается — просто теперь на обоих разделах.
 * В dev показываем всем: там за экраном разработчик, а роль может быть любой
 * (в том числе подменённой ради проверки цехового вида).
 *
 * Роль берётся НАСТОЯЩАЯ (`user.role`), а не `previewRole`: превью роли —
 * это способ посмотреть чужой экран, и терять при этом свой инструмент
 * бессмысленно.
 */
const PROD_ROLES = ['admin', 'director'];

/**
 * АДРЕС MCP-СЕРВЕРА ПЕРЕДАЁТСЯ ТОЛЬКО ТУДА, ГДЕ ОН ДОСТИЖИМ.
 *
 * Сервер локальный — он живёт на машине разработчика, а не рядом с сайтом.
 * С боевой страницы `https://pinhead-os.vercel.app` запрос на
 * `http://localhost:4747` не пройдёт: в `connect-src` (vercel.json) этого
 * адреса нет, да и localhost у зрителя — не та машина, где поднят сервер.
 * Передай мы адрес всё равно — каждый админ получил бы висящий опрос
 * недостижимого хоста, ошибки в консоли и поток CSP-репортов, то есть
 * поломку вместо функции. Без адреса виджет работает вторым своим способом:
 * складывает разметку замечаний в буфер обмена, и это ровно то, что на боевом
 * стенде и возможно.
 *
 * `VITE_AGENTATION_ENDPOINT` — осознанное исключение: если сервер когда-нибудь
 * будет доступен по сети, адрес задаётся на сборке, и синк включится и в проде.
 */
const ENDPOINT = import.meta.env.VITE_AGENTATION_ENDPOINT
  || (IS_DEV ? 'http://localhost:4747' : '');

/**
 * Отказ загрузки — `null`, а не бросок: чанк виджета грузится по сети уже
 * после первой отрисовки, и его неудача (обрыв связи, устаревшая вкладка
 * после выкатки) не имеет права уронить приложение через ErrorBoundary.
 * Инструмент не ломает то, что помогает чинить.
 */
const Widget = ENABLED
  ? lazy(() => import('agentation')
    .then((m) => ({ default: m.Agentation }))
    .catch((err) => {
      console.warn('[agentation] виджет не загрузился, работаем без него', err);
      return { default: () => null };
    }))
  : null;

export default function DevAnnotations() {
  const role = useAuthStore((s) => s.user?.role);

  if (!Widget) return null;
  if (!IS_DEV && !PROD_ROLES.includes(role)) return null;

  return (
    <Suspense fallback={null}>
      <Widget
        // `undefined`, а не пустая строка: пустую виджет счёл бы адресом
        endpoint={ENDPOINT || undefined}
        onSessionCreated={(sessionId) => {
          // Идентификатор сессии — то, чем агент находит замечания
          // (`agentation_get_pending`). Печатаем, чтобы его можно было
          // передать руками, если автоподхват почему-то не сработал.
          console.info('[agentation] сессия:', sessionId);
        }}
      />
    </Suspense>
  );
}
