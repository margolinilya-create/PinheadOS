/**
 * Сбой ДО ответа сервера читается как обычная ошибка ответа — правило ОБОИХ
 * разделов.
 *
 * `supabase-js` возвращает `error`, когда сервер ответил, и БРОСАЕТ, когда
 * ответа не было: нет сети, оборвалось соединение, CORS, клиент не настроен.
 * Проверять только `error` недостаточно, и последствия у каждого экрана свои
 * и одинаково тупиковые: флаг загрузки не снимается, оптимистичная правка
 * не откатывается, а необработанное отклонение промиса всплывает глобальным
 * обработчиком сырым «Load failed» из WebKit.
 *
 * ПОЧЕМУ ЖИВЁТ В `lib/`, А НЕ В `erp/store/shared`. Там оно и появилось, и
 * там же осталось бы, если бы дефект был только в ERP. Но ревизия 25.08
 * нашла тот же класс отказа в сторе Order Studio (`useOrdersStore`):
 * `saveOrder`, `updateOrder`, `patchOrderData` и `updateStatus` проверяли
 * один `error`. Копия обёртки рядом означала бы два правила с одним смыслом,
 * а импорт `erp/store/*` из общего стора запрещён отдельно — он тянет
 * доменный чанк во входной.
 *
 * Модуль-лист: зависимость ровно одна, и она уже во входном чанке.
 */

import { networkFailureMessage } from '../utils/i18n';

/** Ответ, который вернёт `netQuery` — тот же вид, что у supabase-js */
export type NetResult<T> = { data: T | null; error: { message: string } | null };

/**
 * Обёртка ничего не решает за вызывающего: она превращает бросок в такой же
 * `{ data: null, error }`, какой пришёл бы от сервера, и дальше работает уже
 * написанная ветка `if (error) …` — с сообщением, откатом и снятием флагов.
 */
export async function netQuery<T>(
  run: () => PromiseLike<{ data: T; error: { message: string } | null }>,
): Promise<NetResult<T>> {
  try {
    return await run();
  } catch (e) {
    return { data: null, error: { message: networkFailureMessage(e) } };
  }
}
