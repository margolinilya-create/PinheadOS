import { confirm } from '../store/useConfirmStore';

/**
 * «Вышло обновление» — вкладка, открытая сутками.
 *
 * ЗАЧЕМ. Планшет в цеху не закрывают: вкладку открыли утром в понедельник
 * и работают. Выкатка меняет имена чанков, файлы прошлого деплоя по своим
 * адресам исчезают, и первый же переход на ленивый экран падает — человек
 * нажал «Склад» и получил ошибку на ровном месте.
 *
 * Раньше это выглядело как «⚠ Что-то пошло не так» (или сырое «Failed to fetch
 * dynamically imported module» тостом): выход был — перезагрузка его и лечит, —
 * но текст описывает внутренности браузера, а не положение дел. В цеху это
 * читается как «программа сломалась», то есть повод звать мастера.
 *
 * ЧТО ИМЕННО ЛОВИМ. У браузеров три разные формулировки одного события, плюс
 * четвёртая — наследие поры, когда отсутствующий файл отдавал 200 с HTML
 * (SPA-rewrite ловил `/assets/*`; исправлено в `vercel.json` тем же заходом).
 * Она остаётся в списке: вкладки, открытые ДО той выкладки, при следующем
 * переходе получат ровно её.
 *
 * ПОЧЕМУ НЕ ПЕРЕЗАГРУЖАЕМ САМИ. Планшет — устройство ВВОДА: в этот момент
 * в соседней форме может быть набран отчёт по этапу или количество в приёмке.
 * Молчаливый `location.reload()` съел бы набранное и выглядел бы как
 * самопроизвольный сброс — дефект хуже того, который лечим. Поэтому спрашиваем
 * тем же диалогом, которым проект спрашивает про остальные необратимые
 * действия, и перезагружаем только по согласию.
 */
const CHUNK_ERROR_PATTERNS = [
  // Chromium
  'failed to fetch dynamically imported module',
  // Firefox
  'error loading dynamically imported module',
  // Safari / WebKit
  'importing a module script failed',
  // Ответ HTML вместо модуля — см. комментарий выше
  'expected a javascript module script',
  // Имя ошибки у сборщиков с runtime-загрузчиком
  'chunkloaderror',
];

/**
 * Похоже ли на «файла больше нет», а не на настоящую поломку.
 *
 * ОТРИЦАТЕЛЬНАЯ ПОЛОВИНА ВАЖНЕЕ ПОЛОЖИТЕЛЬНОЙ. Если экран упал уже ПОСЛЕ
 * загрузки — `TypeError`, отказ прав, обрыв связи, — «обновите страницу»
 * вредный совет: перезагрузка не поможет, а человек потеряет набранное
 * и пойдёт по кругу. Поэтому смотрим только на формулировки САМОЙ ЗАГРУЗКИ
 * модуля, и у теста есть отрицательные примеры.
 */
export function isChunkLoadError(error: unknown): boolean {
  if (!error) return false;
  const err = error as { message?: unknown; name?: unknown };
  const text = `${String(err.name ?? '')} ${String(err.message ?? error)}`.toLowerCase();
  return CHUNK_ERROR_PATTERNS.some((p) => text.includes(p));
}

/** Спрашиваем один раз: повторные отказы за ту же жизнь вкладки молчат */
let asked = false;

/** Для тестов: вернуть модуль в исходное состояние */
export function resetUpdatePrompt(): void {
  asked = false;
}

export const UPDATE_TITLE = 'Вышло обновление приложения';
export const UPDATE_MESSAGE = 'Эта вкладка открыта со старой версией, и часть '
  + 'экранов больше не загрузится. Обновите страницу — несохранённые данные '
  + 'в открытых формах при этом пропадут.';

/**
 * Обработка ошибки загрузки чанка в одном месте.
 *
 * @returns true, если ошибка распознана как «вышло обновление» и обработана —
 *          значит показывать сырое сообщение поверх уже не нужно.
 */
export function handlePossibleUpdate(
  error: unknown,
  reload: () => void = () => window.location.reload(),
): boolean {
  if (!isChunkLoadError(error)) return false;
  if (asked) return true;
  asked = true;
  void confirm({
    title: UPDATE_TITLE,
    message: UPDATE_MESSAGE,
    confirmLabel: 'Обновить',
    cancelLabel: 'Позже',
  }).then((ok) => {
    if (ok) reload();
    else asked = false; // отказались — при следующем отказе экрана спросим снова
  });
  return true;
}
