import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * E2E НЕ ЗАВИСИТ ОТ ФАЙЛА, КОТОРОГО НЕТ В ГИТЕ.
 *
 * ЧТО ЛОВИТСЯ. `lib/supabase.ts` проверяет `VITE_SUPABASE_URL` и
 * `VITE_SUPABASE_ANON_KEY` НА УРОВНЕ МОДУЛЯ — до React. Без них приложение
 * не стартует, Playwright видит пустой `<div id="root">`, и падает ВЕСЬ
 * прогон: каждый локатор отвечает «element(s) not found». Отказ выглядит
 * как тринадцать сломанных спек, а не как «нет настройки»; в проекте это
 * уже приводило к поискам не в том месте, и в `pinhead-react/CLAUDE.md`
 * записано прямым текстом: «увидели 13 падений подряд с пустой страницей —
 * сначала проверьте `.env`, а не спеки».
 *
 * Значения при этом фиктивны по существу: сеть Supabase перехватывает
 * `e2e/support/mockSupabase`, до настоящего проекта не доходит ни один
 * запрос. То есть e2e держался на локальном файле с БОЕВЫМИ ключами,
 * не нуждаясь ни в одном из них, — и на свежей машине, чистом клоне или
 * пересозданном контейнере был полностью красным.
 *
 * ПОЧЕМУ ТЕСТ ЧИТАЕТ ТЕКСТ КОНФИГА. Vitest мокает `lib/supabase` целиком
 * (`setupTests.js`), то есть unit-среда этой проверки не видит вовсе:
 * выполнить конфиг Playwright и посмотреть на результат отсюда нельзя.
 * Единственный доступный способ — сверить исходник, тем же приёмом, каким
 * сторожатся `vercel.json` и `public/sw.js`.
 *
 * ДВА СЕРВЕРА, И ОБА ОБЯЗАТЕЛЬНЫ. Строка, забытая у одного, вернула бы тот же
 * белый экран на половине прогона — а половина зелёного прогона читается как
 * флака, то есть как случайность, которую «надо перезапустить».
 */

const CONFIG = readFileSync(join(process.cwd(), 'playwright.config.ts'), 'utf8');

/** Комментарии снимаем: объяснение, ЗАЧЕМ строка, содержит те же слова */
const withoutComments = (src: string): string => src
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/^[ \t]*\/\/.*$/gm, '');

const BODY = withoutComments(CONFIG);

describe('e2e поднимает приложение со своими ключами Supabase', () => {
  it('обе переменные заданы в конфиге, а не берутся из .env', () => {
    expect(BODY).toMatch(/VITE_SUPABASE_URL=\S+/);
    expect(BODY).toMatch(/VITE_SUPABASE_ANON_KEY=\S+/);
  });

  it('ключи приходят КАЖДОМУ из двух серверов', () => {
    // Ищем не по имени переменной, а по её присутствию в самой команде:
    // между dev-сервером и сборкой для офлайн-спек разницы здесь нет
    const commands = [...BODY.matchAll(/command:\s*([`'"][\s\S]*?)\n\s*(?:url|\+ ')/g)]
      .map((m) => m[1]);
    const withKeys = [...BODY.matchAll(/command:/g)].length;
    expect(withKeys, 'серверов в конфиге не два — сторож пора обновить').toBe(2);
    // Общая константа — законный способ передать ключи обоим: проверяем,
    // что каждая команда её подставляет, а не что строка написана дважды
    expect(commands.length).toBeGreaterThan(0);
    for (const cmd of commands) {
      expect(
        /MOCK_SUPABASE_ENV|VITE_SUPABASE_URL/.test(cmd),
        `команда без ключей Supabase — этот сервер поднимет белый экран:\n${cmd}`,
      ).toBe(true);
    }
  });

  /**
   * Ключи ФИКТИВНЫЕ. Настоящий адрес проекта здесь означал бы, что прогон
   * при дырке в моке уходит на живую базу — и пишет в неё: e2e создаёт
   * заказы, закрывает этапы и отгружает. Домен `.invalid` зарезервирован
   * стандартом и не резолвится нигде.
   */
  it('адрес заведомо нерабочий — прогон не может уйти на живой проект', () => {
    const url = BODY.match(/VITE_SUPABASE_URL=(\S+)/)?.[1] ?? '';
    expect(url).not.toMatch(/supabase\.(co|in)/);
    expect(url).toMatch(/\.invalid/);
  });
});

/**
 * ТУЛБАР ОБРАТНОЙ СВЯЗИ НЕ ПОПАДАЕТ В ЭТАЛОНЫ ПРОДУКТА.
 *
 * Виджет (agentation.com, `DevAnnotations`) рисуется ПОВЕРХ страницы. Без
 * выключателя чужая панель оказывается в снимках `visual.spec.ts` и под
 * сканером доступности `erp-a11y`. Хуже прочего то, что эталон при этом
 * ЗЕЛЁНЫЙ: панель просто становится частью «продукта», и следующая версия
 * пакета перекрашивает эталон, к продукту отношения не имеющий, — то же
 * самое, что узаконенный эталоном индикатор отказа. Так и было до 03.09:
 * тулбар лежал внутри `studio-sku-*.png`.
 *
 * ФЛАГ НУЖЕН ОБОИМ СЕРВЕРАМ. Пока виджет стоял за `import.meta.env.DEV`,
 * второму (прод-сборка для offline и perf) он был не нужен: виджета там
 * не существовало. С 03.09 виджет работает и в проде для admin/director,
 * а ОБА сервера поднимаются с `VITE_DEV_AUTOLOGIN=1`, то есть под админом
 * «Dev Mode», — значит панель нарисовалась бы и в собранном приложении,
 * попав в замеры раскладки `erp-cls` и в офлайн-спеку.
 */
describe('e2e не тащит в снимки виджет обратной связи', () => {
  it('оба сервера поднимаются с VITE_AGENTATION=0', () => {
    const commands = [...BODY.matchAll(/command:\s*([`'"][\s\S]*?)\n\s*(?:url|reuseExisting)/g)]
      .map((m) => m[1]);
    expect(commands.length, 'серверов в конфиге не два — сторож пора обновить').toBe(2);
    for (const cmd of commands) {
      expect(
        /VITE_AGENTATION=0/.test(cmd),
        `без флага тулбар agentation попадёт в эталоны и в скан доступности:\n${cmd}`,
      ).toBe(true);
    }
  });
});
