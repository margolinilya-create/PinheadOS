// ── Снятие комментариев ──────────────────────────────────────

/**
 * Комментарии снимаются ПЕРЕД любой проверкой — правило проекта (то же делает
 * `src/utils/date.test.ts`). Без этого аудит ловил объяснение вместо кода:
 * четыре «хардкоженных цвета» в `index.css` — это hex внутри комментариев,
 * которые как раз и обосновывают, почему токен имеет такое значение
 * («был #888888 и не проходил AA»). Написать такое объяснение было
 * единственным способом сделать аудит красным.
 *
 * Номера строк обязаны сохраниться, поэтому содержимое комментария
 * заменяется пробелами, а переводы строк остаются на месте: иначе адрес
 * настоящей находки уехал бы, и человек искал бы её не там.
 */
export function stripCssComments(src) {
  return src.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '));
}

/**
 * У JS/JSX комментарии двух видов, и `//` внутри строки (`https://…`) — не
 * комментарий. Поэтому построчный вариант: блочные снимаются, а строчные
 * только когда строка с них НАЧИНАЕТСЯ. Тот же приём, что в тестах проекта.
 */
export function stripJsComments(src) {
  return stripCssComments(src)
    .split('\n')
    .map((l) => (l.trimStart().startsWith('//') ? '' : l))
    .join('\n');
}

// ── 1. Хардкоженные цвета ────────────────────────────────────

/** Значения, которые токеном не выражают: чистый чёрный, белый и серая рамка */
export const HEX_ALLOWLIST = new Set([
  '#fff', '#ffffff', '#000', '#000000', '#ccc',
]);

/**
 * Строка объявляет CSS-токен (`--font-display: 'Barlow Condensed', sans-serif`).
 *
 * Это ЕДИНСТВЕННОЕ законное место, где значение стоит буквально: и цвет,
 * и семейство шрифта. Правило «шрифт только через var(--font-display)»
 * не может требовать этого от самого объявления — иначе токен объявить
 * нечем. Раньше вопрос не вставал только потому, что проверки шрифтов
 * не смотрели `index.css` вовсе, то есть хардкод шрифта в главном файле
 * стилей прошёл бы мимо аудита.
 */
export function isTokenDeclaration(line) {
  return /^\s*--[\w-]+\s*:/.test(line);
}

export function isAllowedHex(line) {
  // Объявление самого токена — здесь hex и должен стоять
  if (isTokenDeclaration(line)) return true;
  // rgba() содержит похожие на hex цифры, но это не цвет-константа
  if (/rgba?\(/.test(line)) return true;
  // Фолбэк вида var(--color-error, #FF3B30)
  if (/var\(.*#[0-9A-Fa-f]/.test(line)) return true;
  return false;
}

/** Находки «цвет мимо токена» в одном CSS-файле; `src` — сырой текст */
export function findHexHits(src, file = '') {
  const hits = [];
  stripCssComments(src).split('\n').forEach((line, i) => {
    if (isAllowedHex(line)) return;
    const found = line.match(/#[0-9A-Fa-f]{3,8}\b/g);
    if (!found) return;
    const bad = found.filter((h) => !HEX_ALLOWLIST.has(h.toLowerCase()));
    if (bad.length > 0) {
      hits.push({ file, line: i + 1, text: `${line.trim()}  [${bad.join(', ')}]` });
    }
  });
  return hits;
}

// ── 2–3, 5. Построчный поиск ─────────────────────────────────

/**
 * Строки, попавшие под регулярку, — уже без комментариев. `exclude` отсеивает
 * правильное употребление (например, шрифт через `var(--font-display)`),
 * `skip` — предикат для случаев вроде объявления самого токена.
 */
export function findLineHits(
  src,
  regex,
  { file = '', strip = stripJsComments, exclude = null, skip = null } = {},
) {
  const hits = [];
  strip(src).split('\n').forEach((line, i) => {
    if (!regex.test(line)) return;
    if (exclude && line.includes(exclude)) return;
    if (skip && skip(line)) return;
    hits.push({ file, line: i + 1, text: line.trim() });
  });
  return hits;
}

// ── 4. Анимации без prefers-reduced-motion ───────────────────

/**
 * Есть ли в блоке правило с УНИВЕРСАЛЬНЫМ СЕЛЕКТОРОМ
 * (`*, *::before, *::after { … }`) — стандартный приём W3C для SC 2.3.3,
 * гасящий вообще все анимации; в проекте объявлен один раз в `utils.css`.
 *
 * Отличать приходится по ПОЗИЦИИ, а не по соседним символам. Первая попытка
 * искала звёздочку, окружённую пробелами и запятыми, — и ровно так же
 * срабатывала на `calc(100% * .5)`: там у `*` тоже пробел слева и справа.
 * Одного такого объявления внутри блока хватало, чтобы ВСЕ анимации проекта
 * разом объявились покрытыми, то есть проверка тихо переставала проверять.
 *
 * Поэтому берём только то, что стоит ПЕРЕД `{`, — список селекторов правила.
 * Звёздочка в значении свойства туда не попадает по построению: она живёт
 * после двоеточия, внутри тела, которое здесь не рассматривается.
 */
export function hasUniversalSelector(block) {
  /**
   * Разбор по структурным символам, а не одной регуляркой: вариант
   * `/(?:^|[{};])([^{};]*)\{/g` СЪЕДАЛ открывающую скобку, и следующий
   * список селекторов оставался без границы слева — то есть внутреннее
   * правило `*, *::before, *::after {` не находилось вовсе.
   *
   * `split` с захватом отдаёт чередование «кусок, разделитель»: кусок перед
   * `{` — это список селекторов, всё остальное — тело объявлений.
   */
  const parts = block.split(/([{};])/);
  for (let i = 0; i + 1 < parts.length; i += 2) {
    if (parts[i + 1] === '{' && /(^|[\s,])\*/.test(parts[i])) return true;
  }
  return false;
}

/**
 * Имена анимаций, не покрытых ни одним `prefers-reduced-motion`.
 *
 * ДВА ПРОХОДА, а не один. Раньше имена собирались и покрытие проверялось
 * в одном цикле по файлам, поэтому глобальный override («гасим ВСЕ анимации»)
 * засчитывался только тем анимациям, которые встретились ДО него по порядку
 * обхода. `fadeSlideIn` объявлена в `wizard.css`, а override живёт
 * в `utils.css`, то есть в файле, идущем раньше по алфавиту, — и покрытая
 * анимация рапортовалась как непокрытая. Порядок файлов не должен решать
 * ничего, поэтому на вход идёт СПИСОК исходников и сначала собираются
 * все имена.
 */
export function uncoveredKeyframes(sources) {
  const cleaned = sources.map(stripCssComments);
  const names = new Set();
  for (const content of cleaned) {
    for (const m of content.matchAll(/@keyframes\s+([\w-]+)/g)) names.add(m[1]);
  }

  const covered = new Set();
  for (const content of cleaned) {
    const blocks = content.matchAll(/@media\s*\(prefers-reduced-motion[^)]*\)\s*\{([^}]*(?:\{[^}]*\}[^}]*)*)\}/g);
    for (const block of blocks) {
      const inner = block[0];
      if (hasUniversalSelector(inner)) {
        for (const name of names) covered.add(name);
      }
      for (const name of names) {
        if (inner.includes(name)) covered.add(name);
      }
    }
  }

  return [...names].filter((n) => !covered.has(n));
}
