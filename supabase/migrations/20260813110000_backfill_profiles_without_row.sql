-- Достроить профили тем, кто зарегистрировался ДО серверного триггера.
--
-- До миграции 20260722215558 профиль писал клиент — `upsert` в `profiles` прямо
-- из `register()`. Работать он не мог никогда: политика `profiles_insert`
-- требует `is_admin()`, а у регистранта в этот момент нет даже сессии
-- (подтверждение адреса включено, `signUp` сессию не выдаёт). Каждая такая
-- регистрация молча получала 42501 — результат вызова не проверялся.
--
-- Человек без строки в `profiles` не просто «ждёт одобрения»: его НЕ ВИДНО
-- в админке вовсе, одобрять некого. А после подтверждения адреса вход ему
-- удаётся — и тут же возвращает на форму входа, потому что `fetchProfile`
-- не находит профиля. Отказа он при этом не видит ни одного.
--
-- Триггер `handle_new_user` висит на INSERT в `auth.users` и уже существующих
-- не лечит: их запись давно вставлена. Отсюда разовый бэкфилл.
--
-- Значения те же, что ставит триггер: роль `manager`, `approved = false`
-- (доступа нет, `erp_is_member()` = false), `active = true`. Имя берётся
-- из метаданных, а при их отсутствии — email, как и в триггере: выдумывать
-- имя за человека нельзя, а пустое поле нарушило бы `not null`.
insert into public.profiles (id, email, name, role, approved, active)
select
  u.id,
  u.email,
  coalesce(nullif(u.raw_user_meta_data->>'name', ''), u.email),
  'manager',
  false,
  true
from auth.users u
where not exists (select 1 from public.profiles p where p.id = u.id)
on conflict (id) do nothing;
