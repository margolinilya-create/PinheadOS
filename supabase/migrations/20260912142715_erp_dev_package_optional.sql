-- Финальный пакет разработки перестал держать завершение (правка 12.09, п. 9).
--
-- «Временно убрать из рабочего сценария блок „Проверка образца" и
-- обязательность „Финального технического пакета"… Эти проверки и поля
-- не должны блокировать кнопку „Завершить разработку"… Текущие данные
-- не удалять из БД — функционал можно скрыть/отключить, чтобы его можно было
-- вернуть позже».
--
-- ПОЧЕМУ СЕРВЕР ОСЛАБЛЯЕТСЯ ТЕМ ЖЕ КОММИТОМ, ЧТО И КЛИЕНТ. Правило стояло
-- ДВУМЯ половинами: `utils/finalPackage.missingFinalPackage` гасил кнопку,
-- а этот страж отклонял переход в `ready_for_serial`. Сними одну — получишь
-- запрещённое в проекте «кнопка есть, действие падает», причём у технолога
-- и с непонятным текстом 23514.
--
-- ЧТО ИМЕННО МЕНЯЕТСЯ: тело стража становится пустым (`return new`), сама
-- функция и триггер ОСТАЮТСЯ. Так вернуть требование — значит пересоздать
-- одну функцию по тексту `20260830160000`, а не собирать заново триггер,
-- права и порядок срабатывания. Проверки и данные никуда не деваются:
-- `sample_approved_at`, `pattern_tech_name`, `pattern_version`, вложения
-- `dev_passport`/`dev_photo` пишутся и читаются как раньше.
--
-- ЦЕНА НАЗВАНА ВСЛУХ. На переходе в `ready_for_serial` висит
-- `erp_dev_handoff_to_warehouse`: он заводит складскую задачу «Приёмка ГП».
-- Без проверки образца склад может получить задачу на вещь, которой
-- физически нет, — ровно дефект, ради которого правка 30.08 и делалась.
-- Заказчик принял это осознанно и просит «временно»; возврат стоит одной
-- миграции.
--
-- КЛИЕНТ ПРИ ЭТОМ БЫВАЕТ СТРОЖЕ СЕРВЕРА, и это сказано здесь, чтобы потом
-- не искать: флаг `devFinalPackageRequired` (по умолчанию ВЫКЛЮЧЕН, то есть
-- у всех требования нет) возвращает перечень и блок «Проверка образца»
-- в интерфейсе. Включив его, не забудьте вернуть и стража — иначе половины
-- снова разойдутся, только в другую сторону.

create or replace function public.erp_dev_package_guard()
returns trigger
language plpgsql security invoker set search_path = public as $$
begin
  -- Требование финального пакета снято правкой заказчика 12.09 (п. 9).
  -- Тело оставлено пустым НАМЕРЕННО: функция и триггер на месте, и возврат
  -- проверок — это пересоздание одной функции по тексту 20260830160000,
  -- а не сборка триггера заново.
  return new;
end $$;

comment on function public.erp_dev_package_guard() is
  'Страж финального пакета ОТКЛЮЧЁН правкой заказчика 12.09 (п. 9): проверки образца и техдокументации не держат переход в ready_for_serial. Данные и триггер сохранены, возврат — пересоздание функции по тексту 20260830160000.';

-- Пересозданная функция получает права заново — отзыв повторяется здесь же.
-- `from public, anon`: право приходит от PUBLIC, и `anon` наследует его —
-- один `from anon` не делает ничего. Триггерную функцию через REST звать
-- нельзя в принципе, но висящее предупреждение адвизора — это шум,
-- за которым теряется настоящее.
revoke execute on function public.erp_dev_package_guard() from public, anon, authenticated;
