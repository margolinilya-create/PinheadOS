-- Индекс на внешний ключ `orders.erp_order_id` (обзор 24.09, п. 14; сессия 68).
--
-- Advisor `unindexed_foreign_keys` держал его единственной находкой класса:
-- связь заказа Order Studio с производственным (`on delete set null`) без
-- покрывающего индекса. При удалении заказа ERP Postgres ищет ссылающиеся
-- строки `orders` полным просмотром — сегодня это одна строка, но мост
-- «ТЗ → производство» (следующая очередь) будет писать эту связь на каждый заказ.
--
-- Остальные индексы внешних ключей заведены 24.09 (`20260924122718_erp_fk_indexes`);
-- этот выпал, потому что `orders` — таблица Order Studio, а не `erp_*`.

create index if not exists orders_erp_order_id_idx on public.orders (erp_order_id);
