-- КОММЕНТАРИЙ ПО ПРОРАБОТКЕ — результат этапа проработки (правка 13.09, п. 10).
--
-- «По аналогии с этапом „Построение лекал", при завершении этапа проработки
-- и переносе разработки в нанесения нужно дать возможность зафиксировать
-- результат этапа… Если комментарий заполнен, сохранить его в карточке
-- разработки как результат этапа проработки и показывать дальше в задаче
-- выбранного участка нанесения».
--
-- ПОЧЕМУ КОЛОНКА, А НЕ ЗАДАЧА И НЕ ЗАМЕТКА ЗАКАЗА. Величина принадлежит
-- РАЗРАБОТКЕ и отвечает на один вопрос — «что технолог передал цеху вместе
-- с образцом». Ровно так же 22.08 заведено `pattern_tech_name`: результат
-- этапа пишется в ТУ ЖЕ колонку, которую читает потребитель, а не переносится
-- отдельной операцией. Свободная заметка заказа (`erp_order_notes`) сюда
-- не годится: её адресат — весь заказ, а не задание конкретного участка
-- нанесения.
--
-- НЕОБЯЗАТЕЛЬНАЯ: документ прямо запрещает делать из неё блокировку («не
-- добавлять сюда количественную логику, обязательные файлы или дополнительные
-- блокировки»). Поэтому просто nullable text — ни CHECK, ни NOT NULL,
-- ни умолчания: пустая строка и NULL означали бы одно и то же, и второй
-- способ сказать «комментария нет» был бы лишним.
--
-- Миграция АДДИТИВНА (новая колонка), поэтому применяется сразу: прежний
-- бандл её не читает и переживает. Строже сервер от неё не становится.

alter table public.erp_experimental
  add column if not exists branding_note text;

comment on column public.erp_experimental.branding_note is
  'Комментарий по проработке: результат этапа проработки, который технолог '
  'оставляет при переносе карточки в «Нанесения». Читает его цех нанесения '
  'в своём задании (см. utils/devBoardMove.devNotePrompt). Необязателен.';
