-- ТРЕТИЙ СЦЕНАРИЙ ГОТОВОГО ИЗДЕЛИЯ: «СКЛАД ГОТОВОЙ ПРОДУКЦИИ»
-- (правка заказчика 14.09, п. 1).
--
-- Документ: «в позиции при типе производства „Готовое изделие" в блоке
-- „Чьё изделие" добавить третий вариант „Склад готовой продукции"».
--
-- ЧТО ИЗ НЕГО СЛЕДУЕТ (решение владельца 14.09). Ось прежняя — ЧЬЁ ИЗДЕЛИЕ, —
-- и у каждого значения ровно два маршрутных последствия:
--
--   purchased — закупаем мы: этап «Закупка» есть, склад только при нанесении;
--   customer  — давальческое: закупки нет, склад ПРИНИМАЕТ чужой товар;
--   stock     — со склада ГП: закупки нет, склад ВЫДАЁТ наш товар в работу.
--
-- Признак, из которого ничего не следует, — это поле, которое заполняют
-- и больше никогда не читают; здесь следствия есть, и они разные.
--
-- МИГРАЦИЯ АДДИТИВНАЯ и применяется ДО фронтенда: прежний бандл нового
-- значения не создаёт, а CHECK лишь перестаёт его отвергать. Обратный порядок
-- дал бы форму, которая предлагает вариант, отклоняемый сервером.
--
-- Клиентская половина — `src/erp/utils/garmentSource.ts` (сравнение строго
-- с каждым значением: на бое 14.09 колонка пуста у ВСЕХ позиций, и правило
-- вида `!= 'purchased'` сняло бы закупку у заведённых заказов задним числом).

alter table public.erp_order_items
  drop constraint if exists erp_order_items_garment_source_check;

alter table public.erp_order_items
  add constraint erp_order_items_garment_source_check
  check (garment_source is null
         or garment_source in ('customer', 'purchased', 'stock'));

comment on column public.erp_order_items.garment_source is
  'Чьё готовое изделие: customer — давальческое (изделие клиента), purchased — закупаем мы, stock — берём со склада готовой продукции. NULL у позиций до правки 07.09 и у всех, чей тип производства не ready_garment; читается как purchased. У customer и stock закупка из маршрута уходит, а этап склада обязателен: у первого склад принимает чужой товар, у второго выдаёт свой.';
