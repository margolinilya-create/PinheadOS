-- Правки менеджера, волна 2: группа «Ожидают материалы» в производственном канбане.
--
-- Требование: заказ, переданный на этап, но не запускаемый из-за отсутствия материалов,
-- должен стоять в отдельной группе перед «Готово к работе», с указанием какого именно
-- материала ждут, комментарием, ожидаемой датой, ответственным и датой обновления.
-- Группа нужна не только закрою и швейке, а и шелкографии, ДТФ, вышивке, ВТО, ОТК.
--
-- Что мешало. Карта «какой материал какому цеху нужен» была КОНСТАНТОЙ в коде
-- (`MATERIAL_GATE_DEPT` в src/erp/utils/routes.ts): ткань блокировала только закрой,
-- фурнитура и бирки — только швейку. Участок, заведённый директором в админке,
-- под гейт не попадал никак — то же самое, что уже чинили миграцией
-- 20260727210000 для `is_production`. Правило проекта: признак цеха живёт
-- в данных, а не в константе.

-- ── 1. Какие материалы блокируют запуск этапа этого участка ──
-- Пустой массив = участок материалами не гейтится (fail-open: остановка
-- производства не должна случаться из-за незаполненной настройки).
alter table public.erp_departments
  add column if not exists gate_material_kinds text[] not null default '{}';

comment on column public.erp_departments.gate_material_kinds is
  'Виды материалов (erp_materials.kind), без которых этап участка не запускается. '
  'Пустой массив — участок материалами не гейтится. Правится в админке.';

-- Бэкфилл ровно по прежней константе — поведение не меняется ни на одном заказе.
-- Остальные участки заказчик настраивает в админке сам: «шелкографии нужна плёнка»
-- знает производство, а не разработчик, и жёстко зашитая догадка тут же
-- остановила бы этапы, которые сегодня спокойно идут.
update public.erp_departments set gate_material_kinds = array['fabric']
 where code = 'cutting' and gate_material_kinds = '{}';

update public.erp_departments set gate_material_kinds = array['hardware', 'labels']
 where code = 'sewing' and gate_material_kinds = '{}';

-- ── 2. Ответственный за получение материала ──
-- В карточке ожидания менеджер хочет видеть, с кого спрашивать. `accepted_by` —
-- это кто ПРИНЯЛ по факту, то есть заполняется уже после события; поля «кто везёт»
-- в схеме не было вовсе.
alter table public.erp_materials
  add column if not exists responsible text;

comment on column public.erp_materials.responsible is
  'Кто отвечает за получение материала (свободный текст). Не путать с accepted_by — '
  'тот заполняется складом уже по факту приёмки.';

-- ── 3. Право отметить поступление материала ──
-- Кнопка «Материал поступил» на карточке ожидания ведёт в тот же путь приёмки,
-- что и экран склада (иначе status='received' без accept_status не снимет гейт,
-- и кнопка окажется декоративной). Значит, ей нужно своё право.
--
-- По умолчанию: кладовщик и закупщик (их работа), диспетчер и директор (разбор
-- заторов). Мастеру и рабочему НЕ даём: приёмка — это сверка количества и
-- качества на складе, а не отметка «вроде привезли».
insert into public.erp_role_permissions (role, permission, allowed)
select r.role, 'material.receive',
  r.role in ('director', 'dispatcher', 'purchaser', 'storekeeper')
from (values
  ('director'),('dispatcher'),('manager'),('foreman'),
  ('worker'),('purchaser'),('storekeeper'),('hr')
) as r(role)
on conflict (role, permission) do nothing;
