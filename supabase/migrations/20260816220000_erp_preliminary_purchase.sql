-- Предварительная закупка до запуска заказа (правки заказчика 16.08, п. 17).
--
-- СЦЕНАРИЙ ДОКУМЕНТА. «Сделка ещё окончательно не запущена, но уже известно,
-- какая ткань потребуется. Чтобы не потерять несколько дней, ткань закупается
-- заранее. Позже заказ официально запускается». И далее (п. 17.1): найти
-- предварительную закупку, привязать её к сделке, подтянуть в карточку заказа —
-- «система при этом не должна создавать вторую дублирующую закупку».
--
-- `erp_materials.order_id` объявлен NOT NULL, поэтому «закупка без заказа»
-- была невозможна в принципе.
--
-- ПРОВЕРЕНО ПЕРЕД ПРАВКОЙ: политики `erp_materials` не ссылаются на `order_id`
-- вовсе — все четыре стоят на `erp_is_member()`/`is_admin()`. Значит строка
-- с пустым заказом остаётся видимой участникам, а не исчезает у того, кто её
-- завёл. Это был единственный настоящий риск снятия ограничения, и он не
-- подтвердился — но проверять его надо было ДО, а не после.
--
-- Привязка — это UPDATE существующей строки, а не копия: дубль закупки прямо
-- запрещён документом. Индекс нужен ровно под один запрос — список
-- непривязанных, — поэтому он частичный.
alter table public.erp_materials
  alter column order_id drop not null;

create index if not exists erp_materials_unassigned_idx
  on public.erp_materials (created_at desc) where order_id is null;

comment on column public.erp_materials.order_id is
  'Заказ, для которого закупается материал. NULL — предварительная закупка до запуска сделки (п. 17 документа 16.08); привязывается позже UPDATE-ом, без создания второй строки.';
