-- Справочник типов задач разработки (ТЗ экспериментального цеха, п.11).
--
-- ── Зачем ──
--
-- Документ заказчика: «При создании разработки пользователь должен иметь
-- возможность выбрать необходимые задачи» — и дальше список: лекала, подбор
-- материала, фурнитура, проработка образца, ДТФ, шелкография, вышивка,
-- сублимация, примерка, доработка, другое. Заказчик выбрал справочник
-- в админке, а не константу в коде: набор задач у разработки меняется вместе
-- с тем, что фабрика умеет делать, и добавление строки не должно быть релизом.
--
-- Правило проекта про справочники действует и здесь: значение — ПОДСКАЗКА,
-- а не ограничение. Тип задачи вводится свободно, справочник даёт datalist
-- и чипы; значения отключаются (`active = false`), а не удаляются — они уже
-- записаны в закрытых задачах, и физическое удаление сделало бы историю
-- нечитаемой.
--
-- ── Порядок операций ──
--
-- CHECK на `kind` перечисляет виды поимённо, поэтому расширять его надо
-- ДО вставки: иначе `insert` падает на 23514, а подсказки не заводятся.
-- Ровно та же последовательность, что у единиц измерения (20260810200000).
--
-- ── Чего здесь НЕТ ──
--
-- Статусов задач в справочнике нет и не будет: они в CHECK-констрейнтах
-- и в стейт-машине разработки, их изменение — доработка кода, а не запись
-- в справочник (правило проекта, вкладка «Статусы» в админке — только чтение).

alter table public.erp_dictionaries
  drop constraint if exists erp_dictionaries_kind_check;
alter table public.erp_dictionaries
  add constraint erp_dictionaries_kind_check
  check (kind in (
    'block_reason', 'problem_type', 'product_type', 'supplier', 'unit',
    'experimental_task_type'
  ));

-- Начальный набор — прямо из списка в документе заказчика (п.11), плюс то,
-- что уже умеет система: передача в цех нанесения и подряд.
insert into public.erp_dictionaries (kind, code, name, sort_order, active)
select 'experimental_task_type', v.code, v.name, v.sort_order, true
  from (values
    ('patterns',       'Лекала',              10),
    ('material',       'Подбор материала',    20),
    ('hardware',       'Фурнитура',           30),
    ('sample',         'Проработка образца',  40),
    ('sewing_sample',  'Пошив образца',       50),
    ('dtf',            'ДТФ',                 60),
    ('silkscreen',     'Шелкография',         70),
    ('embroidery',     'Вышивка',             80),
    ('sublimation',    'Сублимация',          90),
    ('subcontract',    'Подряд',             100),
    ('fitting',        'Примерка',           110),
    ('rework',         'Доработка',          120),
    ('photo',          'Фотосъёмка',         130),
    ('techcard',       'Техкарта',           140),
    ('other',          'Другое',             150)
  ) as v(code, name, sort_order)
 where not exists (
   select 1 from public.erp_dictionaries d
    where d.kind = 'experimental_task_type' and d.code = v.code
 );

comment on constraint erp_dictionaries_kind_check on public.erp_dictionaries is
  'Виды справочников перечислены поимённо. Добавляя вид — расширьте CHECK ДО вставки значений и впишите вид в DictionaryKind, DICTIONARY_LABELS, DICTIONARY_HINTS и KINDS в DictionariesTab: пропуск последнего означает справочник, которого нет в админке (так случилось с "unit").';
