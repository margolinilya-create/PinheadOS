-- ФАКТИЧЕСКИ ЗАКАЗАНО У ПОСТАВЩИКА ПО РАЗМЕРАМ (правка заказчика 20.09, п. 2).
--
-- Документ: «Внутри закупки показывать таблицу „Размер / Количество к заказу /
-- Фактическое количество". Количество к заказу — потребность из заказа.
-- Фактическое количество — сколько реально заказали у поставщика по каждому
-- размеру».
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ КОЛОНКА, А НЕ ПЕРЕЗАПИСЬ `size_grid`. У закупки уже есть
-- `size_grid` — это ПОТРЕБНОСТЬ, снятая с позиции заказа, и по ней триггер
-- `erp_material_grid_qty` считает `qty_expected`. Запиши закупщик свой факт
-- туда же — потребность исчезнет, сравнивать станет не с чем, а плановое
-- количество молча съедет к фактическому. Ровно та же причина, по которой
-- у строки закупки рядом живут `qty_expected` и `qty_ordered`.
--
-- ТРИГГЕР ПЕРЕСЧЁТА СЮДА НЕ РАСПРОСТРАНЯЕТСЯ И НЕ ДОЛЖЕН: он висит на
-- `of size_grid, qty_expected`, а «сколько заказали» — это `qty_ordered`,
-- поле закупщика, которое он ведёт сам (правка 12.09 развела поля менеджера
-- и закупщика намеренно).

alter table public.erp_materials
  add column if not exists size_grid_ordered jsonb;

comment on column public.erp_materials.size_grid_ordered is
  'Фактически заказано у поставщика по размерам — тот же формат [{color, sizes}], что у size_grid. size_grid остаётся ПОТРЕБНОСТЬЮ из заказа: по ней считается qty_expected (правка 20.09, п. 2).';
