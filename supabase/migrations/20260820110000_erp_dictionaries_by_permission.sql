-- Библиотека подрядных операций пополняется из маршрута (правки заказчика 20.08).
--
-- ЧТО ПРОСИТ ДОКУМЕНТ. «Поле "Операция" работает через единую редактируемую
-- библиотеку. Если нужной операции нет, менеджер нажимает + Создать новую
-- операцию. После сохранения операция используется в текущем маршруте,
-- автоматически добавляется в библиотеку и становится доступна в следующих
-- заказах. Добавление нового вида подрядных работ не должно требовать
-- доработки ERP».
--
-- ЧТО НАШЛОСЬ ПРИ ПРОВЕРКЕ. Справочник `route_operation` есть с 16.08, но
-- пополнить его нельзя почти никому: политики `erp_dictionaries` стоят на
-- `is_admin()` (20260727150000, позже не менялись), то есть право
-- `catalog.edit` из матрицы НЕ ОТКРЫВАЕТ СПРАВОЧНИКИ ВООБЩЕ. Директор и
-- руководитель производства, у которых оно проставлено, получали отказ —
-- ровно «декоративное право» из правил проекта, только замеченное с другой
-- стороны: обычно право ничего не выключает, здесь оно ничего не включает.
--
-- ДВЕ ДВЕРИ, И ОБЕ УЗКИЕ:
--   · вся правка справочников — под `catalog.edit` (то, что матрица и обещает);
--   · ДОБАВЛЕНИЕ операции маршрута — ещё и под `order.manage`, потому что
--     маршрут задаёт менеджер заказа, и документ требует, чтобы новая операция
--     заводилась прямо в маршруте.
--
-- Переименование и отключение значений менеджеру НЕ открываются: это правка
-- чужих записей справочника, работа админа. Гейт кнопки в интерфейсе —
-- дословное зеркало этого предиката (правило «страж и клиентский гейт
-- ставятся одним коммитом»).

drop policy if exists erp_dictionaries_insert on public.erp_dictionaries;
create policy erp_dictionaries_insert on public.erp_dictionaries
  for insert to authenticated
  with check (
    public.erp_has_permission('catalog.edit')
    or (kind = 'route_operation' and public.erp_has_permission('order.manage'))
  );

drop policy if exists erp_dictionaries_update on public.erp_dictionaries;
create policy erp_dictionaries_update on public.erp_dictionaries
  for update to authenticated
  using (public.erp_has_permission('catalog.edit'))
  with check (public.erp_has_permission('catalog.edit'));

