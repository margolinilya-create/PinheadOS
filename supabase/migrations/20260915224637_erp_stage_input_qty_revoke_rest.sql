-- `erp_stage_input_qty` — `security definer` БЕЗ внутреннего гейта, доступная
-- любому вошедшему через `/rest/v1/rpc/erp_stage_input_qty`. Формула ровно та,
-- по которой 07.09 закрыли `erp_is_manager` и соседей: `prosecdef` без
-- предиката RLS, без внутренней проверки прав и с `authenticated` в ACL.
--
-- ПОЧЕМУ ОТЗЫВ, А НЕ ГЕЙТ ВНУТРИ. Проверено схемой, а не на слух:
--   · в предикатах политик функция не стоит НИ РАЗУ (`pg_policies` пуст),
--     то есть отзыв не сломает сами политики — в отличие от `is_admin()`
--     и `erp_is_member()`, которым EXECUTE отбирать нельзя;
--   · вызывающий ОДИН — триггерная функция `erp_clamp_stage_qty`, и она сама
--     `security definer` с владельцем `postgres`: при её работе `current_user`
--     это владелец, которого отзыв не касается;
--   · клиент функцию не зовёт вовсе (в `src/` только сгенерированный тип).
-- Внутренний гейт здесь был бы хуже: он отобрал бы у цеха обрезку факта
-- в его же триггере — тот самый отказ, ради которого функция и `definer`.
--
-- Отзыв идёт `from public, anon`: право приходит от PUBLIC (`=X/postgres`
-- в ACL), и `anon` наследует его — `revoke … from anon` в одиночку не делает
-- ничего. `grant … to authenticated` СОЗНАТЕЛЬНО не возвращается: политик,
-- которым бы он понадобился, нет.
--
-- Проверено на живой базе транзакцией с откатом, ОБЕ половины:
--   1. `update erp_item_stages set qty_done = qty_done + 1` проходит —
--      триггер по-прежнему зовёт функцию, отзыв его не коснулся;
--   2. прямой вызов от `set local role authenticated` отвечает 42501.
revoke execute on function public.erp_stage_input_qty(uuid) from public, anon, authenticated;
