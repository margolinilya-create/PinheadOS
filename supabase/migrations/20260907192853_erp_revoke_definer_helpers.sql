-- ОТЗЫВ EXECUTE У ДВУХ SECURITY DEFINER, ДОСТУПНЫХ ЧЕРЕЗ REST
--
-- ТОТ ЖЕ КЛАСС, ЧТО ЧИНИЛИ 04.09 у `erp_ensure_subcontract_send`, и ровно
-- то, о чём предупреждает записанное правило: «перечисление по именам
-- не переживает следующего имени». Тогда закрыли ОДНУ функцию поимённо —
-- и две соседние остались открытыми `authenticated` через
-- `/rest/v1/rpc/…`.
--
-- Найдено не грепом по именам, а ВОПРОСОМ к схеме: перебрать все
-- `prosecdef` не-триггерные функции и отобрать те, у которых
-- ОДНОВРЕМЕННО (а) нет предиката RLS, который бы их вызывал,
-- (б) нет внутренней проверки прав, (в) `authenticated` стоит в ACL.
-- Таких оказалось ровно две.
--
-- ПОЧЕМУ ОСТАЛЬНЫЕ НЕ ТРОГАЕМ — каждая по своей причине, а не «похожи»:
--
--   `erp_has_permission`, `erp_is_manager`, `erp_is_member`, `is_admin`
--       СТОЯТ В ПРЕДИКАТАХ RLS. Выражения политик исполняются от лица
--       вызывающего, и отзыв EXECUTE сломал бы сами политики. Записанное
--       решение проекта: advisor на них ругается, «так и оставляем».
--   `erp_invite_preview`
--       осознанно открыта `anon`: человек ещё не вошёл, а политика
--       `for select to anon` открыла бы всю таблицу приглашений вместо
--       одной строки.
--   `erp_sku_from_dev`
--       имеет ВНУТРЕННИЙ гейт (`erp_has_permission`) и умеет отказывать.
--   `erp_ensure_order_finish_tasks`, `erp_ensure_subcontract_send`,
--   `erp_order_has_open_dev`
--       уже закрыты: в ACL только postgres и service_role.
--
-- ПОЧЕМУ ОТЗЫВ БЕЗОПАСЕН. Обе закрываемые функции зовут ТОЛЬКО триггерные
-- функции — `erp_stage_guard` (для `erp_can_act_in_dept`),
-- `erp_ensure_order_finish_tasks` и `erp_warehouse_fg_accepted`
-- (для `erp_can_pack_ship`). Все три — `security definer` с владельцем
-- `postgres`: внутри них `current_user` равен владельцу, и проверка EXECUTE
-- проходит по его правам, а не по правам цеха. Клиент их не зовёт вовсе —
-- проверено обходом исходников: в `src/` есть только упоминания
-- в комментариях и строка в сгенерированных типах, ни одного
-- `supabase.rpc(...)`.
--
-- ЦЕНА БЕЗДЕЙСТВИЯ НЕВЕЛИКА И НАЗВАНА ЧЕСТНО: обе только ЧИТАЮТ и
-- возвращают булево. Утечка — «узнать по uuid, готов ли заказ к отгрузке»
-- и «может ли такой-то действовать в цехе», причём данные под ними участник
-- и так видит по RLS. Это уборка поверхности вызова, а не заделка дыры;
-- ставится потому, что открытая `definer`-функция без гейта — это
-- приглашение к следующей, которая уже будет писать.
--
-- PUBLIC у обеих уже отозван (в ACL нет записи `=X/postgres`), поэтому
-- достаточно снять право у `authenticated`. Проверять надо ACL, а не
-- писать `revoke … from public, anon` вслепую: тот шаблон нужен там, где
-- право ПРИХОДИТ от PUBLIC, и следом требует явного гранта обратно —
-- здесь это вернуло бы ровно то, что мы снимаем.

revoke execute on function public.erp_can_act_in_dept(uuid) from authenticated;
revoke execute on function public.erp_can_pack_ship(uuid) from authenticated;
