-- Канбан ЭКС: колонка разработки становится ХРАНИМОЙ и двигается руками.
-- Правка заказчика 24.08, п. 4.2.
--
-- ЧТО ПРОСИТ ДОКУМЕНТ. «Ответственный за проработку технолог сам вручную
-- перетаскивает карточку между колонками. Автоматическое движение по основным
-- этапам не нужно. Нанесения не являются обязательным этапом: если нанесения
-- не нужны, технолог переносит карточку сразу из Кроя в Пошив».
--
-- ПОЧЕМУ ЭТО ОБРАЩЕНИЕ ПРЕЖНЕГО РЕШЕНИЯ — И ПОЧЕМУ ОНО ЗАКОННО. Колонка `phase`
-- была удалена 12.08 вместе с линейной моделью, и в проекте записан запрет
-- возвращать её под другим именем: два источника правды разъезжаются. Довод
-- был верен ровно потому, что движение считалось автоматическим — хранимое
-- и вычисленное отвечали на ОДИН вопрос и могли ответить по-разному.
--
-- Теперь вопрос другой. `board_stage` — это НАМЕРЕНИЕ ТЕХНОЛОГА («я считаю,
-- что разработка на этом шаге»), а расчёт по задачам остаётся ответом на вопрос
-- «что с работой». Второго источника правды не появляется: расчёт перестаёт
-- определять колонку и продолжает питать дорожки внутри неё (готово / в работе
-- / заблокировано) и подписи узлов пути.
--
-- Ровно поэтому «пропуск нанесений» из документа не требует никакого отдельного
-- механизма: технолог тащит карточку из «Кроя» в «Пошив», и это и есть решение.
--
-- ЗНАЧЕНИЕ NULL — «НЕ ТРОГАЛИ РУКАМИ». Тогда колонка считается как прежде.
-- Так заведённые раньше разработки не прыгают в момент выкладки: у них
-- ни одного `board_stage`, и доска для них не меняется вовсе.

alter table public.erp_experimental
  add column if not exists board_stage text;

-- CHECK перечисляет ровно те пять шагов, что и `DevStage` на клиенте.
-- Значение вне перечня означало бы карточку, которой нет ни в одной колонке, —
-- то есть исчезнувшую с доски разработку.
alter table public.erp_experimental
  drop constraint if exists erp_experimental_board_stage_check;
alter table public.erp_experimental
  add constraint erp_experimental_board_stage_check
  check (board_stage is null
         or board_stage in ('patterns', 'cutting', 'branding', 'sewing', 'final'));

comment on column public.erp_experimental.board_stage is
  'Колонка канбана ЭКС, поставленная технологом вручную (п. 4.2). NULL — не двигали, колонка вычисляется из задач (utils/experimentalBoard.devBoardColumn). Значения — зеркало DevStage.';

