-- ЛИМИТ ВЛОЖЕНИЯ ERP: 15 → 20 МБ (правка 14.09, расхождение №2 — решение владельца).
--
-- Документ 14.09 называл 20 МБ; в ERP стояло 15, и я сознательно оставил 15
-- со словами «документ велит использовать существующие ограничения ERP,
-- и это они». Владелец решил иначе — поднимаем.
--
-- ПОРЯДОК ВЫКЛАДКИ ЗДЕСЬ ОБРАТНЫЙ ОБЫЧНОМУ. Правило проекта «миграция,
-- делающая сервер СТРОЖЕ, выкладывается ПОСЛЕ фронтенда» — про ужесточение;
-- здесь сервер становится МЯГЧЕ, и порядок переворачивается: сначала бакет
-- начинает принимать 20 МБ, потом клиент начинает их предлагать. Обратный
-- порядок дал бы «форма приняла файл, Storage отказал» — то есть отказ ПОСЛЕ
-- того, как человек дождался загрузки восемнадцати мегабайт с планшета.
--
-- ЖИВАЯ БАЗА ПОПРАВИЛА УЧЁТ МЕСТ. Я записал, что величина живёт в ТРЁХ местах
-- (бакет, `ATTACH_MAX_BYTES`, `TZ_MAX_BYTES`). Бакетов ДВА, и оба стояли
-- на 15728640 — то есть мест четыре.
--
-- `sku-photos` НЕ ТРОГАЕТСЯ, и это не забывчивость. Это фото моделей Order
-- Studio, другая величина и другой вопрос: правка 14.09 про вложения ERP
-- и переписку. Поднять её «заодно» значило бы менять то, о чём не просили, —
-- ровно то правило, по которому `material_source` и `garment_source` не были
-- сведены в одну колонку. Сторож `attachmentLimits.test.ts` знает про оба
-- бакета и требует совпадения ТОЛЬКО от величин ERP.

-- КОММЕНТАРИЯ НА ТАБЛИЦУ ЗДЕСЬ НЕТ, и это не упущение: `storage.buckets`
-- принадлежит `supabase_storage_admin`, а `comment on table` требует ВЛАДЕНИЯ —
-- первая редакция миграции упала на нём с 42501 «must be owner of table
-- buckets». UPDATE строки при этом проходит: право на запись и право на DDL —
-- разные вещи. Да и вешать свой комментарий на системную таблицу платформы
-- значило бы затереть её собственный.
update storage.buckets
   set file_size_limit = 20971520   -- 20 * 1024 * 1024
 where id = 'erp-attachments';
