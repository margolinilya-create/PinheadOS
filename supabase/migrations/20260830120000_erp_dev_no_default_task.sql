-- Правки заказчика 30.08, п. 3 — «убрать обязательные задачи этапов».
--
-- ЧТО ПРОСИТ ДОКУМЕНТ. «Убрать автоматическое создание задач для обязательных
-- этапов основного маршрута разработки. Этапы „Построение лекал", „Крой",
-- „Нанесения", „Пошив" и „Финальный этап" вести только как этапы маршрута
-- и перемещать по канбану. В блоке „Задачи этапов" оставить только
-- дополнительные внутренние задачи экспериментального цеха».
--
-- ПОЧЕМУ ЭТО ПРАВИТСЯ НА СЕРВЕРЕ, А НЕ В КЛИЕНТЕ. Дефолт живёт в самой функции
-- (`coalesce(p_tasks, '[{"task_type":"patterns"…}]')`), то есть задача
-- появляется у ЛЮБОГО, кто зовёт `erp_experimental_create` без списка задач.
-- Убрать её передачей пустого массива из `createExperimental` значило бы
-- оставить дефолт заряженным для следующего вызывающего — а он был бы уверен,
-- что задач не заводится.
--
-- ЧТО СЛОМАЛОСЬ БЫ, ОСТАВЬ МЫ ДЕФОЛТ. Документ описывает ровно то, что было:
-- этап «Построение лекал» закрывался ДВУМЯ способами — кнопкой этапа и
-- действием «Готово» в задаче, — после чего система ещё и спрашивала результат
-- этапа. Одна работа, три места закрытия.
--
-- ЧТО НЕ МЕНЯЕТСЯ. `erp_experimental_add_tasks` остаётся: дополнительные
-- задачи технолог заводит руками, а задачи НАНЕСЕНИЙ заводит вход в шаг
-- «Нанесения» — это не «обязательная задача этапа», а передача работы
-- в цех (у неё есть `stage_id`, её видит очередь цеха, и её закрытие
-- считает серверный автопереход `erp_dev_branding_advance`). Убери мы и их,
-- цех не получил бы работу вовсе.
--
-- Текст функции взят из её ДЕЙСТВУЮЩЕГО определения (миграция
-- 20260820160000); изменена ровно одна строка — дефолт `p_tasks`.

create or replace function public.erp_experimental_create(
  p_order_id  uuid,
  p_item_id   uuid,
  p_tech_name text default null,
  p_tasks     jsonb default null
)
returns public.erp_experimental
language plpgsql security invoker set search_path = public as $$
declare
  v_dev public.erp_experimental;
begin
  insert into public.erp_experimental (order_id, item_id, tech_name)
  values (p_order_id, p_item_id, nullif(btrim(coalesce(p_tech_name, '')), ''))
  returning * into v_dev;

  -- Пустой список по умолчанию: обязательных задач у этапов маршрута больше
  -- нет. Явно переданный `p_tasks` по-прежнему заводится — им пользуются
  -- сценарии, которым стартовые задачи действительно нужны.
  perform public.erp_experimental_add_tasks(v_dev.id, coalesce(p_tasks, '[]'::jsonb));

  return v_dev;
end $$;

grant execute on function public.erp_experimental_create(uuid, uuid, text, jsonb)
  to authenticated;

comment on function public.erp_experimental_create(uuid, uuid, text, jsonb) is
  'Создание разработки вместе со стартовыми задачами одной транзакцией. Задач по умолчанию НЕТ (правка 30.08, п. 3): этапы маршрута ведутся канбаном, а блок «Задачи этапов» — только дополнительная работа технолога.';
