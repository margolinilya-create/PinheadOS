-- Заказ-образец заводит разработку: INSERT гейтится ДВУМЯ правами.
--
-- ── Что сломано ──
--
-- `ordersSlice.createOrder` после создания заказа-образца сразу заводит
-- разработку в экспериментальном цехе, чтобы её не создавали руками. Но
-- политика вставки стоит на `experimental.manage`, а заказы заводят менеджер
-- и диспетчер — у них этого права нет. INSERT падает 42501 МОЛЧА (ошибка
-- гасится тостом, заказ уже создан и возвращён), и получается заказ-образец
-- без разработки.
--
-- В данных: 21 активная позиция-образец, у 15 разработки нет. То есть дефект
-- не гипотетический — он сработал в трёх случаях из четырёх.
--
-- ── Почему право, а не перенос в erp_create_order ──
--
-- Перенести создание внутрь `erp_create_order` можно, но это правка самого
-- старого и самого нагруженного RPC раздела ради одной строки. Расширение
-- политики честнее по смыслу: кто заводит заказ-образец, тот заводит и его
-- разработку. Ведёт её потом технолог — все остальные действия (задачи,
-- передача в цех, исход) остаются под `experimental.manage`.
--
-- Это тот же приём, что у складских задач (20260810290000): INSERT под двумя
-- правами, потому что запись создаёт не тот, кто с ней потом работает.
--
-- ── Чего НЕ делаем ──
--
-- Массовый бэкфилл 15 осиротевших позиций. Он создал бы 15 пустых разработок
-- без задач — то есть мусор, который придётся разбирать руками. Экран вместо
-- этого показывает список «позиций-образцов без разработки» с кнопкой
-- «+ Разработка»: человек заведёт те, которые ещё актуальны.

drop policy if exists erp_experimental_insert on public.erp_experimental;
create policy erp_experimental_insert on public.erp_experimental
  for insert to authenticated
  with check (
    public.erp_has_permission('experimental.manage')
    or public.erp_has_permission('order.manage')
  );

comment on table public.erp_experimental is
  'Разработка изделия в экспериментальном цехе. Ведёт технолог (experimental.manage); ЗАВОДИТ её тот, кто создаёт заказ-образец (order.manage) — иначе авто-создание при создании заказа падало 42501 молча.';
