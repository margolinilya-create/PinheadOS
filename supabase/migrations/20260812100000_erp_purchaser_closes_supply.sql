-- Закупщик закрывает СВОЙ этап маршрута (правки заказчика 12.08).
--
-- ── Что сломано ──
--
-- Заказ с маршрутом, начинающимся с «Закупки», не появляется в разделе закупки,
-- и весь маршрут стоит. Сломано не одно место, а четыре; это миграция для
-- четвёртого — прав.
--
-- Этап `supply` — обычная строка `erp_item_stages`, и закрывается он тем же
-- переходом в `done`, что любой другой этап. Значит, страж `erp_stage_guard`
-- спрашивает `stage.complete`. У роли «Закупщик» на боевой базе стоят ровно три
-- права: `material.receive`, `warehouse.manage`, `stage.block`. То есть человек,
-- ради которого раздел существует, физически не может сдвинуть свой этап:
-- ветка `new.status = 'done'` требует `v_complete or v_progress`, и он получает
-- 42501.
--
-- Сегодня это не проявляется только потому, что заказчик тестирует директором
-- (у него все права), а настоящей учётной записи закупщика в системе нет вовсе:
-- в `erp_employees` две строки, и та, что привязана к цеху `supply`, заведена
-- с ролью `worker` и без `profile_id`. Дефект ждёт того дня, когда закупщика
-- заведут по-настоящему.
--
-- ── Что даём и почему именно это ──
--
-- `stage.complete` — закрыть закупку по заказу («материалы получены» либо
-- «материалы не требуются»). Это и есть работа участка.
--
-- `stage.take` — взять закупку в работу. Без него у закупки нет состояния
-- «этим уже занимаются»: пункт 6 документа заказчика просит корректных статусов
-- НА КАЖДОМ этапе, а этап, который умеет только «не начат» и «закрыт», такого
-- статуса не имеет. Право проведено до кнопки в разделе «Закупка» тем же
-- коммитом — декоративным оно не остаётся.
--
-- `stage.progress` НЕ даём: результат в штуках у закупки не считается, тираж
-- она не выпускает. Приход материала частями ведёт свой журнал
-- (`erp_material_receipts`) под `material.receive`.
--
-- `stage.defect` НЕ даём: возврат брака откатывает производственный маршрут,
-- это решение цеха и менеджера, а не снабжения.
--
-- ── Кладовщика это не касается ──
--
-- У `storekeeper` тот же набор прав, и соблазн «дать обоим» есть. Но этапа
-- в маршруте у склада нет: складские задачи живут в `erp_warehouse_tasks`
-- и уже гейтятся `warehouse.manage`. Право, которое ничего не открывает, —
-- это ровно та декоративность, от которой избавлялись 10.08.
--
-- ── Принадлежность цеху проверяется отдельно ──
--
-- `erp_stage_guard` спрашивает ещё и `erp_can_act_in_dept(old.department_id)`.
-- Закупщик без привязки к цеху проходит (fail-open, зеркало `canActInDept`),
-- с привязкой — обязан быть привязан к `supply`. Это заводится в админке,
-- миграцией не решается: реальных людей в таблице сотрудников пока нет.

update public.erp_role_permissions
   set allowed = true
 where role = 'purchaser'
   and permission in ('stage.complete', 'stage.take');

-- Страховка на случай, если строки в матрице нет вовсе: `erp_has_permission`
-- на отсутствующую строку отвечает «запрещено», и UPDATE выше её не создаст.
insert into public.erp_role_permissions (role, permission, allowed)
select 'purchaser', p, true
  from (values ('stage.complete'), ('stage.take')) as v(p)
on conflict (role, permission) do update set allowed = true;
