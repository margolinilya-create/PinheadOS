-- Канбан ЭКС: между «Построением лекал» и «Кроем» появляется собственный шаг
-- «Ожидает материалы». Правка заказчика 01.09, п. 1.
--
-- ЧТО ПРОСИТ ДОКУМЕНТ. «Если по заказу есть закупка и материал ещё не получен,
-- система должна разрешить перенести карточку только в „Ожидает материалы".
-- Сразу в Крой перенести нельзя… Из „Ожидает материалы" технолог также сама
-- переносит карточку в Крой, но система должна разрешать это только после
-- того, как закупка завершена и материал получен».
--
-- ПОЧЕМУ ЭТО НЕ ДОРОЖКА, А КОЛОНКА. Дорожка `awaiting_materials` внутри колонки
-- существует с волны материального гейта и отвечает на вопрос «что с работой».
-- Здесь спрашивают другое: КУДА технолог вправе перенести карточку. До 01.09
-- ответ был «никуда» — выход с лекал при незавершённой закупке блокировался
-- целиком, и карточка стояла в «Лекалах» вместе с уже сделанной работой.
-- Отсюда и ключ `materials`, а не `awaiting_materials`: одноимённые колонка
-- и дорожка читались бы как одно и то же в двух разных перечислениях.
--
-- ШАГ НЕОБЯЗАТЕЛЬНЫЙ. Заказ без закупки (или с уже принятым материалом) идёт
-- «Лекала → Крой» напрямую — документ разрешает это прямым текстом. Поэтому
-- значение вводится В CHECK, но ни в каком бэкфилле не участвует: у заведённых
-- раньше разработок `board_stage` остаётся прежним, и доска для них не меняется.
--
-- СТРАЖА ПОСЛЕДОВАТЕЛЬНОСТИ НА СЕРВЕРЕ НЕТ, и это названо вслух (решение
-- заказчика 01.09). `board_stage` пишет тот, у кого есть право
-- `experimental.manage`, то есть сам технолог: запрет перескакивать этапы —
-- защита от ошибки, а не от обхода прав. Серверная копия потребовала бы второй
-- реализации правил «есть ли у заказа нанесения» и «принят ли материал»,
-- а расходящиеся копии одного правила проект уже ловил не раз.

-- CHECK перечисляет ровно те шаги, что и `DevStage` на клиенте; сверяет их
-- сторож `pinhead-react/src/erp/utils/devBoardStage.test.ts`. Значение вне
-- перечня означало бы карточку, которой нет ни в одной колонке, — то есть
-- исчезнувшую с доски разработку.
alter table public.erp_experimental
  drop constraint if exists erp_experimental_board_stage_check;
alter table public.erp_experimental
  add constraint erp_experimental_board_stage_check
  check (board_stage is null
         or board_stage in ('patterns', 'materials', 'cutting',
                            'branding', 'sewing', 'final'));

