-- РАЗБОР УЖЕ ЗАВЕДЁННЫХ ЗАДАЧ ПРИЁМКИ (правка 12.09, вторая порция, баг 01).
--
-- ПРАВКА КОДА НЕ ЧИНИТ УЖЕ ЗАВЕДЁННЫЕ ДАННЫЕ. Задачи, появившиеся по прежнему
-- правилу (запуск закупки), остаются на экране склада и продолжают предлагать
-- принять материал, которого никто не отправлял, — то есть жалоба заказчика
-- никуда не денется, сколько ни правь триггер.
--
-- СОСТОЯНИЕ БОЕВОЙ БАЗЫ НА 12.09 (задачи `material_receipt` вне `accepted`):
--   · d761760f… — материал 7a831d22… в статусе `pending`   → снять
--   · f0e8b8a4… — материал 877597d2… в статусе `ordered`   → снять
--   · e71f2ea7… — у заказа нет ни одной позиции закупки    → снять
--   · 5fb665aa… — материал a2fd8e3e… `in_transit`          → привязать
--
-- ЗАКРЫТЫЕ ЗАДАЧИ НЕ ТРОГАЕМ. `accepted` — это история: материал принят,
-- строка журнала написана, и переписывать её задним числом значило бы
-- утверждать, что приёмки не было. `material_id` у них остаётся пустым,
-- и карточка по-прежнему покажет их как приёмку по заказу целиком.
--
-- ИДЕМПОТЕНТНО: обе операции отбирают строки по СОСТОЯНИЮ, а не по списку
-- идентификаторов, и повторный прогон ничего не меняет.

-- 1. Привязать открытую задачу к позиции, которая действительно в пути.
--    Если таких позиций у заказа несколько, берём самую раннюю: остальные
--    получат свои задачи собственным переходом статуса.
--    Коррелированным подзапросом, а не `from lateral`: в `UPDATE ... FROM`
--    целевая таблица из бокового подзапроса не видна (42P10).
update public.erp_warehouse_tasks t
   set material_id = (
     select m.id from public.erp_materials m
      where m.order_id = t.order_id and m.status = 'in_transit'
      order by m.created_at
      limit 1)
 where t.task_type = 'material_receipt'
   and t.material_id is null
   and t.status <> 'accepted';

-- 2. Снять открытые задачи, у которых в пути нет ничего: их не должно было
--    существовать вовсе. Именно DELETE, а не терминальный статус: «принято»
--    было бы неправдой о материале, которого склад не видел, а отдельного
--    значения «заведена по ошибке» у складских задач нет и заводить его ради
--    разовой чистки не стоит — на экране остались бы карточки-призраки.
delete from public.erp_warehouse_tasks t
 where t.task_type = 'material_receipt'
   and t.material_id is null
   and t.status <> 'accepted';
