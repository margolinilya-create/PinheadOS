-- Кладовщик закрывает СВОЙ этап приёмки готового изделия (правки 07.09, п. 9).
--
-- ЗАПРЕТ СНЯТ, ПОТОМУ ЧТО ИЗМЕНИЛСЯ ВОПРОС. До 07.09 у склада не было
-- ни одного этапа маршрута, и `stage.complete` кладовщику не давалось
-- осознанно: право, которое ничего не открывает, — декоративное. Теперь
-- у готового изделия с нанесением маршрут начинается с приёмки на складе
-- (`buildRoute`, участок `warehouse`), и без этой пары прав кладовщик получал
-- бы 42501 от `erp_stage_guard` на работе, ради которой этап и заведён —
-- ровно тот отказ, который 12.08 чинили закупщику на этапе «Закупка».
--
-- ПРАВО ОГРАНИЧЕНО ЦЕХОМ: `storekeeper` входит в `DEPT_BOUND_ROLES`, то есть
-- `erp_can_act_in_dept` пускает его только на этапы своего участка,
-- а производственных этапов у склада нет ни одного.
--
-- Матрица — источник правды НА СЕРВЕРЕ (`erp_has_permission`);
-- `DEFAULT_PERMISSIONS` действует, только пока она не загрузилась, и
-- расхождение двух даёт «кнопка есть, действие падает». Сторож —
-- `permissionsCoverage.test.ts`.
insert into public.erp_role_permissions (role, permission, allowed)
values
  ('storekeeper', 'stage.take', true),
  ('storekeeper', 'stage.complete', true)
on conflict (role, permission) do update set allowed = excluded.allowed;
