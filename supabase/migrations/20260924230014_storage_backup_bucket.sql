-- Приватный бакет для ночной копии Storage (сессия 68).
--
-- ЗАЧЕМ. Бэкап файлов делался архивом в артефакты GitHub Actions, и первый
-- же зелёный прогон (#58, 24.09) выдал архив ВСЕХ файлов в артефакты
-- публичного репозитория — их скачивает любой вошедший на GitHub, — а в лог
-- путь каждого объекта публичного бакета. В приватном репозитории та же схема
-- упирается в квоту артефактов: 398 МБ каждую ночь × 30 дней. Копия
-- переезжает внутрь проекта: workflow копирует объекты серверным `copy`
-- в этот бакет, только новые, без путей в логе (`.github/workflows/storage-backup.yml`).
--
-- ПРИВАТНОСТЬ. `public = false`, и политик `storage.objects` для этого бакета
-- НЕТ: все существующие политики привязаны к своим бакетам условием
-- `bucket_id = '…'` (сверено 24.09), поэтому anon и authenticated не видят
-- здесь ни одного объекта. Читать и писать может только service_role —
-- ровно тот ключ, что лежит в секретах workflow. Сторож —
-- `pinhead-react/src/erp/utils/storageBackup.test.ts`: он требует, чтобы
-- ни одна политика ни в одной миграции не упоминала этот бакет.
--
-- ЛИМИТ РАЗМЕРА не задаётся (`null` — действует общий лимит проекта): копия
-- обязана принять всё, что принял рабочий бакет, а лимиты рабочих бакетов
-- (20 и 15 МБ) могут со временем расти.
--
-- `storage-gc` этот бакет не трогает — он работает только с `erp-attachments`.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('storage-backup', 'storage-backup', false, null, null)
on conflict (id) do update
  set public = false;
