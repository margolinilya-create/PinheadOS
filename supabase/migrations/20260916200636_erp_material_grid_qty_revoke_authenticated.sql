-- ДОЗАКРЫТИЕ ТРИГГЕРНОЙ ФУНКЦИИ `erp_material_grid_qty()` (к 20260916194500).
--
-- Предыдущая миграция отозвала EXECUTE `from public, anon` — и сторож
-- репозитория стал зелёным, потому что читает ТЕКСТ миграции. А живая база
-- показала другое: в ACL остался `authenticated=X/postgres`, то есть функция
-- по-прежнему вызывалась ролью вошедшего через `/rest/v1/rpc/…`.
--
-- ЭТО ТОТ САМЫЙ СЛУЧАЙ, О КОТОРОМ ГОВОРИТ ПРАВИЛО «СВЕРЯЙТЕ С ЖИВОЙ БАЗОЙ,
-- А НЕ С ФОРМУЛИРОВКОЙ». Обычная формула проекта — `from public, anon` —
-- верна для функций, которым право приходит ТОЛЬКО от PUBLIC. Здесь роль
-- `authenticated` держит собственный грант (его выдаёт `grant execute on all
-- functions in schema public`), и наследование тут ни при чём: своё право
-- отзывается только явно.
--
-- Канон раздела виден в самой базе: у всех прочих триггерных функций ACL —
-- ровно `{postgres, service_role}`. Приводим к нему.
--
-- Дыры не было и до правки: прямой вызов триггерной функции Postgres
-- отклоняет сам («trigger functions can only be called as triggers»). Дефект
-- в другом — в постоянном предупреждении адвизора, за которым теряется
-- настоящее, и в расхождении с каноном, по которому следующий будет
-- ориентироваться.

revoke execute on function public.erp_material_grid_qty() from public, anon, authenticated;
