-- Крой изделия подсказывает КАТАЛОГ, а не справочник.
--
-- РЕШЕНИЕ ЗАКАЗЧИКА: каталог SKU — источник правды по ассортименту, а
-- `erp_dictionaries` остаётся под то, чего в каталоге нет вовсе (поставщики,
-- единицы измерения, причины блокировок, типы проблем, операции маршрута).
--
-- ПОЧЕМУ СНИМАЕТСЯ ИМЕННО `fit`, А `product_type` ОСТАЁТСЯ. Перед миграцией
-- содержимое сверено с боевой базой — это отдельное требование плана, потому
-- что сужение CHECK отбирает подсказки безвозвратно:
--
--   · `fit` в справочнике: Regular, Oversize, Free Fit. В каталоге SKU кроя
--     четыре — classic, free, oversize, regular, то есть каталог покрывает
--     справочник ЦЕЛИКОМ и даже шире. Снятие ничего не отнимает;
--   · `product_type` в справочнике: Футболка, Лонгслив, Худи, Свитшот, Шоппер —
--     все есть в каталоге, НО ещё Рубашка, Фартук и Кепка, которых в каталоге
--     нет ни одной. Снять вид целиком значило бы молча отобрать у менеджера
--     три изделия, которые он заводит. Поэтому вид остаётся, а в интерфейсе
--     каталог идёт первым и дополняется справочником (`CatalogDatalist`).
--
-- Значения `fit` УДАЛЯЮТСЯ, а не отключаются, и это не спорит с правилом
-- «значения отключаются»: правило защищает историю, а справочник кроя —
-- только подсказка. В заказе крой хранится ТЕКСТОМ (`erp_order_items.fit`),
-- внешнего ключа нет, и уже заведённые позиции миграция не задевает вовсе.
-- Отключением здесь не обойтись: CHECK сузить нельзя, пока строки вида есть.
--
-- Вид справочника живёт в ЧЕТЫРЁХ местах (правило проекта): этот CHECK,
-- `DictionaryKind`, подпись с подсказкой и `KINDS` в админке. Сторож —
-- `erp/utils/dictionaryKinds.test.ts`.

delete from public.erp_dictionaries where kind = 'fit';

alter table public.erp_dictionaries
  drop constraint if exists erp_dictionaries_kind_check;
alter table public.erp_dictionaries
  add constraint erp_dictionaries_kind_check
  check (kind in ('block_reason', 'problem_type', 'product_type', 'supplier',
                  'unit', 'experimental_task_type', 'route_operation'));
