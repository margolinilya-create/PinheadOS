-- Файлы ТЗ и макетов принимаются в любом формате (правка 12.09, п. 4).
--
-- «В блоках загрузки файлов ТЗ и макета нанесения есть ограничения по
-- форматам, из-за чего часть рабочих файлов нельзя загрузить в ERP…
-- Ограничения по максимальному размеру файла и стандартные проверки
-- безопасности можно оставить».
--
-- ЧТО ИМЕННО ОТКАЗЫВАЛО. Ограничение стояло в ЧЕТЫРЁХ слоях, и снимать надо
-- все: `accept` у полей (диалог просто не показывал файл), проверка типа
-- в клиенте (`tzSlice.checkFile`, `CreateOrderModal.addTzDoc`), жёсткий
-- `contentType: application/pdf` при загрузке ТЗ — и вот этот, последний
-- и самый незаметный: `allowed_mime_types` на самом бакете. Снять первые
-- три и оставить четвёртый значило бы получить отказ Storage уже ПОСЛЕ
-- выбора файла — то есть худший вид поломки: интерфейс показывает файл
-- приложенным, а в бакете его нет.
--
-- Заодно это чинит расхождение, жившее с 20.08: лист закупки предлагает
-- выбрать .xlsx/.csv/.ods (`PurchaseListSection`), а бакет принимал только
-- PDF и картинки — такой файл молча вставал в состояние `error`.
--
-- ЧТО ОСТАЁТСЯ. `file_size_limit` = 15 МБ (та же величина, что `TZ_MAX_BYTES`
-- в клиенте) и политики записи под `erp_is_member()`: писать по-прежнему
-- может только активный и одобренный участник ERP. Это и есть названные
-- в правке «стандартные проверки безопасности». Снимается ровно перечень
-- типов, а не контроль доступа и не размер.
--
-- ЧЕМ ПЛАТИМ, СКАЗАНО ВСЛУХ. Бакет публичный на чтение, и с этой правкой
-- участник ERP может положить туда файл любого типа, доступный по вечной
-- ссылке. Довод «хостинг произвольного контента под доменом компании»
-- (20260729120000) остаётся верным — но он про ЛЮБОГО авторизованного,
-- а запись с тех пор сужена до `erp_is_member()`. Цена принята осознанно:
-- цех не может работать, когда рабочий файл нельзя приложить.

update storage.buckets
   set allowed_mime_types = null
 where id = 'erp-attachments';

