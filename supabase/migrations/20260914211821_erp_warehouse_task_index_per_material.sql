-- ЗАДАЧА ПРИЁМКИ ПРИНАДЛЕЖИТ ПОЗИЦИИ, И УНИКАЛЬНОСТЬ ОБЯЗАНА ЗНАТЬ ОБ ЭТОМ
-- (правка заказчика 14.09, п. 4).
--
-- Документ: «при наличии нескольких материалов в одной закупке первый материал
-- переводится в статус „В пути", а второй перевести не получается… Текущая
-- ошибка: duplicate key value violates unique constraint». Имя в документе
-- искажено (`grp_…`); настоящее — `erp_warehouse_tasks_order_type_idx`.
--
-- ЧТО ПРОИСХОДИТ. Индекс заведён `20260722120000` под правило «одна задача
-- каждого типа на заказ» и переопределён частичным в `20260820130000`:
--
--     unique (order_id, task_type) where stage_id is null
--
-- Тогда это было верно: приёмка материалов была ОДНА на заказ. Правка 12.09
-- (`20260912232217`) сделала её ПОЗИЦИОННОЙ — `erp_material_receipt_task`
-- вставляет строку `(order_id, material_id, 'material_receipt')`, и `stage_id`
-- у неё пуст, то есть строка попадает ровно под этот предикат. Ключ второго
-- материала того же заказа совпадает с ключом первого — 23505.
--
-- Собственная защита писателя от дубля тут не помогает и не должна: она
-- спрашивает «нет ли задачи у ЭТОГО материала», и для второго материала
-- честно отвечает «нет».
--
-- ЧИНИТСЯ ПРЕДИКАТОМ, А НЕ СНЯТИЕМ ИНДЕКСА. Правило «одна задача типа
-- на заказ» по-прежнему верно для маркировки, приёмки готовой продукции
-- и упаковки — их писатели (`erp_warehouse_task_derive`,
-- `erp_ensure_order_finish_tasks`, `erp_warehouse_fg_accepted`) на него
-- опираются. Из-под индекса выводятся ровно ПОЗИЦИОННЫЕ задачи, у которых
-- уже есть своя уникальность — `erp_warehouse_tasks_material_idx (material_id)
-- where task_type = 'material_receipt'`, заведённая той же правкой 12.09.
--
-- ПРОВЕРЕНО НА БОЕВОЙ БАЗЕ 14.09 перед правкой:
--   · задач `material_receipt` две, у обеих `material_id` заполнен и заказы
--     разные — дублей нет, бэкфилл не нужен;
--   · `on conflict (order_id, task_type)` не осталось ни в одном действующем
--     определении функций (снято через `pg_get_functiondef`), поэтому смена
--     предиката ничего не ломает выводом индекса: у частичного индекса голый
--     `ON CONFLICT` по колонкам не выводится, и это в проекте уже ловили.

drop index if exists public.erp_warehouse_tasks_order_type_idx;

create unique index if not exists erp_warehouse_tasks_order_type_idx
  on public.erp_warehouse_tasks (order_id, task_type)
  where stage_id is null and material_id is null;

comment on index public.erp_warehouse_tasks_order_type_idx is
  'Одна задача каждого вида на заказ — для задач, принадлежащих ЗАКАЗУ целиком (маркировка, приёмка ГП, упаковка). Позиционные задачи приёмки материалов (material_id заполнен) под него не подпадают: у них своя уникальность erp_warehouse_tasks_material_idx, и двум материалам одного заказа нужны две задачи.';
