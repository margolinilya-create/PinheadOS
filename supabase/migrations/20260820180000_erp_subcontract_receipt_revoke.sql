-- Триггерная функция приёмки подряда осталась вызываемой через REST.
--
-- ЧТО СЛУЧИЛОСЬ. `20260820130000` завела `erp_subcontract_returned_receipt()`
-- и отозвала у неё EXECUTE `from public, anon` — по правилу проекта «`from anon`
-- в одиночку не работает, право приходит от PUBLIC». Правило верное, но
-- НЕПОЛНОЕ: у Supabase роль `authenticated` получает EXECUTE ещё и ПРЯМЫМ
-- грантом (default privileges схемы), и отзыв у PUBLIC его не снимает.
-- Обход `20260812160000` это учитывал — `from public, anon, authenticated`, —
-- а отдельный отзыв повторил только половину.
--
-- Дыры нет: Postgres сам отклоняет прямой вызов триггерной функции. Но
-- предупреждение адвизора висит постоянно, а за постоянным шумом теряется
-- настоящее — ровно то, ради чего обход и писали.
--
-- Сторож усилен вместе с правкой: `triggerFunctionsRevoked.test.ts` проверял
-- ЛИШЬ НАЛИЧИЕ отзыва, поэтому зелёным он был и с половинным. Тест, который
-- слабее своего названия, опаснее его отсутствия.
revoke execute on function public.erp_subcontract_returned_receipt()
  from public, anon, authenticated;
