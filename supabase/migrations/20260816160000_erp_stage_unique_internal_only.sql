-- Уникальность этапа перестаёт мешать нескольким подрядным этапам подряд
-- (правки заказчика 16.08, блок 2).
--
-- ЗАЧЕМ. Документ прямо описывает маршрут с НЕСКОЛЬКИМИ подрядными этапами
-- на одной позиции («несколько подрядчиков подряд»), в том числе с одним и тем
-- же цехом-владельцем: сублимацию и упаковку принимает один и тот же участок.
-- Полный индекс `(item_id, department_id, cycle)` разрешает ровно один такой
-- этап и отвечал бы 23505 на втором.
--
-- Наши этапы уникальность СОХРАНЯЮТ: она защищает от повторного заведения
-- этапа при переносе между цехами и при возврате из подряда, и ослаблять её
-- незачем — «два закроя в одном проходе» это ошибка, а не сценарий.
--
-- ПОРЯДОК ЗДЕСЬ КРИТИЧЕН, И ОН СОБЛЮДЁН. Частичный индекс нельзя класть, пока
-- в клиенте жив `upsert(onConflict: 'item_id,department_id,cycle')`: PostgREST
-- шлёт голый `ON CONFLICT (col, col)`, а целевой индекс Postgres выводит только
-- из списка колонок — частичный подойдёт лишь если в ON CONFLICT продублирован
-- его предикат, чего PostgREST не умеет. Спецификация проверяется при
-- ПЛАНИРОВАНИИ запроса, до поиска конфликта, поэтому «дубля же не будет»
-- не спасает: 42P10 приходит на каждый вызов. Единственный такой upsert
-- (возврат подряда в `subcontractingSlice`) снят тем же коммитом и заменён
-- явной проверкой существования. Сторожит `upsertConflict.test.ts`.
drop index if exists public.erp_item_stages_item_dept_cycle_key;

create unique index erp_item_stages_item_dept_cycle_key
  on public.erp_item_stages (item_id, department_id, cycle)
  where coalesce(executor, 'internal') = 'internal';

comment on index public.erp_item_stages_item_dept_cycle_key is
  'Один этап на (позиция, цех, проход) — только для НАШИХ этапов. Подрядных на одну позицию может быть несколько, в том числе с общим цехом-владельцем (сублимация и упаковка возвращаются на один участок).';
