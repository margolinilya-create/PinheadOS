-- Инвариант: закрыт — значит есть время завершения. И наоборот.
--
-- НАШЛОСЬ НАГРУЗОЧНЫМ ПРОГОНОМ 11.08 (docs/2026-08-11-load-test.md).
-- 44 этапа из 132 закрытых стоят в `done` с пустым `finished_at`, и ещё один —
-- в `in_progress` с проставленным. У всех 44 пусто и `started_at`, ни у одного
-- нет записи в ленте событий, и все датированы двумя днями — 27.07 и 03.08,
-- днями миграций. То есть это наследие заливки данными, а не живой путь:
-- 5110 этапов нагрузочного прогона, прошедшие через настоящие действия,
-- не дали НИ ОДНОЙ такой строки.
--
-- Следствие настоящее: время цикла, факт в плане и любой ответ на вопрос
-- «сколько это заняло» считаются по данным, которых у трети закрытых этапов нет.
--
-- ПОЧЕМУ НОРМАЛИЗАЦИЯ, А НЕ ЗАПРЕТ. Отказ (CHECK или ветка в стороже) — это
-- «кнопка есть, действие падает»: сегодня все три пути записи время ставят,
-- но `erp_stage_apply_defect` принимает статус ПАТЧЕМ, и достаточно одного
-- патча с `status='done'` без времени, чтобы у цеха отвалилось закрытие этапа.
-- Инвариант формы данных дешевле выполнить, чем сторожить: триггер
-- дописывает недостающее и не может ничего заблокировать.
--
-- ПОЧЕМУ ЗДЕСЬ, А НЕ ОТДЕЛЬНЫМ ТРИГГЕРОМ. `erp_clamp_stage_qty` уже нормализует
-- строку этапа перед записью (обрезает счётчики) и стоит BEFORE INSERT/UPDATE.
-- Четвёртый BEFORE-триггер на той же таблице означал бы, что порядок
-- нормализаций зависит от алфавита имён.
--
-- `skipped` НЕ ТРОГАЕМ ни в одну сторону: пропуск — терминальный статус, но
-- не «выполнено», и что там значит время завершения, решает не этот файл.
-- `started_at` тоже не восстанавливаем: он ставится один раз при первом входе
-- в работу, и этап, закрытый с доски напрямую, законно не имеет его вовсе.

-- ── 1. Бэкфилл: время завершения там, где этап закрыт ────────────────────────
-- Берём `updated_at` — последнее изменение строки. Это приближение, и оно
-- названо приближением: точного времени не существует нигде, лента событий
-- у этих строк пуста. Лучше приблизительное время, чем отсутствие времени,
-- по которому метрика молча считает по неполной выборке.
update erp_item_stages
   set finished_at = updated_at
 where status = 'done' and finished_at is null;

-- ── 2. Зеркальный случай: этап в работе с проставленным завершением ──────────
-- Переоткрытый после брака этап сохранил время закрытия — по нему выходило,
-- что задание одновременно идёт и уже сдано.
update erp_item_stages
   set finished_at = null
 where status in ('waiting', 'ready', 'in_progress', 'blocked')
   and finished_at is not null;

-- ── 3. Впредь — нормализацией, не договорённостью ────────────────────────────
-- Текст функции взят ПОДЛИННЫЙ (pg_get_functiondef), добавлен один блок:
-- правило проекта — пересоздаёшь функцию целиком, не пиши её по памяти.
create or replace function public.erp_clamp_stage_qty()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $$
declare v_qty int;
begin
  select qty into v_qty from public.erp_order_items where id = new.item_id;
  if v_qty is not null then
    if new.qty_done < 0 then new.qty_done := 0; end if;
    if new.qty_done > v_qty then new.qty_done := v_qty; end if;
  end if;
  if new.qty_rework < 0 then new.qty_rework := 0; end if;

  -- Закрыт — значит есть время завершения; вернулся в работу — значит нет.
  -- `skipped` не участвует: это терминальный статус, но не «выполнено».
  if new.status = 'done' and new.finished_at is null then
    new.finished_at := now();
  elsif new.status in ('waiting', 'ready', 'in_progress', 'blocked')
        and new.finished_at is not null then
    new.finished_at := null;
  end if;

  return new;
end $$;
