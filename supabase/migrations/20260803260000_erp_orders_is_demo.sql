-- Тестовые заказы отделяются от боевых флагом, а не удалением.
--
-- На 03.08.2026 в проде 36 заказов из 147 — тестовые («СТАС ТЕСТ 2.0»,
-- «Тест новый», «стас тест проработка», «Тест прораб»), из них 26 активных.
-- Это треть рабочего списка: они раздували счётчики цехов, попадали
-- в «горящие сроки» и в уведомления о просрочке. Удалять их нельзя —
-- на них проверялись сценарии, и история этапов по ним осмысленна.
--
-- Решение заказчика 03.08.2026: флаг + фильтр в интерфейсе. По умолчанию
-- демо скрыто, переключатель показа — у admin/director. Ничего не удаляется
-- и ничего не переводится в архив: заказ остаётся ровно там, где был.
--
-- Флаг НЕ проставляется этой миграцией автоматически по имени. Эвристика
-- «в названии есть „тест“» ошибётся на настоящем заказе — например, на пробной
-- партии для клиента, — а молча спрятать боевой заказ хуже, чем показать
-- тестовый. Разметку делает человек в админке.

alter table public.erp_orders
  add column if not exists is_demo boolean not null default false;

comment on column public.erp_orders.is_demo is
  'Тестовый/демонстрационный заказ. По умолчанию скрыт в интерфейсе; ставится вручную.';

-- Частичный индекс: боевые списки всегда спрашивают `is_demo = false`,
-- и класть в индекс демо-строки незачем.
create index if not exists erp_orders_not_demo_idx
  on public.erp_orders (status, due_date)
  where is_demo = false;
