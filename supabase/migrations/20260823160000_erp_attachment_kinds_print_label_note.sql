-- Виды вложений `print`, `label`, `note` в CHECK базы (правки 22.08, пп. 5.2–5.3, 5.8).
--
-- НАЙДЕНО ПРОВЕРКОЙ НА ЖИВОЙ БАЗЕ, а не тестами. Перечисление видов вложения
-- живёт в ДВУХ местах: `ErpAttachmentKind` на клиенте и CHECK здесь. Новые виды
-- были заведены только в первом — типы сходятся, тесты зелёные, а первая же
-- попытка приложить макет нанесения отвечает 23514, роняя СОЗДАНИЕ ЗАКАЗА
-- целиком: вложения вставляет та же транзакция, что и заказ.
--
-- Это ровно тот отказ, который в проекте уже случался с `material_source`:
-- значение `mixed` завели в одной таблице, а CHECK соседней остался на двух,
-- и заказ со смешанными материалами не создавался вообще. Правило записано
-- в CLAUDE.md — «перечисление, расширенное в одной таблице, проверьте
-- во ВСЕХ»; здесь оно нарушено и восстановлено.
--
-- Сторожит `attachmentKinds.test.ts`: он сверяет клиентский союз с CHECK
-- последней миграции, определяющей констрейнт.

alter table public.erp_order_attachments
  drop constraint if exists erp_order_attachments_kind_check;

alter table public.erp_order_attachments
  add constraint erp_order_attachments_kind_check
  check (kind in (
    'preview', 'attachment', 'packaging', 'tech', 'purchase', 'purchase_list',
    'subcontract', 'dev_pattern', 'dev_passport', 'dev_photo',
    -- Макет КОНКРЕТНОГО нанесения и файл КОНКРЕТНОЙ бирки: до правки макеты
    -- лежали общей кучей вида `tech`, и цех угадывал, какой к какому относится
    'print', 'label',
    -- Изображение заметки к заказу
    'note'
  ));
