-- ПОТОЛОК ФАКТА НА СЕРВЕРЕ — вторая половина правки 12.09 (п. 4).
--
-- Клиентское правило (`utils/stageOverPlan`) и этот страж — ОДНО правило,
-- и написаны они одним коммитом: клиент, разрешающий то, что сервер отклонит,
-- даёт «кнопка есть, действие падает»; сервер, разрешающий то, что клиент
-- запрещает, — дыру через REST.
--
-- ВЫКЛАДЫВАЕТСЯ ПОСЛЕ ФРОНТЕНДА, и это не осторожность. Страж делает сервер
-- СТРОЖЕ, а прежний бандл о потолке не знает: примени мы его раньше, цех
-- получил бы отказ на числе, которое форма приняла. Колонка и расчёт входа
-- уехали отдельной миграцией (`20260913000500`) — они аддитивны и старый
-- бандл их переживает.
--
-- Почему здесь, а не в `erp_clamp_done`: этот триггер — ПОСЛЕДНЕЕ слово для
-- любой записи `qty_done`, включая прямой UPDATE мимо RPC. Тот же урок 12.09:
-- «одну и ту же величину могут резать ДВА места».

create or replace function public.erp_clamp_stage_qty()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  v_over_plan boolean;
  v_cap       int;
begin
  if new.qty_done < 0 then new.qty_done := 0; end if;
  if new.qty_rework < 0 then new.qty_rework := 0; end if;

  -- ПОТОЛОК ФАКТА (правка 12.09, вторая порция, п. 4). Считается только
  -- когда число ВЫРОСЛО: у смены статуса, плановых дат и возврата брака
  -- `qty_done` не растёт, и лишний обход графа на каждой записи счётчика
  -- этому триггеру не нужен.
  --
  -- ПОТОЛОК — БОЛЬШЕЕ ИЗ ТИРАЖА И ПЕРЕДАННОГО, дословно по документу:
  -- «нельзя указать 101 и более» при заказе 100 и «можно работать максимум
  -- со 105», когда закрой сдал 105. Запрещено ПРЕВЫШЕНИЕ ЗАКАЗА, а не «сдать
  -- больше, чем успел предыдущий этап»: тираж цех вправе закрыть всегда.
  --
  -- Взять потолком один только вход было первой редакцией правки, и она
  -- оказалась СТРОЖЕ ИНТЕРФЕЙСА: «Завершить этап» и перенос карточки
  -- на канбане пишут `qty_done = тираж`, и у этапа, чей предшественник ещё
  -- в работе, закрытие упиралось бы в отказ. Пропуск по меткам транзакции
  -- (`erp.moving`, `erp.subcontract_rollup`) при таком потолке не нужен вовсе:
  -- ни перенос, ни приёмка подряда тиража не превышают, а если превысят —
  -- это ровно тот «плюс» мимо закроя, который документ и запрещает.
  if tg_op = 'UPDATE' and new.qty_done > coalesce(old.qty_done, 0) then
    select d.allows_over_plan into v_over_plan
      from erp_departments d where d.id = new.department_id;

    if not coalesce(v_over_plan, false) then
      select greatest(coalesce(i.qty, 0), public.erp_stage_input_qty(new.id))
        into v_cap
        from erp_order_items i where i.id = new.item_id;
      if new.qty_done > v_cap then
        raise exception
          'Больше % шт на этом этапе сдать нельзя: столько заказано или передано с закроя. Сверх заказа количество появляется только на закрое', v_cap
          using errcode = 'check_violation';
      end if;
    end if;
  end if;

  -- Закрыт — значит есть время завершения; вернулся в работу — значит нет.
  -- `skipped` не участвует: это терминальный статус, но не «выполнено».
  if new.status = 'done' and new.finished_at is null then
    new.finished_at := now();
  elsif new.status in ('waiting', 'ready', 'in_progress', 'blocked')
        and new.finished_at is not null then
    new.finished_at := null;
  end if;

  return new;
end $$;

comment on function public.erp_clamp_stage_qty() is
  'Нормализация счётчиков этапа перед записью: не ниже нуля, и факт не выше большего из тиража и переданного с предыдущего этапа — кроме участков с allows_over_plan (закрой), где и появляются «плюсы» к тиражу (правка 12.09, п. 4). Отказ, а не молчаливая обрезка: обрезанное число вызывающий видит как «сохранилось». Здесь же инвариант finished_at.';
