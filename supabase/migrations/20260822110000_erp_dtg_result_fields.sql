-- Цех DTG: форма отчёта участка, которой он не получил при заведении.
--
-- Участок завели 18.08 (`20260818203338_erp_dtg_method_and_department`), и всё
-- вокруг него сделали: перечисление `BrandingMethod`, роль в матрице прав,
-- операция маршрута, колонка в админке. А `result_fields` остался пустым —
-- у всех остальных производственных участков там 2-3 поля.
--
-- Молча это означает «отчёт не требуется»: схема отчёта живёт в данных
-- (`erp_departments.result_fields`) и пустое значение читается fail-open, ровно
-- как пустой `gate_material_kinds`. Fail-open выбран осознанно — цех не должен
-- остаться без способа сдать работу из-за незаполненной настройки, — но здесь
-- он сработал не как страховка, а как пропуск: рабочий DTG закрывает этап,
-- не вводя ни одной цифры, и в производстве не остаётся ни выпуска, ни брака.
--
-- Значения — по образцу соседних участков нанесения (`dtf`, `silkscreen`):
-- у DTG та же единица (штуки) и тот же вопрос «сколько нанесли и сколько
-- испортили». Правится потом в админке, как и у всех.

update public.erp_departments
   set result_fields = '[
     {"code":"printed","label":"Нанесено","unit":"шт","target":"qty_good","required":true},
     {"code":"defect","label":"Брак","unit":"шт","target":"qty_defect","required":false}
   ]'::jsonb
 where code = 'dtg'
   and coalesce(jsonb_array_length(result_fields), 0) = 0;
