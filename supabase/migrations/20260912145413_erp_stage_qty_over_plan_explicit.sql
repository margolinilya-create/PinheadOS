-- Фактический выпуск сверх тиража больше не теряется (правка 12.09, п. 5).
--
-- «Если на производственном этапе указать фактическое количество больше
-- количества в заказе, ERP засчитывает только плановый тираж и не сохраняет
-- превышение. Например: заказ 100 шт, фактически выполнено 105 шт — система
-- фиксирует только 100 шт… Сохранять полный фактический результат и отдельно
-- считать превышение».
--
-- ПОТОЛОК СТОЯЛ В ДВУХ МЕСТАХ, и снять надо оба. Это главное, что стоит
-- знать про эту миграцию: сними одно — правка «работает» наполовину и молча.
--
-- 1. `erp_clamp_done` (20260810180000) — общее правило приращения счётчика,
--    его зовут все пять писателей: частичная готовность, отчёт участка,
--    возврат брака и два подрядных роллапа.
-- 2. `erp_clamp_stage_qty` (последняя редакция — 20260811100000) — BEFORE-
--    триггер на самой таблице. Он обрезает ЛЮБУЮ запись `qty_done`, включая
--    прямой UPDATE клиента, и остался бы последним словом: сервер вернул бы
--    ровно 100 там, где цех сдал 105, а вызывающий увидел бы «сохранилось»
--    и не понял, почему число не то.
--
-- ФУНКЦИИ ПЕРЕПИСАНЫ ЯВНО, А НЕ ПЕРЕСОБРАНЫ ЧЕРЕЗ `pg_get_functiondef`.
-- Приём с динамической пересборкой годится для `erp_create_order` (350 строк,
-- девять секций — по памяти такое не пишут), но здесь он сделал бы функции
-- НЕВИДИМЫМИ для сторожей репозитория: `latestDefining` ищет в миграциях
-- `create or replace function public.<имя>(`, и, не найдя, читал бы прежнюю
-- редакцию — то есть подтверждал бы снятый потолок как действующий. Ровно
-- тот класс дефекта, от которого в проекте завели правило «сторож должен
-- сверяться с состоянием, а не с файлом». Обе функции короткие, и подлинный
-- текст ниже сверен с `pg_get_functiondef` боевой базы перед правкой.
--
-- ЧТО ОСТАЁТСЯ. Обрезка СНИЗУ нулём — в обеих: отрицательный факт это
-- не перевыполнение, а ошибка ввода. `erp_clamp_rework` не трогаем вовсе,
-- у переделки потолка не было и раньше (одну единицу можно вернуть в брак
-- дважды — это второй заход, а не ошибка данных).
--
-- АВТО-ЗАКРЫТИЕ ЭТАПА НЕ МЕНЯЕТСЯ. Условие `qty_done >= v_total` при 105
-- и тираже 100 по-прежнему истинно — именно поэтому потолок и можно снять,
-- не трогая ни одного из пяти вызывающих.
--
-- «ПЛЮС» НЕ ХРАНИТСЯ НИГДЕ. Он равен `max(qty_done − item.qty, 0)`, то есть
-- полностью выводится из двух уже существующих чисел. Вторая колонка рядом
-- означала бы двух писателей одной величины — на этом проект ловился дважды
-- (`qty_received` с пустым журналом, брак подряда через разность). Считает
-- клиент, `erp/utils/stageQty`.

-- ── 1. Общее правило приращения: потолок снят, нижняя граница осталась ──
create or replace function public.erp_clamp_done(p_current int, p_delta int, p_total int)
returns int language sql immutable set search_path = public as $$
  select greatest(coalesce(p_current, 0) + coalesce(p_delta, 0), 0)
$$;

comment on function public.erp_clamp_done(int, int, int) is
  'Приращение qty_done: обрезка снизу нулём. ПОТОЛКА НЕТ с 12.09 (правка п. 5): факт сверх тиража сохраняется целиком, «плюс» считается как max(qty_done − qty, 0). Параметр p_total оставлен, чтобы не менять сигнатуру у пяти вызывающих, и больше не используется.';

-- ── 2. BEFORE-триггер таблицы ──
--
-- Текст подлинный (`20260811100000_erp_stage_finished_at_invariant`), снята
-- ровно одна строка — `if new.qty_done > v_qty then new.qty_done := v_qty`.
-- Инвариант `finished_at` не тронут: он про другое и работает как работал.
--
-- `v_qty` больше не читается, и выборка позиции снята вместе с ним: запрос,
-- результат которого никто не смотрит, на каждой записи счётчика — это
-- не «безвредный остаток», а лишний поход в таблицу на самой горячей операции
-- цеха. Нижняя граница нуля в позиции не нуждается.
create or replace function public.erp_clamp_stage_qty()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $$
begin
  if new.qty_done < 0 then new.qty_done := 0; end if;
  if new.qty_rework < 0 then new.qty_rework := 0; end if;

  -- Закрыт — значит есть время завершения; вернулся в работу — значит нет.
  -- `skipped` не участвует: это терминальный статус, но не «выполнено».
  if new.status = 'done' and new.finished_at is null then
    new.finished_at := now();
  elsif new.status in ('waiting', 'ready', 'in_progress', 'blocked')
        and new.finished_at is not null then
    new.finished_at := null;
  end if;

  return new;
end $$;

comment on function public.erp_clamp_stage_qty() is
  'Нормализация счётчиков этапа перед записью: не ниже нуля. Потолок по тиражу снят 12.09 (правка п. 5) — факт сверх заказа сохраняется целиком. Здесь же инвариант finished_at.';

-- Пересозданные функции получают EXECUTE от PUBLIC заново — отзыв повторяется.
-- `from public, anon`: право приходит от PUBLIC, и `anon` наследует его.
-- `erp_clamp_done` остаётся доступной `authenticated`: её зовут SECURITY INVOKER-
-- функции и UPDATE самого клиента. `erp_clamp_stage_qty` — триггерная, её
-- не зовут напрямую вовсе.
revoke execute on function public.erp_clamp_done(int, int, int) from public, anon;
grant execute on function public.erp_clamp_done(int, int, int) to authenticated;
revoke execute on function public.erp_clamp_stage_qty() from public, anon, authenticated;
