-- Упаковка изделия разложена на поля, которые документ перечисляет отдельно
-- (правки заказчика 16.08, п. 1).
--
-- ЧТО БЫЛО. Документ называет пять вещей, которые отличаются у изделий внутри
-- одной сделки: «тип пакета, размер пакета, расположение стикера, расположение
-- маркировки, дополнительные требования». Типом заведовало поле `packaging`,
-- а остальные четыре уходили в один свободный комментарий.
--
-- Комментарий — плохое место для того, что читает цех при упаковке: строку
-- «пакет 40×60, стикер на лицевую снизу справа, маркировка на боковой шов»
-- невозможно ни отфильтровать, ни показать в задании отдельной подписью,
-- и половина её теряется при беглом чтении. Отсюда три колонки.
--
-- `packaging_note` ОСТАЁТСЯ и означает теперь ровно то, чем документ его
-- и называет — «дополнительные требования». Переносить старые значения
-- в новые колонки автоматически нельзя: разобрать свободный текст на три поля
-- значит угадывать, а угаданная маркировка хуже отсутствующей.
alter table public.erp_order_items
  add column if not exists packaging_size text,
  add column if not exists sticker_place text,
  add column if not exists marking_place text;

comment on column public.erp_order_items.packaging_size is
  'Размер пакета для этого изделия (п. 1 документа 16.08).';
comment on column public.erp_order_items.sticker_place is
  'Куда клеится стикер. Отдельное поле, а не часть комментария: это читает цех при упаковке.';
comment on column public.erp_order_items.marking_place is
  'Куда наносится маркировка.';
comment on column public.erp_order_items.packaging_note is
  'Дополнительные требования к упаковке — ровно то, чем документ 16.08 его и называет.';
