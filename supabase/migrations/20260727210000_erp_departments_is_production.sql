-- Аудит по скилам, находка 1: цеха стали редактируемыми, а код их не видит.
--
-- Волна 2 дала админке заводить участки, но список производственных цехов остался
-- константой QUEUE_DEPT_CODES в src/erp/data/departments.ts. Она определяет всё:
-- меню сайдбара, колонки канбана, гейт ТЗ, загрузку на дашборде, переключатель
-- очередей, форму создания заказа, подряд. Новый участок, заведённый директором,
-- просто не существовал для приложения.
--
-- Переносим признак в данные: `is_production` — «у цеха есть рабочая очередь,
-- он показывается в канбане и требует ТЗ». Закупка, логистика, склады и
-- экспериментальный цех живут своими экранами и в очередь не входят.

alter table public.erp_departments
  add column if not exists is_production boolean not null default false;

-- Бэкфилл ровно по прежнему QUEUE_DEPT_CODES — поведение не меняется
update public.erp_departments
   set is_production = true
 where code in ('cutting', 'silkscreen', 'dtf', 'embroidery', 'sewing', 'vto');

-- ОТК: заказчик прямо назвал его в примере сообщения об ошибке ТЗ
-- («не назначено ТЗ швейному цеху и ОТК»), а участка не было.
-- Заводим сам цех — он появится в меню, канбане, очередях и назначениях ТЗ.
-- В маршрут по умолчанию (utils/routes.BASE_CHAIN) ОТК НЕ добавляется: это
-- меняет поток каждого нового заказа и требует решения заказчика. Пока попасть
-- на ОТК можно переносом карточки на канбане.
insert into public.erp_departments (code, name, type, sort_order, is_branding, active, is_production)
values ('qc', 'ОТК', 'qc', 85, false, true, true)
on conflict (code) do nothing;
