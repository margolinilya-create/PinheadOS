-- Участок «Подряд» в списке участков (документ 21.08).
--
-- ЧТО ПРОСИТ ДОКУМЕНТ. «Добавить в список участков отдельный участок "Подряд".
-- При выборе этого участка исполнитель определяется автоматически как
-- "Подрядчик", и внутри этапа открываются поля подрядчика, операции, количества,
-- сроков, ответственного, комментария и файлов. Конкретная операция (варка,
-- сублимация) хранится внутри этапа и НЕ создаёт ни отдельного участка,
-- ни отдельной вкладки — задача видна только во вкладке "Подряд"».
-- Пример маршрута: «Закрой — Швейка — Подряд: Варка — ВТО — Склад».
--
-- ПОЧЕМУ ЭТО МОЖНО СЕЙЧАС, ХОТЯ 16.08 БЫЛО НЕЛЬЗЯ. В сессии 32 псевдо-цех
-- «Подряд» был отвергнут двумя доводами, и оба с тех пор сняты:
--
--   1. «Уникальность (item_id, department_id, cycle) разрешит РОВНО ОДИН
--      подрядный этап на позицию, а документ требует нескольких» — индекс
--      стал частичным в той же сессии:
--      `where coalesce(executor,'internal') = 'internal'`. Подрядные этапы
--      под него не подпадают вовсе, и их может быть сколько угодно.
--   2. «Псевдо-цех потечёт во все поверхности, читающие цеха из данных» —
--      все они фильтруют по `is_production`: сайдбар, канбан, вкладки очереди,
--      план, загрузка, гейт ТЗ. Непроизводственный участок в них не попадает,
--      и это ровно то, чего документ и требует.
--
-- ЧТО ЭТОТ УЧАСТОК ЗНАЧИТ. «Подряд» — не наш цех и не подрядчик как компания:
-- это МЕСТО В МАРШРУТЕ, где работу делают снаружи. Имя подрядчика, операция,
-- количества и сроки живут в самом этапе и его спутнике `erp_subcontracting`.
--
-- ЧЕГО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ. Не трогает существующие этапы. Подрядность
-- по-прежнему определяется колонкой `erp_item_stages.executor`, а не кодом
-- участка: этапы, заведённые до этой правки с реальным цехом и
-- `executor='contractor'`, обязаны остаться подрядными. (На боевой базе таких
-- нет вовсе — проверено, ноль строк, — но правило от этого не меняется.)
--
-- ⚠️ СОВПАДЕНИЕ ИМЁН, КОТОРОЕ НЕ ЯВЛЯЕТСЯ СВЯЗЬЮ. Значение 'outsource' есть
-- ещё и у `erp_order_items.production_type` («подряд под ключ» — тип
-- производства ПОЗИЦИИ). Это разные колонки в разных таблицах и разные решения:
-- тип производства говорит, кто делает изделие целиком, участок — где в
-- маршруте один конкретный шаг уходит наружу. Сравнивать одно с другим нельзя.

insert into public.erp_departments (
  code, name, type, sort_order, is_production, is_branding, active,
  gate_material_kinds, result_fields
)
-- `gate_material_kinds` пуст — материальный гейт участку не нужен: изделия
-- уходят наружу, и запирать шаг ожиданием нашей ткани значило бы остановить
-- подряд там, где материал везёт подрядчик. Пусто = не гейтится (fail-open),
-- как у любого участка без настройки.
-- `result_fields` пуст — отчёт о результате подряд сдаёт не формой участка,
-- а журналом перемещений `erp_subcontract_moves`: он и приращает `qty_done`.
select 'outsource', 'Подряд', 'outsource', 95, false, false, true,
       '{}'::text[], '[]'::jsonb
where not exists (select 1 from public.erp_departments where code = 'outsource');

-- Явно, а не «как заведётся»: непроизводственный участок не попадает в очередь,
-- на канбан, в план и в загрузку — задача подряда видна только во вкладке
-- «Подряд», как и просит документ
update public.erp_departments
   set is_production = false, is_branding = false, active = true
 where code = 'outsource';

comment on table public.erp_departments is
  'Участки. is_production = true — свой цех с очередью и канбаном; false — участок со своим экраном (закупка, склады, «Подряд»). Участок «Подряд» означает шаг маршрута, выполняемый снаружи: подрядчик, операция и сроки лежат в самом этапе и в erp_subcontracting.';
