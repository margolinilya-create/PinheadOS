-- ОТК перестаёт быть отдельным цехом (правки заказчика 10.08, волна 1).
--
-- Документ: «Отдельный раздел/цех ОТК убрать из интерфейса и производственного
-- маршрута как самостоятельную сущность. Логика контроля качества при необходимости
-- должна быть встроена в реальные производственные этапы».
--
-- Маршрут новых заказов финальный ОТК больше не получает — это сделано в коде
-- (`buildRoute`), вместе с галочкой «Финальный ОТК» в форме создания.
--
-- Здесь — вторая половина: сам участок. Не удаляем, а ДЕАКТИВИРУЕМ:
--   · меню, очередь, канбан и гейт ТЗ читают участки из данных (`active`,
--     `is_production`), поэтому неактивный цех исчезает отовсюду сам;
--   · удаление строки оборвало бы внешние ключи у любых будущих ссылок и лишило бы
--     нас возможности вернуть участок одной галочкой, если решение изменится.
--
-- Проверено перед правкой: этапов у цеха `qc` в базе НЕТ НИ ОДНОГО — ни открытых,
-- ни закрытых. Поэтому ничего не переносим и не закрываем: живых маршрутов правка
-- не касается. Если бы этапы были, деактивация их не тронула бы (участок читается
-- по id, а не по флагу), но заказы встали бы на невидимом этапе — и тогда
-- потребовался бы отдельный перенос.

update public.erp_departments
   set active = false, updated_at = now()
 where code = 'qc';
