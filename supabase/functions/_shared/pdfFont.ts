/**
 * Шрифт с кириллицей для PDF, общий на все серверные функции.
 *
 * ЭТО САМАЯ ДОРОГАЯ ЧАСТЬ ЛЮБОГО НАШЕГО PDF, и она уже выстрадана листом
 * закупки. Четырнадцать стандартных шрифтов PDF кодируют текст в WinAnsi
 * и кириллицы не знают ВООБЩЕ: `drawText` с русской строкой либо бросает,
 * либо рисует мусор. Поэтому шрифт встраивается в документ (DejaVu Sans,
 * свободная лицензия), а `fontkit` подключается явно — без него `embedFont`
 * не принимает TTF.
 *
 * Проверять это надо в ГОТОВОМ ФАЙЛЕ: «функция ответила 200» ничего не значит,
 * документ выходит мусорным молча.
 *
 * Кэш живёт в памяти инстанса: холодный старт тянет шрифт один раз,
 * последующие вызовы берут готовый. Падение загрузки — отказ всей операции,
 * а не «сделаем без кириллицы»: PDF с мусором вместо названий материалов
 * хуже отсутствующего.
 *
 * Копия этой логики во второй функции означала бы, что однажды одна из них
 * останется со старым URL шрифта — и сломается ровно тем способом, который
 * не виден по коду.
 */

const FONT_URL = 'https://cdn.jsdelivr.net/npm/dejavu-fonts-ttf@2.37.3/ttf/DejaVuSans.ttf';

let fontCache: Uint8Array | null = null;

export async function loadPdfFont(): Promise<Uint8Array> {
  if (fontCache) return fontCache;
  const res = await fetch(FONT_URL);
  if (!res.ok) throw new Error(`шрифт не загрузился: ${res.status}`);
  fontCache = new Uint8Array(await res.arrayBuffer());
  return fontCache;
}
